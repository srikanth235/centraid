//! THE MODEL'S KINDS: the words the assistant says things on, and how each reads from the vault.
//!
//! [`crate::KINDS`] says what a kind owes a member; this says what the model may call it, which
//! of its fields a question can name, and what it is linked to. A chat kind is usually a vault
//! entity kind (a `note`, a `transaction`), and sometimes a table that is none (a `daily figure`,
//! a `budget`, a `rule`). Each [`ActionDecl`](crate::ActionDecl)'s `Say` names its kinds here.

/// `contracts/assist/verbs.json`: the verbs the model says, each with its argument line and its past tense.
pub const VERBS_JSON: &str = include_str!("../../../contracts/assist/verbs.json");

/// A table and a column: where a value is read from.
pub type Source = (&'static str, &'static str);

/// One model-facing field of a kind.
#[derive(Debug, Clone, Copy)]
pub struct ChatField {
    pub name: &'static str,
    /// `text`, `number`, `money`, `enum`, `bool` or `date`.
    pub kind: &'static str,
    pub source: Source,
    pub unit: Option<&'static str>,
    /// `(the model's word, the vault's value)` for an enum.
    pub values: &'static [(&'static str, &'static str)],
}

/// A link from one kind to another, and the vault relation it travels.
#[derive(Debug, Clone, Copy)]
pub struct ChatLink {
    pub kind: &'static str,
    pub label: &'static str,
    /// `attendee`, `about`, `subtask`, `list_column`, `entry`, `folder_column`, `with` or `depicts`.
    pub via: &'static str,
}

/// A kind the assistant can name: a person, a task, a note.
#[derive(Debug, Clone, Copy)]
pub struct ChatKind {
    pub app: &'static str,
    pub id: &'static str,
    pub name: &'static str,
    pub plural: &'static str,
    /// The vault kind whose entities its rows are, or the table that holds them.
    pub entity: &'static str,
    pub table: &'static str,
    pub pk: &'static str,
    pub name_source: Source,
    pub date: Option<(&'static str, Source)>,
    pub fields: &'static [ChatField],
    pub links: &'static [ChatLink],
    pub trash: bool,
    pub container: bool,
    pub writable: bool,
    /// The full-text domain whose hits are this kind's rows, when the kind is searchable.
    pub search: Option<&'static str>,
}

