#[cfg(test)]
mod tests {
    use super::*;

    fn identity() -> ed25519_dalek::SigningKey {
        ed25519_dalek::SigningKey::from_bytes(&[0x42; 32])
    }

    fn vault() -> VaultId {
        vault_of(&identity())
    }

    fn gateway() -> GatewayId {
        GatewayId::from_bytes([0x11; 16])
    }

    fn nonce() -> Nonce {
        Nonce::from_bytes([0x77; 16])
    }

    fn head() -> HeadFields {
        HeadFields {
            epoch: 2,
            generation: 5,
            writes: 9,
            taken_at_ms: 1_700_000_000_000,
            manifest: Name::from_bytes([0x33; 32]),
            prev: Some(Name::from_bytes([0x34; 32])),
        }
    }

    /// THE CLAIM PREIMAGE IS A FORMAT, PINNED BYTE FOR BYTE.
    #[test]
    fn the_claim_preimage_is_the_documented_layout() {
        let v = VaultId::from_bytes([0x22; 32]);
        let head = Name::from_bytes([0x33; 32]);
        let with_head = claim_preimage(&gateway(), &v, 2, Some(&head), &nonce());
        let mut expected = Vec::new();
        expected.extend_from_slice(&25_u32.to_be_bytes());
        expected.extend_from_slice(b"centraid-gateway-claim-v3");
        expected.extend_from_slice(&16_u32.to_be_bytes());
        expected.extend_from_slice(&[0x11; 16]);
        expected.extend_from_slice(&32_u32.to_be_bytes());
        expected.extend_from_slice(&[0x22; 32]);
        expected.extend_from_slice(&8_u32.to_be_bytes());
        expected.extend_from_slice(&2_u64.to_be_bytes());
        expected.extend_from_slice(&32_u32.to_be_bytes());
        expected.extend_from_slice(&[0x33; 32]);
        expected.extend_from_slice(&16_u32.to_be_bytes());
        expected.extend_from_slice(&[0x77; 16]);
        assert_eq!(with_head, expected);
        let without = claim_preimage(&gateway(), &v, 2, None, &nonce());
        assert_eq!(without.len(), expected.len() - 32);
    }

    /// THE HEAD PREIMAGE IS E2's LAYOUT, FIELD FOR FIELD.
    #[test]
    fn the_head_preimage_is_the_documented_layout() {
        let v = VaultId::from_bytes([0x22; 32]);
        let mut expected = Vec::new();
        expected.extend_from_slice(&24_u32.to_be_bytes());
        expected.extend_from_slice(b"centraid-gateway-head-v3");
        expected.extend_from_slice(&16_u32.to_be_bytes());
        expected.extend_from_slice(&[0x11; 16]);
        expected.extend_from_slice(&32_u32.to_be_bytes());
        expected.extend_from_slice(&[0x22; 32]);
        for value in [2_u64, 5, 9, 1_700_000_000_000] {
            expected.extend_from_slice(&8_u32.to_be_bytes());
            expected.extend_from_slice(&value.to_be_bytes());
        }
        expected.extend_from_slice(&32_u32.to_be_bytes());
        expected.extend_from_slice(&[0x33; 32]);
        expected.extend_from_slice(&32_u32.to_be_bytes());
        expected.extend_from_slice(&[0x34; 32]);
        assert_eq!(head_preimage(&gateway(), &v, &head()), expected);
        let none = HeadFields {
            prev: None,
            ..head()
        };
        let bare = head_preimage(&gateway(), &v, &none);
        assert_eq!(&bare[bare.len() - 4..], &0_u32.to_be_bytes());
    }

    /// The names digest ignores order and repeats.
    #[test]
    fn the_names_digest_is_of_the_sorted_distinct_names() {
        let (a, b) = (Name::from_bytes([1; 32]), Name::from_bytes([2; 32]));
        assert_eq!(names_digest(&[b, a, b]), names_digest(&[a, b]));
        assert_ne!(names_digest(&[a]), names_digest(&[a, b]));
    }

    /// EVERY KIND OF RECORD HAS ITS OWN CONTEXT: a signature over one never
    /// verifies as another, even when every other field lines up.
    #[test]
    fn a_signature_is_good_for_its_own_kind_only() {
        let names = [Name::from_bytes([5; 32])];
        let delete = sign_delete(&identity(), &gateway(), 2, 6, &names);
        assert!(verify_delete(&gateway(), &vault(), 2, 6, &names, &delete));
        assert!(!verify_undo(
            &gateway(),
            &vault(),
            2,
            6,
            Some(&names),
            &delete
        ));
        let undo = sign_undo(&identity(), &gateway(), 2, 6, Some(&names));
        assert!(verify_undo(&gateway(), &vault(), 2, 6, Some(&names), &undo));
        assert!(!verify_undo(&gateway(), &vault(), 2, 6, None, &undo));
        assert!(!verify_delete(&gateway(), &vault(), 2, 6, &names, &undo));
    }

    /// A HEAD IS BOUND TO EVERY FIELD IT SIGNS.
    #[test]
    fn a_head_signature_verifies_only_the_head_it_signed() {
        let signed = sign_head(&identity(), &gateway(), &head());
        assert!(verify_head(&gateway(), &vault(), &head(), &signed));
        let variants = [
            HeadFields { epoch: 3, ..head() },
            HeadFields {
                generation: 6,
                ..head()
            },
            HeadFields {
                writes: 10,
                ..head()
            },
            HeadFields {
                taken_at_ms: 1,
                ..head()
            },
            HeadFields {
                manifest: Name::from_bytes([9; 32]),
                ..head()
            },
            HeadFields {
                prev: None,
                ..head()
            },
        ];
        for variant in variants {
            assert!(!verify_head(&gateway(), &vault(), &variant, &signed));
        }
        assert!(!verify_head(
            &GatewayId::from_bytes([0x12; 16]),
            &vault(),
            &head(),
            &signed
        ));
        let stranger = vault_of(&ed25519_dalek::SigningKey::from_bytes(&[0x43; 32]));
        assert!(!verify_head(&gateway(), &stranger, &head(), &signed));
    }

    /// A CLAIM IS BOUND TO ITS NONCE, EPOCH, HEAD AND GATEWAY; A READ GRANT
    /// IS A CLAIM AT EPOCH 0 AND NOTHING ELSE.
    #[test]
    fn a_claim_verifies_only_the_claim_it_signed() {
        let head = Name::from_bytes([5; 32]);
        let signature = sign_claim(&identity(), &gateway(), 3, Some(&head), &nonce());
        assert!(verify_claim(
            &gateway(),
            &vault(),
            3,
            Some(&head),
            &nonce(),
            &signature
        ));
        assert!(!verify_claim(
            &gateway(),
            &vault(),
            4,
            Some(&head),
            &nonce(),
            &signature
        ));
        assert!(!verify_claim(
            &gateway(),
            &vault(),
            3,
            None,
            &nonce(),
            &signature
        ));
        assert!(!verify_claim(
            &gateway(),
            &vault(),
            3,
            Some(&head),
            &Nonce::from_bytes([1; 16]),
            &signature
        ));
        let read = sign_read(&identity(), &gateway(), &nonce());
        assert!(verify_claim(
            &gateway(),
            &vault(),
            READ_EPOCH,
            None,
            &nonce(),
            &read
        ));
        assert!(!verify_claim(
            &gateway(),
            &vault(),
            1,
            None,
            &nonce(),
            &read
        ));
    }

    /// A PAIRING IS BOUND TO ITS SECRET, NONCE AND GATEWAY.
    #[test]
    fn a_pairing_signature_binds_its_secret_nonce_and_gateway() {
        let secret = Secret::from_bytes([8; 16]);
        let signature = sign_pair(&identity(), &gateway(), &secret, &nonce());
        assert!(verify_pair(
            &gateway(),
            &vault(),
            &secret,
            &nonce(),
            &signature
        ));
        assert!(!verify_pair(
            &gateway(),
            &vault(),
            &Secret::from_bytes([9; 16]),
            &nonce(),
            &signature
        ));
        assert!(!verify_pair(
            &GatewayId::from_bytes([0x12; 16]),
            &vault(),
            &secret,
            &nonce(),
            &signature
        ));
        assert!(!verify_pair(
            &gateway(),
            &vault(),
            &secret,
            &Nonce::from_bytes([2; 16]),
            &signature
        ));
    }
}
