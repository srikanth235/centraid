//! THE SIGNING VECTORS: every record the vault key signs, pinned (#1191, E1).
//!
//! `contracts/crypto/gateway-signing-vectors.json` holds, for fixed keys and
//! fields, the exact preimage and Ed25519 signature of a claim, a read grant,
//! a head, a delete, an undo and a pairing. The phone's test reads the same
//! file, so a revision of either end that builds a byte differently fails
//! here, in this crate's gate, before it can fail a restore.
//!
//! `CENTRAID_UPDATE_FIXTURES=1 cargo test -p centraid-gateway --test
//! signing_vectors` regenerates the file, and the comparison still runs
//! afterwards: the variable is a generator and never a way to go green.
//! Freely regenerated until the first release.

use centraid_gateway::rules::ids::{GatewayId, Name, Nonce, Secret, VaultId};
use centraid_gateway::rules::signing::{
    HeadFields, claim_preimage, delete_preimage, head_preimage, pair_preimage, sign_claim,
    sign_delete, sign_head, sign_pair, sign_read, sign_undo, undo_preimage,
};
use serde_json::{Value, json};

const FILE: &str = "../../contracts/crypto/gateway-signing-vectors.json";

fn vectors() -> Value {
    let key = ed25519_dalek::SigningKey::from_bytes(&[0x42; 32]);
    let vault = VaultId::from_bytes(key.verifying_key().to_bytes());
    let gateway = GatewayId::from_bytes([0x11; 16]);
    let nonce = Nonce::from_bytes([0x77; 40]);
    let secret = Secret::from_bytes([0x88; 16]);
    let manifest = Name::from_bytes([0x33; 32]);
    let prev = Name::from_bytes([0x34; 32]);
    let names = [Name::from_bytes([0x02; 32]), Name::from_bytes([0x01; 32])];
    let head = HeadFields {
        epoch: 2,
        generation: 5,
        writes: 9,
        taken_at_ms: 1_700_000_000_000,
        manifest,
        prev: Some(prev),
    };
    let first_head = HeadFields {
        epoch: 1,
        generation: 1,
        writes: 1,
        taken_at_ms: 1_700_000_000_000,
        manifest,
        prev: None,
    };
    let entry = |name: &str, fields: Value, preimage: Vec<u8>, signature: String| {
        json!({
            "name": name,
            "fields": fields,
            "preimage": hex::encode(preimage),
            "signature": signature,
        })
    };
    json!({
        "about": "centraid-gateway signing, protocol 3 (#1191, E1). Ed25519 over u32be-length-prefixed fields; generated by crates/gateway/tests/signing_vectors.rs.",
        "vault_seed": hex::encode([0x42_u8; 32]),
        "vault_id": vault.hex(),
        "gateway_id": gateway.hex(),
        "nonce": nonce.hex(),
        "vectors": [
            entry(
                "claim",
                json!({"epoch": 7, "head_seen": manifest.hex()}),
                claim_preimage(&gateway, &vault, 7, Some(&manifest), &nonce),
                sign_claim(&key, &gateway, 7, Some(&manifest), &nonce).hex(),
            ),
            entry(
                "claim without a head",
                json!({"epoch": 2, "head_seen": null}),
                claim_preimage(&gateway, &vault, 2, None, &nonce),
                sign_claim(&key, &gateway, 2, None, &nonce).hex(),
            ),
            entry(
                "read grant",
                json!({"epoch": 0, "head_seen": null}),
                claim_preimage(&gateway, &vault, 0, None, &nonce),
                sign_read(&key, &gateway, &nonce).hex(),
            ),
            entry(
                "head",
                json!({"epoch": 2, "generation": 5, "writes": 9, "taken_at_ms": 1_700_000_000_000_i64,
                       "manifest": manifest.hex(), "prev": prev.hex()}),
                head_preimage(&gateway, &vault, &head),
                sign_head(&key, &gateway, &head).hex(),
            ),
            entry(
                "first head",
                json!({"epoch": 1, "generation": 1, "writes": 1, "taken_at_ms": 1_700_000_000_000_i64,
                       "manifest": manifest.hex(), "prev": null}),
                head_preimage(&gateway, &vault, &first_head),
                sign_head(&key, &gateway, &first_head).hex(),
            ),
            entry(
                "delete",
                json!({"epoch": 2, "generation": 6, "names": names.iter().map(Name::hex).collect::<Vec<_>>()}),
                delete_preimage(&gateway, &vault, 2, 6, &names),
                sign_delete(&key, &gateway, 2, 6, &names).hex(),
            ),
            entry(
                "undo of names",
                json!({"epoch": 2, "generation": 7, "names": names.iter().map(Name::hex).collect::<Vec<_>>()}),
                undo_preimage(&gateway, &vault, 2, 7, Some(&names)),
                sign_undo(&key, &gateway, 2, 7, Some(&names)).hex(),
            ),
            entry(
                "undo of everything",
                json!({"epoch": 2, "generation": 8, "names": null}),
                undo_preimage(&gateway, &vault, 2, 8, None),
                sign_undo(&key, &gateway, 2, 8, None).hex(),
            ),
            entry(
                "pairing by secret",
                json!({"secret": hex::encode(secret.as_bytes())}),
                pair_preimage(&gateway, &vault, &secret, &nonce),
                sign_pair(&key, &gateway, &secret, &nonce).hex(),
            ),
        ],
    })
}

#[test]
fn the_signing_vectors_are_the_ones_in_the_contract() {
    let made = vectors();
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join(FILE);
    if std::env::var_os("CENTRAID_UPDATE_FIXTURES").is_some() {
        let text = serde_json::to_string_pretty(&made).expect("renders") + "\n";
        std::fs::write(&path, text).expect("writes the vectors");
    }
    let held: Value = serde_json::from_str(
        &std::fs::read_to_string(&path).expect("contracts/crypto/gateway-signing-vectors.json"),
    )
    .expect("parses");
    assert_eq!(
        held, made,
        "a signing preimage or signature moved; that is a format change — \
         regenerate with CENTRAID_UPDATE_FIXTURES=1 only when it is meant"
    );
}
