//! THE CHAT CATALOG, generated from the domain declarations.
//!
//! `centraid-domain` declares the model-facing kinds (`KINDS`) and the actions chat
//! runs on its own (`ACTIONS`); `contracts/assist/verbs.json` is the verb
//! vocabulary (its argument line, its past tense). This writes
//! `$OUT_DIR/catalog.rs` (included by `native/meta.rs`):
//!
//! * `Kind` and `Kind::ALL`: the declared kinds, in order. An empty catalogue leaves one
//!   variant, `Undeclared`, that nothing makes, so `Kind` is still inhabited.
//! * `Verb`: the verb vocabulary of `contracts/assist/verbs.json`; a verb is live (a `VERBS`
//!   row) when a direct action of a writable kind serves it, or the runtime owns it
//!   (`builtin`: `undo`).
//! * `ACTIONS`: one lookup, `(verb, kind, qualifier)`, to the action chat runs.
//! * `KINDS` and `VERBS`: the rows of the live kinds and verbs.
//!
//! A catalogue that contradicts itself fails the build with the sentence that names
//! the declaration.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use centraid_domain::{ActionDecl, FieldDecl, KindDecl, Source};
use serde_json::Value;

fn camel(snake: &str) -> String {
    snake
        .split('_')
        .map(|word| {
            let mut chars = word.chars();
            chars
                .next()
                .map(|first| first.to_uppercase().collect::<String>() + chars.as_str())
                .unwrap_or_default()
        })
        .collect()
}

fn text<'a>(value: &'a Value, key: &str) -> &'a str {
    value[key]
        .as_str()
        .unwrap_or_else(|| panic!("catalog: `{key}` is not a string in {value}"))
}

fn at((table, column): Source) -> String {
    format!("at({table:?}, {column:?})")
}

fn field_type(name: &str) -> &'static str {
    match name {
        "text" => "FieldType::Text",
        "number" => "FieldType::Number",
        "money" => "FieldType::Money",
        "enum" => "FieldType::Enum",
        "bool" => "FieldType::Bool",
        "date" => "FieldType::Date",
        other => panic!("catalog: unknown field type {other}"),
    }
}

fn via(name: &str) -> &'static str {
    match name {
        "attendee" => "Via::Attendee",
        "about" => "Via::About",
        "subtask" => "Via::Subtask",
        "list_column" => "Via::ListColumn",
        "entry" => "Via::Entry",
        "folder_column" => "Via::FolderColumn",
        "with" => "Via::With",
        "depicts" => "Via::Depicts",
        other => panic!("catalog: unknown link via {other}"),
    }
}

fn field_expr(field: &FieldDecl) -> String {
    let mut out = format!(
        "field({:?}, {}, {})",
        field.name,
        field_type(field.kind),
        at(field.source)
    );
    if let Some(unit) = field.unit {
        let _ = write!(out, ".unit({unit:?})");
    }
    if !field.values.is_empty() {
        out.push_str(".values(&[");
        for (model, vault) in field.values {
            let _ = write!(out, "({model:?}, {vault:?}), ");
        }
        out.push_str("])");
    }
    out
}

fn list(names: &[&str]) -> String {
    format!(
        "&[{}]",
        names
            .iter()
            .map(|name| format!("{name:?}"))
            .collect::<Vec<_>>()
            .join(", ")
    )
}

fn main() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let verbs_path = root.join("contracts/assist/verbs.json");
    println!("cargo:rerun-if-changed={}", verbs_path.display());
    println!(
        "cargo:rerun-if-changed={}",
        root.join("crates/domain/src/lib.rs").display()
    );
    let verbs: Value =
        serde_json::from_str(&std::fs::read_to_string(&verbs_path).expect("verbs.json"))
            .expect("verbs.json is JSON");

    let live: Vec<&KindDecl> = centraid_domain::KINDS.iter().collect();
    let live_ids: Vec<&str> = live.iter().map(|kind| kind.id).collect();
    let writable: Vec<&str> = live
        .iter()
        .filter(|kind| kind.writable)
        .map(|kind| kind.id)
        .collect();

    let mut out = String::new();
    out.push_str("// @generated by crates/assist/build.rs from crates/domain; do not edit.\n\n");
    out.push_str(
        "/// The model-facing kinds the runtime reads: generated from the domain's `KINDS`.\n",
    );
    out.push_str(
        "#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize)]\n",
    );
    out.push_str("#[serde(rename_all = \"snake_case\")]\npub enum Kind {\n");
    if live_ids.is_empty() {
        out.push_str("    /// Never made: an empty catalogue still leaves `Kind` inhabited, so the code over it stays reachable.\n    Undeclared,\n");
    }
    for id in &live_ids {
        let _ = writeln!(out, "    {},", camel(id));
    }
    out.push_str("}\n\nimpl Kind {\n");
    let _ = writeln!(out, "    pub const ALL: [Self; {}] = [", live_ids.len());
    for id in &live_ids {
        let _ = writeln!(out, "        Self::{},", camel(id));
    }
    out.push_str("    ];\n}\n\n");

    out.push_str("pub static KINDS: &[KindSpec] = &[\n");
    for kind in &live {
        let _ = writeln!(out, "    KindSpec {{");
        let _ = writeln!(out, "        app: {:?},", kind.app);
        let _ = writeln!(
            out,
            "        search: {},",
            kind.search
                .map_or("None".to_owned(), |domain| format!("Some({domain:?})"))
        );
        let _ = writeln!(out, "        kind: Kind::{},", camel(kind.id));
        let _ = writeln!(out, "        name: {:?},", kind.name);
        let _ = writeln!(out, "        plural: {:?},", kind.plural);
        let _ = writeln!(out, "        entity: {:?},", kind.entity);
        let _ = writeln!(out, "        table: {:?},", kind.table);
        let _ = writeln!(out, "        pk: {:?},", kind.pk);
        let _ = writeln!(out, "        name_source: {},", at(kind.name_source));
        match kind.date {
            Some((label, source)) => {
                let _ = writeln!(
                    out,
                    "        date: Some(DateSpec {{ label: {label:?}, source: {} }}),",
                    at(source)
                );
            }
            None => out.push_str("        date: None,\n"),
        }
        out.push_str("        fields: &[\n");
        for field in kind.fields {
            let _ = writeln!(out, "            {},", field_expr(field));
        }
        out.push_str("        ],\n        links: &[\n");
        for link in kind.links {
            assert!(
                live_ids.contains(&link.kind),
                "catalog: {} links to {}, which is not a live kind",
                kind.id,
                link.kind
            );
            let _ = writeln!(
                out,
                "            Link {{ kind: Kind::{}, label: {:?}, via: {} }},",
                camel(link.kind),
                link.label,
                via(link.via)
            );
        }
        let _ = writeln!(
            out,
            "        ],\n        trash: {},\n        container: {},\n    }},",
            kind.trash, kind.container
        );
    }
    out.push_str("];\n\n");

    out.push_str("pub static DECLARED_KINDS: &[DeclaredKind] = &[];\n\n");

    let vocabulary = verbs["verbs"].as_array().expect("verbs");
    let rows: Vec<&ActionDecl> = centraid_domain::ACTIONS.iter().collect();
    let backs = |name: &str| {
        rows.iter().any(|row| {
            (row.verb == name || row.also.contains(&name)) && writable.contains(&row.kind)
        })
    };
    let live_verbs: Vec<&Value> = vocabulary
        .iter()
        .filter(|verb| verb["builtin"].as_bool().unwrap_or(false) || backs(text(verb, "name")))
        .collect();
    let live_verb_names: Vec<&str> = live_verbs.iter().map(|verb| text(verb, "name")).collect();

    out.push_str("/// Every verb of `contracts/assist/verbs.json`; `VERBS` lists the ones some action backs.\n");
    out.push_str(
        "#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize)]\n",
    );
    out.push_str("#[serde(rename_all = \"snake_case\")]\npub enum Verb {\n");
    for verb in vocabulary {
        let _ = writeln!(out, "    {},", camel(text(verb, "name")));
    }
    out.push_str("}\n\n");

    let kind_order = |id: &str| {
        live_ids
            .iter()
            .position(|known| *known == id)
            .unwrap_or(usize::MAX)
    };
    let mut commands: BTreeMap<&str, Vec<(usize, &str, &str)>> = BTreeMap::new();
    let mut seen: Vec<(&str, &str, Option<&str>)> = Vec::new();
    let mut runnable: Vec<(&ActionDecl, &str)> = Vec::new();
    for row in &rows {
        assert!(
            writable.contains(&row.kind),
            "catalog: action {} serves {}, which is not a writable kind",
            row.name,
            row.kind
        );
        for verb in std::iter::once(&row.verb).chain(row.also) {
            assert!(
                live_verb_names.contains(verb),
                "catalog: action {} serves `{verb}`, which verbs.json does not declare",
                row.name
            );
            let key = (*verb, row.kind, row.qualifier);
            assert!(
                !seen.contains(&key),
                "catalog: `{verb} {}` is backed twice (second: {}/{})",
                row.kind,
                row.app,
                row.name
            );
            seen.push(key);
            runnable.push((row, verb));
            if row.qualifier.is_none() {
                commands.entry(verb).or_default().push((
                    kind_order(row.kind),
                    row.kind,
                    row.command,
                ));
            }
        }
    }

    out.push_str("/// THE ONE LOOKUP: `(verb, kind, qualifier)` to the action chat runs.\n");
    out.push_str("pub static ACTIONS: &[ActionSpec] = &[\n");
    for (action, verb) in &runnable {
        let inverse = action
            .inverse
            .and_then(|name| rows.iter().find(|back| back.name == name))
            .map_or("None".to_owned(), |back| {
                format!(
                    "Some(InverseSpec {{ app: {:?}, action: {:?}, command: {:?}, id_param: {:?} }})",
                    back.app, back.name, back.command, back.id_param
                )
            });
        let aliases: Vec<String> = action
            .aliases
            .iter()
            .map(|(property, names)| format!("({property:?}, {})", list(names)))
            .collect();
        let pairs = |items: &[(&str, &str)]| {
            items
                .iter()
                .map(|(property, value)| format!("({property:?}, {value:?})"))
                .collect::<Vec<_>>()
                .join(", ")
        };
        let _ = writeln!(
            out,
            "    ActionSpec {{ app: {:?}, action: {:?}, command: {:?}, verb: Verb::{}, qualifier: {}, kind: Kind::{}, id_param: {:?}, inverse: {inverse}, properties: {}, required: {}, aliases: &[{}], consts: &[{}], defaults: &[{}], minted: {} }},",
            action.app,
            action.name,
            action.command,
            camel(verb),
            action
                .qualifier
                .map_or("None".to_owned(), |q| format!("Some({q:?})")),
            camel(action.kind),
            action.id_param,
            list(action.properties),
            list(action.required),
            aliases.join(", "),
            pairs(action.consts),
            pairs(action.defaults),
            list(action.minted),
        );
    }
    out.push_str("];\n\n");

    out.push_str("pub static VERBS: &[VerbSpec] = &[\n");
    for verb in &live_verbs {
        let name = text(verb, "name");
        let mut rows = commands.remove(name).unwrap_or_default();
        let pinned: Vec<&str> = verb["kindOrder"]
            .as_array()
            .map(Vec::as_slice)
            .unwrap_or_default()
            .iter()
            .filter_map(Value::as_str)
            .collect();
        rows.sort_by_key(|(order, kind, _)| {
            (
                pinned
                    .iter()
                    .position(|pin| pin == kind)
                    .unwrap_or(usize::MAX),
                *order,
            )
        });
        let _ = writeln!(out, "    VerbSpec {{");
        let _ = writeln!(out, "        verb: Verb::{},", camel(name));
        let _ = writeln!(out, "        name: {name:?},");
        let _ = writeln!(out, "        args: {:?},", text(verb, "args"));
        let _ = writeln!(out, "        done: {:?},", text(verb, "done"));
        let _ = writeln!(
            out,
            "        flag: {},",
            verb["flag"]
                .as_str()
                .map_or("None".to_owned(), |flag| format!("Some({flag:?})"))
        );
        out.push_str("        commands: &[\n");
        for (_, kind, command) in rows {
            let _ = writeln!(out, "            (Kind::{}, {command:?}),", camel(kind));
        }
        out.push_str("        ],\n    },\n");
    }
    out.push_str("];\n\n");

    out.push_str("pub static DECLARED_VERBS: &[DeclaredVerb] = &[];\n");

    let target = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR")).join("catalog.rs");
    std::fs::write(target, out).expect("write catalog.rs");
}
