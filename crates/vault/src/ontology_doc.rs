/// The FTS5 shadow tables of `search`: an implementation of it, not a table.
fn is_shadow(name: &str) -> bool {
    [
        "search_config",
        "search_data",
        "search_docsize",
        "search_idx",
    ]
    .contains(&name)
}

fn esc(text: &str) -> String {
    text.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
}

/// One column of a table, as SQLite reports it.
struct Column {
    name: String,
    sql_type: String,
    not_null: bool,
    default: Option<String>,
    primary: bool,
    generated: bool,
    references: Option<String>,
}

fn columns_of(connection: &rusqlite::Connection, table: &str) -> Result<Vec<Column>> {
    let mut references: std::collections::BTreeMap<String, String> = Default::default();
    let mut keys = connection.prepare(&format!("PRAGMA foreign_key_list(\"{table}\")"))?;
    for row in keys.query_map([], |row| {
        Ok((
            row.get::<_, String>(2)?,
            row.get::<_, String>(3)?,
            row.get::<_, Option<String>>(4)?,
        ))
    })? {
        let (target, from, to) = row?;
        references
            .entry(from)
            .or_insert_with(|| format!("{target}.{}", to.as_deref().unwrap_or("rowid")));
    }
    let mut info = connection.prepare(&format!("PRAGMA table_xinfo(\"{table}\")"))?;
    let rows = info.query_map([], |row| {
        let name: String = row.get(1)?;
        Ok(Column {
            references: references.get(&name).cloned(),
            name,
            sql_type: row.get(2)?,
            not_null: row.get::<_, i64>(3)? != 0,
            default: row.get(4)?,
            primary: row.get::<_, i64>(5)? != 0,
            generated: matches!(row.get::<_, i64>(6)?, 2 | 3),
        })
    })?;
    Ok(rows.collect::<std::result::Result<_, _>>()?)
}

fn render_columns(columns: &[Column]) -> String {
    let mut out = String::from(
        "<div class=\"colscroll\"><div class=\"colhead\"><span>column</span><span>type</span><span>constraints</span><span>references</span><span class=\"cnote\">note</span></div>\n",
    );
    for column in columns {
        let mut badges = String::new();
        let mut badge = |class: &str, label: &str| {
            badges.push_str(&format!("<span class=\"badge b-{class}\">{label}</span>"));
        };
        if column.primary {
            badge("PK", "PK");
        }
        if column.references.is_some() {
            badge("FK", "FK");
        }
        if column.not_null && !column.primary {
            badge("NN", "NN");
        }
        if column.generated {
            badge("CK", "GEN");
        }
        let note = match (&column.default, column.generated) {
            (_, true) => "generated".to_owned(),
            (Some(default), _) => format!("default {default}"),
            _ => String::new(),
        };
        out.push_str(&format!(
            "<div class=\"colrow\"><span class=\"cn\">{}</span><span class=\"ct\">{}</span><span>{badges}</span><span class=\"cref\">{}</span><span class=\"cnote\">{}</span></div>\n",
            esc(&column.name),
            esc(&column.sql_type.to_lowercase()),
            column
                .references
                .as_deref()
                .map(|target| format!("→ {}", esc(target)))
                .unwrap_or_default(),
            esc(&note),
        ));
    }
    out.push_str("</div>");
    out
}

/// The generated block, markers included, for a vault founded by this build.
pub fn render_schema_section() -> Result<String> {
    let dir = centraid_ontology::scratch::scratch_dir();
    std::fs::create_dir_all(&dir)?;
    let rendered = (|| -> Result<String> {
        let vault = crate::Vault::create(dir.join("vault.db"))?;
        vault.read(|connection| {
            let mut names = connection.prepare(
                "SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY name",
            )?;
            let live: Vec<String> = names
                .query_map([], |row| row.get(0))?
                .collect::<std::result::Result<_, _>>()?;
            let live: Vec<&String> = live.iter().filter(|name| !is_shadow(name)).collect();
            for name in &live {
                if !TABLES.iter().any(|(_, table, _)| table == name) {
                    return Err(VaultError::Invariant {
                        context: format!(
                            "`{name}` is a table of the founded file with no entry in ontology_doc::TABLES: say what it is for, in a group, in the same change"
                        ),
                    });
                }
            }
            for (_, table, _) in TABLES {
                if !live.iter().any(|name| name.as_str() == table) {
                    return Err(VaultError::Invariant {
                        context: format!(
                            "ontology_doc::TABLES names `{table}`, which the founded file does not hold"
                        ),
                    });
                }
            }
            let mut out = String::new();
            out.push_str(BEGIN);
            out.push('\n');
            let (mut tables, mut cells) = (0, 0);
            for (group, label, about) in GROUPS {
                out.push_str(&format!(
                    "<div class=\"schemahdr\" data-group=\"{group}\"><span class=\"sid\">{group}</span><h3>{}</h3><p class=\"sdesc\">{}</p></div>\n",
                    esc(label),
                    esc(about)
                ));
                for (_, table, purpose) in TABLES.iter().filter(|(g, _, _)| *g == group) {
                    let columns = columns_of(connection, table)?;
                    tables += 1;
                    cells += columns.len();
                    out.push_str(&format!(
                        "<div class=\"tbl rv in\" data-group=\"{group}\" data-table=\"{table}\"><header><h4>{table}</h4><p class=\"tp\">{}</p></header>\n{}</div>\n",
                        esc(purpose),
                        render_columns(&columns)
                    ));
                }
            }
            out.push_str(&format!(
                "<p class=\"note\" data-tables=\"{tables}\" data-columns=\"{cells}\">{tables} tables and {cells} columns, read off a vault this build founded.</p>\n"
            ));
            out.push_str(END);
            Ok(out)
        })
    })();
    let _ = std::fs::remove_dir_all(&dir);
    rendered
}

/// `page` with its generated block replaced by `block`; `None` when the page
/// has no markers (a page that lost them is not silently re-grown).
#[must_use]
pub fn splice(page: &str, block: &str) -> Option<String> {
    let start = page.find(BEGIN)?;
    let end = page.find(END)? + END.len();
    (start < end).then(|| format!("{}{}{}", &page[..start], block, &page[end..]))
}
