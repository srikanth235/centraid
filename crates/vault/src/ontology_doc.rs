//! The published ontology page's schema section, rendered from the founded file.
//!
//! `scripts/docs-site/src/content/ontology-body.html` is the model's public
//! design. Its §03 is not written: it is this module's output, spliced between
//! two markers by `bin/export-ontology-page`, and `tests/ontology_page.rs`
//! re-renders it from a vault founded by this build and diffs, so a table
//! added, renamed or dropped without the page is red (ONT-01 of the model
//! before [#1135](https://github.com/srikanth235/centraid/issues/1135) was
//! exactly that gap).
//!
//! Columns, types, nullability, keys and references come from SQLite's own
//! `PRAGMA table_xinfo` and `foreign_key_list` over the founded file. What a
//! table is *for* cannot be read from a file, so [`TABLES`] states it in a
//! sentence, and [`render_schema_section`] refuses a table that has none: a new
//! table is a decision about the page in the same change.

