//! THE DOOR THE ROOM RUNTIME STANDS ON (app-plane §1): the core hands a room host its one write
//! path, the time, and a way to show the shell a room it did not ask for. `crates/screens`
//! depends on this crate, so the runtime attaches itself through [`RoomHost`]; nothing here
//! knows what a room is beyond the wire.

use centraid_api_proto::core_v1 as wire;

use crate::error::Result;

pub trait RoomCtx {
    /// The mounted vault's clock, in milliseconds.
    fn now_ms(&self) -> i64;

    /// Run one vault command under `invoke_key`, through the one write path.
    ///
    /// # Errors
    /// The vault's refusal, or a failure that is not one.
    fn command(
        &self,
        name: &str,
        input: &serde_json::Value,
        invoke_key: &str,
    ) -> Result<centraid_vault::commands::CommandOutcome>;

    /// Materialise an export payload in the vault's private staging area for the save sheet.
    /// The returned path is generated by the core and is safe to hand to the shell.
    fn stage_room_file(&self, bytes: &[u8]) -> Result<String> {
        let _ = bytes;
        Err(crate::error::CoreError::Unavailable {
            reason: "this door cannot stage a room export".to_owned(),
        })
    }

    /// Adopt a streamed archive produced in the vault staging area into private, generated
    /// room-export storage before handing it to a save sheet.
    fn stage_room_archive(&self) -> Result<String> {
        Err(crate::error::CoreError::Unavailable {
            reason: "this door cannot stage a room archive".to_owned(),
        })
    }

    /// Read already staged/held content by digest, capped by the caller. Room imports use this
    /// for small text formats and never receive a filesystem path.
    fn held_bytes(&self, hash: &str, max_bytes: u64) -> Result<Vec<u8>> {
        let _ = (hash, max_bytes);
        Err(crate::error::CoreError::Unavailable {
            reason: "held content is unavailable".to_owned(),
        })
    }

    /// Remove a room export after the shell's save sheet closes.
    fn remove_room_file(&self, path: &str) {
        let _ = path;
    }

    /// One request of the core's own (the backup status, a drain), answered inline.
    ///
    /// # Errors
    /// The core's refusal.
    fn call(&self, request: &wire::Request) -> Result<wire::Response>;

    /// The device store.
    ///
    /// # Errors
    /// The store cannot be opened.
    fn device(&self) -> Result<std::sync::Arc<crate::device::Checked<crate::device::DirStore>>>;

    /// Whether this phone has a Reminders store to import from (iOS does, Android has none).
    fn reminders_source(&self) -> bool {
        true
    }

    /// What a draft is kept under for the vault in front.
    fn vault_id(&self) -> String;

    /// A read-only door onto the vault file, guarded by the SQLite authorizer.
    ///
    /// # Errors
    /// The vault file cannot be opened for reading.
    fn reader(&self) -> Result<centraid_domain::read::Reader>;

    fn locker_unlocked(&self) -> bool;

    /// The monotonic Locker session epoch used to reject stale secure room payloads.
    fn locker_epoch(&self) -> u64;

    /// Advance the secure response epoch after a pending owner check is cancelled by navigation.
    /// This does not relock an already-open session.
    fn locker_cancel_check(&self);

    fn locker_unlock(&self) -> Result<(u32, Option<String>)>;

    fn locker_unlock_failed(&self) -> Result<u32>;

    fn locker_failed_unlocks(&self) -> Result<(u32, Option<String>)>;

    fn locker_lock(&self) -> Result<()>;

    fn locker_reveal_field(
        &self,
        item_id: &str,
        field_id: &str,
    ) -> Result<zeroize::Zeroizing<String>>;

    fn locker_seal_field(&self, field_id: &str, plaintext: &str) -> Result<(String, String)>;

    fn search(
        &self,
        request: &centraid_search::EachRequest,
    ) -> Result<Vec<centraid_search::Target>>;

    /// A bounded, keyset-paged FTS result. The answer preserves denial and cursor state.
    fn search_page(
        &self,
        request: &centraid_search::SearchRequest,
    ) -> Result<centraid_search::Answer> {
        let _ = request;
        Err(crate::error::CoreError::Unsupported {
            type_url: "room_search_page".to_owned(),
        })
    }

    /// The vault's whole-word spelling correction for the same search domain.
    fn search_correction(
        &self,
        kinds: &[String],
        query: &str,
        thin: bool,
    ) -> Result<Option<String>> {
        let _ = (kinds, query, thin);
        Err(crate::error::CoreError::Unsupported {
            type_url: "room_search_correction".to_owned(),
        })
    }

    /// Show the shell a room.
    fn push(&self, shown: wire::RoomShown);

    /// Ask the shell to perform a phone-side effect outside a request response.
    /// Room lifecycle transitions use this to cancel prompts and clear data
    /// that belongs to a vault that is no longer in front.
    fn push_effect(&self, effect: wire::ShellEffect);
}

pub trait RoomHost: Send + Sync {
    /// Answer one request from the shell.
    ///
    /// # Errors
    /// A refusal the shell should see as a typed error.
    fn call(&self, ctx: &dyn RoomCtx, request: &wire::RoomRequest) -> Result<wire::RoomResponse>;

    /// A commit wrote these tables: rooms that read them are built again and shown.
    fn changed(&self, ctx: &dyn RoomCtx, tables: &[String]);
}
