/// The sheet's body (everything below the banner `design_emit` prepends).
pub fn body(tokens: &Tokens) -> Result<String> {
    let site = &tokens.site;
    let native = &tokens.native;
    let number = |table: &std::collections::BTreeMap<String, f64>, section: &str, key: &str| {
        table
            .get(key)
            .copied()
            .with_context(|| format!("[native.{section}] has no `{key}`"))
    };

    // The static properties and the touch type scale, then the light theme.
    let mut root: Vec<(String, String)> = Vec::new();
    for key in RADII {
        root.push((
            format!("--r-{key}"),
            format!("{}px", number(&native.radii, "radii", key)?),
        ));
    }
    for key in SPACING {
        root.push((
            format!("--sp-{key}"),
            format!("{}px", number(&native.spacing, "spacing", key)?),
        ));
    }
    root.extend(pairs(&site.root.head));
    let mut touch = Vec::new();
    for (key, css) in TYPE_ROLES {
        let role = native
            .types
            .get(key)
            .with_context(|| format!("[native.type.{key}] is missing"))?;
        root.push((
            format!("--t-{css}"),
            type_shorthand(role.weight, role.font_size, role.line_height),
        ));
        touch.push((format!("--t-{css}-size"), rem(role.font_size)));
    }
    root.extend(touch);
    root.extend(pairs(&site.root.tail));
    let light = theme_props(tokens, Scheme::Light)?;
    let dark = theme_props(tokens, Scheme::Dark)?;
    root.extend(light.iter().cloned());

    // The desktop overrides.
    let mut fine = pairs(&site.fine.props);
    let mut fine_sizes = Vec::new();
    for (key, css) in TYPE_ROLES {
        let role = site
            .fine
            .types
            .get(key)
            .with_context(|| format!("[site.fine.type.{key}] is missing"))?;
        fine.push((
            format!("--t-{css}"),
            type_shorthand(role.weight, role.font_size, role.line_height),
        ));
        fine_sizes.push((format!("--t-{css}-size"), rem(role.font_size)));
    }
    fine.extend(fine_sizes);
    if site.fine.types.len() != TYPE_ROLES.len() {
        bail!("[site.fine.type] names a role the generator does not know");
    }

    let density: Vec<String> = site
        .density
        .iter()
        .map(|tier| {
            block(
                &format!("[data-density='{}']", tier.tier),
                &[
                    ("--density-pad".to_owned(), format!("{}px", tier.pad)),
                    ("--density-row".to_owned(), format!("{}px", tier.row)),
                ],
                0,
            )
        })
        .collect();

    let mut layer = String::from(":root {\n");
    for (at, group) in site.layer.iter().enumerate() {
        if at > 0 {
            layer.push('\n');
        }
        let lines: Vec<&str> = group.comment.split('\n').collect();
        for (n, line) in lines.iter().enumerate() {
            let lead = if n == 0 { "  /* " } else { "     " };
            let tail = if n + 1 == lines.len() { " */" } else { "" };
            let _ = writeln!(layer, "{lead}{line}{tail}");
        }
        for pair in &group.props {
            let _ = writeln!(layer, "  {}: {};", pair[0], pair[1]);
        }
    }
    layer.push('}');

    let sections = [
        block(":root", &root, 0),
        format!(
            "@media (pointer: fine) {{\n{}\n}}",
            block(":root", &fine, 2)
        ),
        format!(
            "@media (prefers-color-scheme: dark) {{\n{}\n}}",
            block(":root:not([data-theme])", &dark, 2)
        ),
        block("[data-theme='light']", &light, 0),
        block("[data-theme='dark']", &dark, 0),
        density.join("\n\n"),
        REDUCED_MOTION.to_owned(),
        SITE_LAYER_HEAD.to_owned(),
        layer,
    ];
    let mut out = String::new();
    out.push_str(GENERATED);
    out.push('\n');
    out.push_str(&font_faces(tokens));
    out.push('\n');
    out.push_str(GENERATED);
    out.push_str("\n\n");
    out.push_str(&sections.join("\n\n"));
    out.push('\n');
    Ok(out)
}

