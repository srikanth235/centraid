//! The public sites' stylesheet, generated from `design/tokens.toml` (#1173),
//! and the lint over what the sites author on top of it.
//!
//! `centraid.dev` (the landing page) and `centraid.dev/docs/` render in the
//! product's design. Their one shared sheet, `assets/centraid-tokens.css`, is
//! written here:
//!
//! * the colour roles, spacing, radii and touch type scale are the shells' own
//!   (`[native.*]`), so the sites cannot disagree with the apps;
//! * what the shells do not carry (the desktop overrides, the page-scale values,
//!   the font subsets, a few colours) is `[site]`;
//! * this module holds only the **order** the custom properties are written in
//!   and the **formulas** that compose them (`color-mix(...)`), the way the
//!   TypeScript `toCss()` it replaces did.
//!
//! The lint half ([`lint`]) is the other direction: it reads the sites'
//! authored files and fails on a font CDN, a literal font family, a retired
//! theme name, and a `var()` that names nothing the sheet or the file declares.
//! It replaces `scripts/site-tokens.mjs`.

