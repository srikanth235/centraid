#[derive(Clone, Copy, PartialEq, Eq)]
enum Scheme {
    Light,
    Dark,
}

fn block(selector: &str, props: &[(String, String)], indent: usize) -> String {
    let pad = " ".repeat(indent);
    let mut out = format!("{pad}{selector} {{\n");
    for (name, value) in props {
        let _ = writeln!(out, "{pad}  {name}: {value};");
    }
    let _ = write!(out, "{pad}}}");
    out
}

fn pairs(list: &PropList) -> Vec<(String, String)> {
    list.iter()
        .map(|pair| (pair[0].clone(), pair[1].clone()))
        .collect()
}

fn rem(px: f64) -> String {
    format!("{}rem", px / 16.0)
}

fn type_shorthand(weight: u32, size: f64, line: f64) -> String {
    format!("{weight} {}/{} var(--font-sans)", rem(size), rem(line))
}

/// One scheme's theme custom properties, in order.
fn theme_props(tokens: &Tokens, scheme: Scheme) -> Result<Vec<(String, String)>> {
    let (roles, site, name) = match scheme {
        Scheme::Light => (&tokens.native.colors.light, &tokens.site.light, "light"),
        Scheme::Dark => (&tokens.native.colors.dark, &tokens.site.dark, "dark"),
    };
    let role = |key: &str| -> Result<&String> {
        roles
            .get(key)
            .with_context(|| format!("[native.colors.{name}] has no `{key}`"))
    };
    let mut used: BTreeSet<&str> = BTreeSet::new();
    let mut out: Vec<(String, String)> = Vec::new();
    for (property, source) in THEME {
        let value = match source {
            Role(key) => role(key)?.clone(),
            Site => {
                used.insert(property);
                site.get(*property)
                    .with_context(|| format!("[site.{name}] has no `{property}`"))?
                    .clone()
            }
            Literal(text) => (*text).to_owned(),
            Mix(key, percent) => {
                format!(
                    "color-mix(in oklab, {} {percent}%, transparent)",
                    role(key)?
                )
            }
            ChipTint => {
                let key = match scheme {
                    Scheme::Light => "iconChipTintLight",
                    Scheme::Dark => "iconChipTintDark",
                };
                let tint = tokens
                    .native
                    .geometry
                    .get(key)
                    .with_context(|| format!("[native.geometry] has no `{key}`"))?;
                format!("{}%", (tint * 100.0).round())
            }
        };
        out.push(((*property).to_owned(), value));
    }
    for hue in HUES {
        let key = format!("c{}{}", hue[..1].to_uppercase(), &hue[1..]);
        out.push((format!("--c-{hue}"), role(&key)?.clone()));
    }
    for hue in HUES {
        let property = format!("--c-{hue}-text");
        let value = site
            .get(&property)
            .with_context(|| format!("[site.{name}] has no `{property}`"))?;
        out.push((property, value.clone()));
    }
    let wanted: BTreeSet<String> = HUES
        .iter()
        .map(|hue| format!("--c-{hue}-text"))
        .chain(used.iter().map(|property| (*property).to_owned()))
        .collect();
    for key in site.keys() {
        if !wanted.contains(key) {
            bail!("[site.{name}] `{key}` is not read by the generator");
        }
    }
    Ok(out)
}

fn font_faces(tokens: &Tokens) -> String {
    let fonts = &tokens.site.fonts;
    let slug = fonts.family.to_lowercase().replace(' ', "-");
    let mut out = String::new();
    for weight in &fonts.weights {
        for subset in &fonts.subsets {
            let _ = write!(
                out,
                "@font-face {{\n  font-family: '{family}';\n  font-style: normal;\n  font-display: swap;\n  font-weight: {weight};\n  src: url(fonts/{slug}-{name}-{weight}-normal.woff2) format('woff2');\n  unicode-range: {range};\n}}\n",
                family = fonts.family,
                name = subset.name,
                range = subset.unicode_range,
            );
        }
    }
    out
}

/// The product's own file names for the font files the sheet names, so a
/// missing `.woff2` can be reported by the caller.
#[must_use]
pub fn font_file_names(tokens: &Tokens) -> Vec<String> {
    let fonts = &tokens.site.fonts;
    let slug = fonts.family.to_lowercase().replace(' ', "-");
    let mut out = Vec::new();
    for weight in &fonts.weights {
        for subset in &fonts.subsets {
            out.push(format!("{slug}-{}-{weight}-normal.woff2", subset.name));
        }
    }
    out
}

