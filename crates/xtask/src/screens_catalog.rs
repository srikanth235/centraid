//! `cargo xtask screens-catalog`: THE RUST SPELLING OF EVERY APP'S CATALOGUE (#1135).
//!
//! Each app's `manifest.json` names its actions and queries and the typed input
//! of each. A Rust screen used to have to spell those a second time, as strings
//! (`"propose"`, `"title"`), so a rename in the manifest broke a phone at run
//! time. This emitter writes the one file that holds them as types instead:
//!
//! ```text
//! act::agenda::Propose { title, starts, ..Default::default() }  -> ActRequest
//! load::tasks::Board { view, ..Default::default() }             -> LoadRequest
//! ```
//!
//! A field is a manifest property. A required one is a plain field; a property
//! the schema lets be `null` is a `Field` (`Keep` leaves it out, `Clear` sends
//! `null`, `Is(x)` sends it); any other is an `Option`. A property typed `array`
//! or `object` travels as its JSON text (the core decodes it by the schema), a
//! boolean as 0 or 1, and a query's `limit` rides the request's own `limit`.
//! `id` is named for what it identifies (`task_id`) unless the action creates
//! the row (then it is the optional id the phone mints). The core still
//! validates the input against the schema: a required field left at its default
//! is refused as `input_schema`, so the types buy names, not totality.
//!
//! The file is committed. `--check` fails when it is stale, and a unit test
//! below runs the same comparison, so the gate cannot go green over a manifest
//! the Rust file has not heard of. The emitter's first form was the Kotlin
//! catalogue of the stopped lane (5513a5a78); the Kotlin output is gone with KMP.

use std::fmt::Write as _;
use std::path::Path;

use anyhow::{Context, Result, bail};
use serde_json::Value;

/// Where the generated file lives, relative to the repository root.
pub const OUTPUT: &str = "crates/screens/src/catalog.rs";

/// Write the file, or with `check` compare it to the committed one.
///
/// # Errors
/// A manifest that does not parse, an unreadable tree, or (with `check`) a
/// stale file.
pub fn run(root: &Path, check: bool) -> Result<()> {
    let wanted = generate(root)?;
    let path = root.join(OUTPUT);
    if check {
        let have = std::fs::read_to_string(&path).unwrap_or_default();
        if have != wanted {
            bail!(
                "{OUTPUT} is stale: a manifest changed and the Rust catalogue did not. \
                 Run `cargo xtask screens-catalog` and commit the result."
            );
        }
        return Ok(());
    }
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir)?;
    }
    std::fs::write(&path, wanted).with_context(|| format!("writing {}", path.display()))
}

/// The file's text, from the manifests under `crates/apps`.
///
/// # Errors
/// An unreadable or malformed manifest.
pub fn generate(root: &Path) -> Result<String> {
    let mut apps = Vec::new();
    for entry in std::fs::read_dir(root.join("crates/apps"))? {
        let manifest = entry?.path().join("manifest.json");
        if manifest.is_file() {
            let text = std::fs::read_to_string(&manifest)?;
            let json: Value = serde_json::from_str(&text)
                .with_context(|| format!("parsing {}", manifest.display()))?;
            apps.push(json);
        }
    }
    apps.sort_by(|a, b| text(a, "id").cmp(text(b, "id")));

    let mut out = String::from(HEADER);
    out.push_str("\npub mod act {\n    use super::*;\n");
    for app in &apps {
        emit_app(&mut out, app, Side::Act)?;
    }
    out.push_str("}\n\npub mod load {\n    use super::*;\n");
    for app in &apps {
        emit_app(&mut out, app, Side::Load)?;
    }
    out.push_str("}\n");
    Ok(out)
}

const HEADER: &str = "\
// GENERATED by `cargo xtask screens-catalog` from crates/apps/*/manifest.json. DO NOT EDIT.
//
// A screen never spells an action, a query or an input name as a string: it
// builds `act::<app>::<Action> { .. }` or `load::<app>::<Query> { .. }` and
// converts it into the request. A stale file fails `cargo xtask screens-catalog --check`.

#![cfg_attr(rustfmt, rustfmt::skip)]
#![allow(clippy::all, clippy::pedantic, missing_docs)]

use centraid_api_proto::core_v1 as wire;

use crate::field::{Field, flag, put_field, real, text, whole};
";

#[derive(Clone, Copy, PartialEq, Eq)]
enum Side {
    Act,
    Load,
}

fn emit_app(out: &mut String, app: &Value, side: Side) -> Result<()> {
    let id = text(app, "id");
    let key = if side == Side::Act {
        "actions"
    } else {
        "queries"
    };
    let items = app
        .get(key)
        .and_then(Value::as_array)
        .with_context(|| format!("{id} has no `{key}`"))?;
    if items.is_empty() {
        return Ok(());
    }
    let _ = writeln!(out, "\n    pub mod {} {{\n        use super::*;", snake(id));
    let _ = writeln!(out, "        pub const APP: &str = \"{id}\";");
    for item in items {
        emit_item(out, item, side)?;
    }
    out.push_str("    }\n");
    Ok(())
}

/// One manifest property, as a Rust field.
struct Param {
    /// The manifest's name, sent on the wire.
    wire: String,
    /// The Rust field name.
    name: String,
    /// The Rust type, without `Option`/`Field`.
    ty: String,
    /// The `Value` constructor for one element.
    encode: &'static str,
    required: bool,
    /// The schema lets the property be `null`: the caller can clear it.
    nullable: bool,
    /// A string enum: `(Rust variant, wire value)`.
    entries: Vec<(String, String)>,
    /// The query's `limit`, which rides the request itself.
    is_limit: bool,
    /// A required property whose schema allows exactly one value (`kind: "section"`):
    /// not a field, always sent.
    fixed: Option<String>,
}

fn emit_item(out: &mut String, item: &Value, side: Side) -> Result<()> {
    let name = text(item, "name");
    let ty = pascal(name);
    let verb = text(item, "verb");
    let kind = text(item, "kind");
    let schema = item.get("input").cloned().unwrap_or(Value::Null);
    let required: Vec<&str> = schema
        .get("required")
        .and_then(Value::as_array)
        .map(|names| names.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();
    let mut params = Vec::new();
    if let Some(props) = schema.get("properties").and_then(Value::as_object) {
        let siblings: Vec<&String> = props.keys().collect();
        for (wire, prop) in props {
            params.push(param(
                side, &ty, wire, prop, &required, kind, verb, &siblings,
            ));
        }
    }
    // Required first, then the rest; each group in the manifest's (sorted) order.
    params.sort_by_key(|p| !p.required);

    for p in params
        .iter()
        .filter(|p| !p.entries.is_empty() && p.fixed.is_none())
    {
        let first = &p.entries[0].0;
        let variants: Vec<String> = p
            .entries
            .iter()
            .map(|(variant, _)| variant.clone())
            .collect();
        let _ = writeln!(
            out,
            "\n        #[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]\n        pub enum {ty}{} {{",
            pascal(&p.wire)
        );
        for variant in &variants {
            if variant == first {
                out.push_str("            #[default]\n");
            }
            let _ = writeln!(out, "            {variant},");
        }
        out.push_str("        }\n");
        let _ = writeln!(out, "        impl {ty}{} {{", pascal(&p.wire));
        out.push_str("            fn wire(self) -> &'static str {\n                match self {\n");
        for (variant, wire) in &p.entries {
            let _ = writeln!(out, "                    Self::{variant} => \"{wire}\",");
        }
        out.push_str("                }\n            }\n        }\n");
    }

    let doc = one_line(text(item, "description"));
    let returns = if side == Side::Act {
        "ActRequest"
    } else {
        "LoadRequest"
    };
    let _ = writeln!(out, "\n        /// {doc}");
    let _ = writeln!(
        out,
        "        #[derive(Clone, Debug, Default)]\n        pub struct {ty} {{"
    );
    for p in params.iter().filter(|p| p.fixed.is_none()) {
        let _ = writeln!(out, "            pub {}: {},", p.name, field_type(p));
    }
    out.push_str("        }\n");
    let _ = writeln!(
        out,
        "        impl {ty} {{\n            pub const NAME: &str = \"{name}\";"
    );
    let _ = writeln!(
        out,
        "            pub fn request(self) -> wire::{returns} {{"
    );
    let _ = writeln!(out, "                #[allow(unused_mut)]");
    let _ = writeln!(
        out,
        "                let mut map = std::collections::HashMap::<String, wire::Value>::new();"
    );
    for p in params.iter().filter(|p| !p.is_limit) {
        let _ = writeln!(out, "                {}", put(p));
    }
    if side == Side::Act {
        out.push_str(
            "                wire::ActRequest { app: APP.to_owned(), action: Self::NAME.to_owned(), input: map, invoke_key: String::new() }\n",
        );
    } else {
        let limit = params
            .iter()
            .find(|p| p.is_limit)
            .map_or_else(String::new, |p| format!(" limit: self.{},", p.name));
        let _ = writeln!(
            out,
            "                wire::LoadRequest {{ app: APP.to_owned(), query: Self::NAME.to_owned(),{limit} params: map, ..Default::default() }}"
        );
    }
    out.push_str("            }\n        }\n");
    let _ = writeln!(
        out,
        "        impl From<{ty}> for wire::{returns} {{\n            fn from(value: {ty}) -> Self {{\n                value.request()\n            }}\n        }}"
    );
    Ok(())
}

#[allow(clippy::too_many_arguments)]
fn param(
    side: Side,
    ty_name: &str,
    wire: &str,
    prop: &Value,
    required: &[&str],
    kind: &str,
    verb: &str,
    siblings: &[&String],
) -> Param {
    let types: Vec<&str> = match prop.get("type") {
        Some(Value::String(one)) => vec![one.as_str()],
        Some(Value::Array(many)) => many.iter().filter_map(Value::as_str).collect(),
        _ => Vec::new(),
    };
    let nullable = types.contains(&"null");
    let base = types
        .iter()
        .find(|t| **t != "null")
        .copied()
        .unwrap_or("string");
    let entries: Vec<(String, String)> = prop
        .get("enum")
        .and_then(Value::as_array)
        .map(|values| {
            values
                .iter()
                .filter_map(Value::as_str)
                .map(|value| (pascal(value), value.to_owned()))
                .collect()
        })
        .unwrap_or_default();
    let (ty, encode) = if entries.is_empty() {
        match base {
            "integer" => ("i64".to_owned(), "whole"),
            "number" => ("f64".to_owned(), "real"),
            "boolean" => ("bool".to_owned(), "flag"),
            // An array or an object is its JSON text; the core decodes it by the schema.
            _ => ("String".to_owned(), "text"),
        }
    } else {
        (format!("{ty_name}{}", pascal(wire)), "choice")
    };
    // `id` is named for what it identifies, unless that spelling is another property's.
    let named = format!("{}_id", snake(kind));
    let clashes = siblings.iter().any(|other| snake(other) == named);
    let name = if wire == "id" && verb != "create" && side == Side::Act && !clashes {
        named
    } else {
        snake(wire)
    };
    let is_limit = side == Side::Load && wire == "limit";
    let fixed = (entries.len() == 1 && required.contains(&wire)).then(|| entries[0].1.clone());
    Param {
        fixed,
        wire: wire.to_owned(),
        name: keyword_safe(&name),
        ty: if is_limit { "u32".to_owned() } else { ty },
        encode,
        required: required.contains(&wire),
        nullable,
        entries,
        is_limit,
    }
}

fn field_type(p: &Param) -> String {
    if p.is_limit || p.required {
        p.ty.clone()
    } else if p.nullable {
        format!("Field<{}>", p.ty)
    } else {
        format!("Option<{}>", p.ty)
    }
}

/// The `Value` for the Rust expression `arg`.
fn value_expr(p: &Param, arg: &str) -> String {
    if p.encode == "choice" {
        format!("text({arg}.wire())")
    } else if p.encode == "text" {
        format!("text({arg})")
    } else {
        format!("{}({arg})", p.encode)
    }
}

/// The statement that adds this field to the request's map.
fn put(p: &Param) -> String {
    if let Some(only) = &p.fixed {
        format!("map.insert(\"{}\".to_owned(), text(\"{only}\"));", p.wire)
    } else if p.required {
        format!(
            "map.insert(\"{}\".to_owned(), {});",
            p.wire,
            value_expr(p, &format!("self.{}", p.name))
        )
    } else if p.nullable {
        format!(
            "put_field(&mut map, \"{}\", self.{}, |it| {});",
            p.wire,
            p.name,
            value_expr(p, "it")
        )
    } else {
        format!(
            "if let Some(it) = self.{} {{ map.insert(\"{}\".to_owned(), {}); }}",
            p.name,
            p.wire,
            value_expr(p, "it")
        )
    }
}

fn text<'a>(value: &'a Value, key: &str) -> &'a str {
    value.get(key).and_then(Value::as_str).unwrap_or_default()
}

fn one_line(raw: &str) -> String {
    raw.replace('\n', " ").replace("  ", " ")
}

/// `organize-task` -> `OrganizeTask`; `catch-up` -> `CatchUp`; `snake_case` too.
fn pascal(raw: &str) -> String {
    let name: String = raw
        .split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            chars.next().map_or_else(String::new, |first| {
                first.to_uppercase().collect::<String>() + chars.as_str()
            })
        })
        .collect();
    // An identifier cannot start with a digit (`3d`).
    if name.starts_with(|c: char| c.is_ascii_digit()) {
        format!("V{name}")
    } else {
        name
    }
}

/// `projectId` -> `project_id`; `catch-up` -> `catch_up`.
fn snake(raw: &str) -> String {
    let mut out = String::new();
    for (index, c) in raw.chars().enumerate() {
        if c.is_ascii_alphanumeric() {
            if c.is_ascii_uppercase() && index > 0 && !out.ends_with('_') {
                out.push('_');
            }
            out.push(c.to_ascii_lowercase());
        } else if !out.ends_with('_') && !out.is_empty() {
            out.push('_');
        }
    }
    out.trim_end_matches('_').to_owned()
}

fn keyword_safe(name: &str) -> String {
    const HARD: &[&str] = &[
        "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn",
        "for", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref",
        "return", "self", "static", "struct", "super", "trait", "true", "type", "unsafe", "use",
        "where", "while", "async", "await", "dyn", "abstract", "become", "box", "do", "final",
        "macro", "override", "priv", "typeof", "unsized", "virtual", "yield", "try",
    ];
    if HARD.contains(&name) {
        format!("r#{name}")
    } else {
        name.to_owned()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn root() -> std::path::PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../..")
            .canonicalize()
            .unwrap()
    }

    /// THE FRESHNESS GATE: the committed Rust file is exactly what the
    /// manifests generate. A manifest edit that does not regenerate fails here.
    #[test]
    fn the_committed_catalogue_is_fresh() {
        run(&root(), true).unwrap();
    }

    #[test]
    fn names_are_spelled_the_rust_way() {
        assert_eq!(pascal("organize-task"), "OrganizeTask");
        assert_eq!(snake("remind_before_min"), "remind_before_min");
        assert_eq!(snake("projectId"), "project_id");
    }

    #[test]
    fn agenda_has_its_typed_builders() {
        let file = generate(&root()).unwrap();
        assert!(file.contains("pub struct Propose {"));
        assert!(file.contains("pub mod agenda {"));
    }
}
