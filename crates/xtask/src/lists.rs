//! THE GENERATED LISTS (#1191, L1): a value the gateway and the phone must agree on is written once,
//! in the gateway's `rules/limits.rs`, and the phone's copy is generated from it.
//!
//! `cargo xtask lists` writes `crates/vault/src/backup/generated_limits.rs`; `--check` compares it.
//! The rule `generated-lists-are-fresh` (`cargo xtask rules`) is the same comparison, so a limit
//! changed on one side and not the other is red.
//!
//! The values are read off the gateway's source: each `pub const NAME: TYPE = EXPR;` where `EXPR` is
//! integers (underscores allowed) and the names of other constants of the file, joined by `*`.

use std::collections::BTreeMap;
use std::fs;
use std::path::Path;

use anyhow::{Context, Result, anyhow, bail};

use crate::rules::RuleReport;

const NAME: &str = "generated-lists-are-fresh";
const SOURCE: &str = "crates/gateway/src/rules/limits.rs";
const OUTPUT: &str = "crates/vault/src/backup/generated_limits.rs";
const BASELINE: &str = "contracts/migrations/001_baseline.sql";
const SHAPES_OUTPUT: &str = "crates/vault/tests/common/edge_shapes.rs";

/// The phone's constant, its type, the gateway constant it mirrors and what it is.
const MIRRORS: [(&str, &str, &str, &str); 4] = [
    (
        "NAMES_PER_CALL",
        "usize",
        "MAX_NAMES",
        "The most names one `exists` or `delete` call carries: the protocol's cap.",
    ),
    (
        "LIST_PAGE",
        "usize",
        "LIST_LIMIT",
        "The most entries one `list` page carries: the protocol's cap.",
    ),
    (
        "BUNDLE_BYTES",
        "u64",
        "MAX_BUNDLE_BYTES",
        "The most bytes one `put_many` sends or one `get_many` answers, every part's frame header\n/// included: the protocol's bundle cap.",
    ),
    (
        "TOMBSTONE_GRACE_MS",
        "u64",
        "GRACE_MS",
        "How long a tombstone keeps its bytes before a purge drops them.",
    ),
];

/// Write (or, with `check`, compare) the generated files.
pub fn run(root: &Path, check: bool) -> Result<()> {
    for (output, wanted) in [
        (OUTPUT, render(root)?),
        (SHAPES_OUTPUT, render_shapes(root)?),
    ] {
        let path = root.join(output);
        if check {
            let held = fs::read_to_string(&path).unwrap_or_default();
            if held != wanted {
                bail!("{output} is stale: run `cargo xtask lists`");
            }
        } else {
            fs::write(&path, wanted).with_context(|| format!("writing {output}"))?;
        }
    }
    Ok(())
}

/// The shapes the baseline seeds `edge_shape` with, as a test's oracle: `(relation, from, to)`.
fn render_shapes(root: &Path) -> Result<String> {
    let baseline =
        fs::read_to_string(root.join(BASELINE)).with_context(|| format!("reading {BASELINE}"))?;
    let at = baseline
        .find("INSERT INTO edge_shape")
        .ok_or_else(|| anyhow!("{BASELINE} seeds no edge_shape"))?;
    let block = &baseline[at..];
    let block = &block[..block
        .find(';')
        .ok_or_else(|| anyhow!("the seed does not end"))?];
    let code: String = block
        .lines()
        .map(|line| line.split("--").next().unwrap_or(""))
        .collect::<Vec<_>>()
        .join("\n");
    let mut rows = Vec::new();
    let mut rest = code.split_once("VALUES").map_or("", |(_, rows)| rows);
    while let Some(open) = rest.find('(') {
        let close = rest[open..]
            .find(')')
            .ok_or_else(|| anyhow!("a seed row does not close"))?
            + open;
        let parts: Vec<&str> = rest[open + 1..close]
            .split(',')
            .map(|part| part.trim().trim_matches('\''))
            .collect();
        let [rel, from, to] = parts.as_slice() else {
            bail!(
                "an edge_shape row is not three values: {}",
                &rest[open..=close]
            );
        };
        rows.push(format!("    (\"{rel}\", \"{from}\", \"{to}\"),\n"));
        rest = &rest[close + 1..];
    }
    Ok(format!(
        "//! GENERATED by `cargo xtask lists` from the `edge_shape` seed in `{BASELINE}`: do not edit.\n\
         //!\n\
         //! The shapes the baseline seeds `edge_shape` with, for a test to hold the trigger and the\n\
         //! commands against (#1191, L1).\n\n\
         pub const SHAPES: [(&str, &str, &str); {}] = [\n{}];\n",
        rows.len(),
        rows.concat()
    ))
}

/// The `generated-lists-are-fresh` rule.
pub fn all(root: &Path) -> Vec<RuleReport> {
    let findings = match run(root, true) {
        Ok(()) => Vec::new(),
        Err(error) => vec![format!("{error:#}")],
    };
    vec![RuleReport::applied(NAME, 1, findings)]
}

fn render(root: &Path) -> Result<String> {
    let source =
        fs::read_to_string(root.join(SOURCE)).with_context(|| format!("reading {SOURCE}"))?;
    let consts = constants(&source);
    let mut out = String::from(
        "//! GENERATED by `cargo xtask lists` from `crates/gateway/src/rules/limits.rs`: do not edit.\n\
         //!\n\
         //! The limits the phone and the gateway must agree on. The gateway's file is the one place\n\
         //! each is written (#1191, L1); `cargo xtask rules` fails when this file is not what the\n\
         //! generator writes.\n\n",
    );
    for (name, ty, from, doc) in MIRRORS {
        let value = value_of(&consts, from, &mut Vec::new())?;
        out.push_str(&format!(
            "/// {doc}\n/// Mirrors the gateway's `{from}`.\npub const {name}: {ty} = {value};\n\n"
        ));
    }
    out.truncate(out.trim_end().len());
    out.push('\n');
    Ok(out)
}

/// Every `pub const NAME: TYPE = EXPR;` of the source, by name.
fn constants(source: &str) -> BTreeMap<String, String> {
    let mut found = BTreeMap::new();
    for statement in source.split(';') {
        let code: String = statement
            .lines()
            .filter(|line| !line.trim_start().starts_with("//"))
            .collect::<Vec<_>>()
            .join(" ");
        let Some(rest) = code.trim().strip_prefix("pub const ") else {
            continue;
        };
        let Some((head, expr)) = rest.split_once('=') else {
            continue;
        };
        let Some((name, _)) = head.split_once(':') else {
            continue;
        };
        found.insert(name.trim().to_owned(), expr.trim().to_owned());
    }
    found
}

fn value_of(consts: &BTreeMap<String, String>, name: &str, seen: &mut Vec<String>) -> Result<u128> {
    if seen.iter().any(|held| held == name) {
        bail!("`{name}` is defined in terms of itself");
    }
    let expr = consts
        .get(name)
        .ok_or_else(|| anyhow!("{SOURCE} has no constant `{name}`"))?;
    seen.push(name.to_owned());
    let mut product: u128 = 1;
    for factor in expr.split('*') {
        let factor = factor.trim();
        let number = if factor.chars().all(|c| c.is_ascii_digit() || c == '_') && !factor.is_empty()
        {
            factor
                .replace('_', "")
                .parse::<u128>()
                .with_context(|| format!("`{factor}` in `{name}`"))?
        } else {
            value_of(consts, factor, seen)?
        };
        product *= number;
    }
    seen.pop();
    Ok(product)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_product_of_integers_and_named_constants_is_evaluated() {
        let consts = constants(
            "/// the day\npub const DAY_MS: i64 = 86_400_000;\n// a note\npub const GRACE_MS: i64 = 7 * DAY_MS;\npub const MAX_NAMES: usize = 1_000;",
        );
        assert_eq!(
            value_of(&consts, "GRACE_MS", &mut Vec::new()).unwrap(),
            604_800_000
        );
        assert_eq!(
            value_of(&consts, "MAX_NAMES", &mut Vec::new()).unwrap(),
            1000
        );
        assert!(value_of(&consts, "NO_SUCH", &mut Vec::new()).is_err());
    }

    #[test]
    fn the_generated_file_is_what_the_generator_writes_and_an_edit_is_seen() {
        let root = crate::testing::fixture_dir("lists-fresh");
        fs::create_dir_all(root.join("crates/gateway/src/rules")).unwrap();
        fs::create_dir_all(root.join("crates/vault/src/backup")).unwrap();
        fs::create_dir_all(root.join("crates/vault/tests/common")).unwrap();
        fs::create_dir_all(root.join("contracts/migrations")).unwrap();
        fs::write(
            root.join(BASELINE),
            "INSERT INTO edge_shape (rel, from_kind, to_kind) VALUES\n  ('contains', 'album', 'photo'),\n  -- a note\n  ('tagged', '*', 'tag');\n",
        )
        .unwrap();
        fs::write(
            root.join(SOURCE),
            "pub const DAY_MS: i64 = 86_400_000;\npub const MAX_NAMES: usize = 1_000;\npub const LIST_LIMIT: usize = 1_000;\npub const MAX_BUNDLE_BYTES: u64 = 256 * 1024 * 1024;\npub const GRACE_MS: i64 = 7 * DAY_MS;\n",
        )
        .unwrap();
        assert!(run(&root, true).is_err(), "nothing written yet is stale");
        run(&root, false).unwrap();
        run(&root, true).unwrap();
        assert!(all(&root)[0].findings.is_empty());
        let path = root.join(OUTPUT);
        let text = fs::read_to_string(&path).unwrap();
        assert!(
            text.contains("pub const TOMBSTONE_GRACE_MS: u64 = 604800000;"),
            "{text}"
        );
        fs::write(&path, text.replace("604800000", "1")).unwrap();
        assert!(
            !all(&root)[0].findings.is_empty(),
            "an edited generated file is seen"
        );
    }
}
