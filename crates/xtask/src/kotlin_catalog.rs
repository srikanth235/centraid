//! `cargo xtask kotlin-catalog`: THE KOTLIN SPELLING OF EVERY APP'S CATALOGUE (#1135).
//!
//! Each app's `manifest.json` names its actions and queries and the typed input
//! of each. Kotlin used to spell those names a second time, as strings (`"task.add"`,
//! `{"id":…}`), so a rename in the manifest broke a phone at run time. This
//! emitter writes the one Kotlin file that holds them as functions instead:
//!
//! ```text
//! Act.Tasks.Complete(taskId)            -> ActRequest
//! Load.Tasks.Board(view = …, limit = …) -> LoadRequest
//! ```
//!
//! A parameter is a manifest property: a required one is required, a property the
//! schema lets be `null` is a `Field` (`Keep` leaves it alone, `Clear` sets it
//! `null`, `Is(x)` sets it), any other is nullable and absent when `null`. A
//! property typed `array` or `object` travels as its JSON text (the core
//! decodes it by the schema), and a query's `limit` rides the request's own
//! `limit`. `id` is named for what it identifies (`taskId`) unless the action
//! creates the row (then it is the optional id the phone mints).
//!
//! The file is committed. `--check` fails when it is stale, and a unit test below
//! runs the same comparison, so the gate cannot go green over a manifest the
//! Kotlin file has not heard of.

use std::fmt::Write as _;
use std::path::Path;

use anyhow::{Context, Result, bail};
use serde_json::Value;

/// Where the generated file lives, relative to the repository root.
pub const OUTPUT: &str =
    "mobile/shared/src/commonMain/kotlin/dev/centraid/shared/catalog/ActionCatalog.kt";

/// Write the file, or with `check` compare it to the committed one.
///
/// # Errors
/// A manifest that does not parse, an unreadable tree, or (with `check`) a
/// stale file.
pub fn run(root: &Path, check: bool) -> Result<()> {
    let wanted = generate(root)?;
    let path = root.join(OUTPUT);
    if check {
        let have = std::fs::read_to_string(&path).unwrap_or_default();
        if have != wanted {
            bail!(
                "{OUTPUT} is stale: a manifest changed and the Kotlin catalogue did not. \
                 Run `cargo xtask kotlin-catalog` and commit the result."
            );
        }
        return Ok(());
    }
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir)?;
    }
    std::fs::write(&path, wanted).with_context(|| format!("writing {}", path.display()))
}

/// The file's text, from the nine manifests under `crates/apps`.
///
/// # Errors
/// An unreadable or malformed manifest.
pub fn generate(root: &Path) -> Result<String> {
    let mut apps = Vec::new();
    for entry in std::fs::read_dir(root.join("crates/apps"))? {
        let manifest = entry?.path().join("manifest.json");
        if manifest.is_file() {
            let text = std::fs::read_to_string(&manifest)?;
            let json: Value = serde_json::from_str(&text)
                .with_context(|| format!("parsing {}", manifest.display()))?;
            apps.push(json);
        }
    }
    apps.sort_by(|a, b| text(a, "id").cmp(text(b, "id")));

    let mut out = String::from(HEADER);
    out.push_str("\npublic object Act {\n");
    for app in &apps {
        emit_app(&mut out, app, Side::Act)?;
    }
    out.push_str("}\n\npublic object Load {\n");
    for app in &apps {
        emit_app(&mut out, app, Side::Load)?;
    }
    out.push_str("}\n");
    Ok(out)
}

const HEADER: &str = "\
@file:Suppress(\"ktlint\", \"FunctionName\", \"unused\", \"detekt:all\")

// GENERATED by `cargo xtask kotlin-catalog` from crates/apps/*/manifest.json. DO NOT EDIT.
//
// Kotlin never spells an action, a query or an input name as a string: it calls
// `Act.<App>.<Action>(…)` or `Load.<App>.<Query>(…)`, and the runtime
// (`sync/ActionPlane.kt`) sends the request. A stale file fails
// `cargo xtask kotlin-catalog --check`.

package dev.centraid.shared.catalog

import centraid.core.v1.ActRequest
import centraid.core.v1.LoadRequest
";

#[derive(Clone, Copy, PartialEq, Eq)]
enum Side {
    Act,
    Load,
}

fn emit_app(out: &mut String, app: &Value, side: Side) -> Result<()> {
    let id = text(app, "id");
    let key = if side == Side::Act {
        "actions"
    } else {
        "queries"
    };
    let items = app
        .get(key)
        .and_then(Value::as_array)
        .with_context(|| format!("{id} has no `{key}`"))?;
    if items.is_empty() {
        return Ok(());
    }
    let _ = writeln!(out, "    public object {} {{", pascal(id));
    let _ = writeln!(out, "        public const val APP: String = \"{id}\"");
    for item in items {
        emit_item(out, item, side)?;
    }
    out.push_str("    }\n\n");
    Ok(())
}

/// One manifest property, as a Kotlin parameter.
struct Param {
    /// The manifest's name, sent on the wire.
    wire: String,
    /// The Kotlin parameter name.
    name: String,
    /// The Kotlin type, without nullability.
    ty: String,
    /// The `Value` constructor for one element.
    encode: &'static str,
    required: bool,
    /// The schema lets the property be `null`: the caller can clear it.
    nullable: bool,
    /// A string enum: `(Kotlin entry, wire value)`.
    entries: Vec<(String, String)>,
    /// The query's `limit`, which rides the request itself.
    is_limit: bool,
    /// A required property whose schema allows exactly one value (`kind: "section"`,
    /// `rel: "attached"`): not a parameter, always sent.
    fixed: Option<String>,
}

fn emit_item(out: &mut String, item: &Value, side: Side) -> Result<()> {
    let name = text(item, "name");
    let fun = pascal(name);
    let verb = text(item, "verb");
    let kind = text(item, "kind");
    let schema = item.get("input").cloned().unwrap_or(Value::Null);
    let required: Vec<&str> = schema
        .get("required")
        .and_then(Value::as_array)
        .map(|names| names.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();
    let mut params = Vec::new();
    if let Some(props) = schema.get("properties").and_then(Value::as_object) {
        let siblings: Vec<&String> = props.keys().collect();
        for (wire, prop) in props {
            params.push(param(
                side, &fun, wire, prop, &required, kind, verb, &siblings,
            ));
        }
    }
    // Required first, then the rest; each group in the manifest's (sorted) order.
    params.sort_by_key(|p| !p.required);

    for p in &params {
        if p.entries.is_empty() || p.fixed.is_some() {
            continue;
        }
        let entries: Vec<String> = p
            .entries
            .iter()
            .map(|(entry, wire)| format!("{entry}(\"{wire}\")"))
            .collect();
        let _ = writeln!(
            out,
            "\n        public enum class {fun}{}(internal val wire: String) {{ {} }}",
            pascal(&p.wire),
            entries.join(", ")
        );
    }
    let doc = one_line(text(item, "description"));
    let _ = writeln!(out, "\n        /** {doc} */");
    let returns = if side == Side::Act {
        "ActRequest"
    } else {
        "LoadRequest"
    };
    if params.iter().all(|p| p.fixed.is_some()) {
        let _ = writeln!(out, "        public fun {fun}(): {returns} =");
    } else {
        let _ = writeln!(out, "        public fun {fun}(");
        for p in params.iter().filter(|p| p.fixed.is_none()) {
            let _ = writeln!(out, "            {},", signature(p));
        }
        let _ = writeln!(out, "        ): {returns} =");
    }
    let ctor = if side == Side::Act {
        format!("act(APP, \"{name}\")")
    } else {
        let limit = params
            .iter()
            .find(|p| p.is_limit)
            .map_or_else(String::new, |p| format!(", limit = {}", p.name));
        format!("load(APP, \"{name}\"{limit})")
    };
    if params.iter().all(|p| p.is_limit) && side == Side::Load {
        let _ = writeln!(out, "            {ctor}");
    } else if params.is_empty() {
        let _ = writeln!(out, "            {ctor}");
    } else {
        let _ = writeln!(out, "            {ctor} {{");
        for p in params.iter().filter(|p| !p.is_limit) {
            let _ = writeln!(out, "                {}", put(p));
        }
        out.push_str("            }\n");
    }
    Ok(())
}

fn param(
    side: Side,
    fun: &str,
    wire: &str,
    prop: &Value,
    required: &[&str],
    kind: &str,
    verb: &str,
    siblings: &[&String],
) -> Param {
    let types: Vec<&str> = match prop.get("type") {
        Some(Value::String(one)) => vec![one.as_str()],
        Some(Value::Array(many)) => many.iter().filter_map(Value::as_str).collect(),
        _ => Vec::new(),
    };
    let nullable = types.contains(&"null");
    let base = types
        .iter()
        .find(|t| **t != "null")
        .copied()
        .unwrap_or("string");
    let entries: Vec<(String, String)> = prop
        .get("enum")
        .and_then(Value::as_array)
        .map(|values| {
            values
                .iter()
                .filter_map(Value::as_str)
                .map(|value| (pascal(value), value.to_owned()))
                .collect()
        })
        .unwrap_or_default();
    let (ty, encode) = if entries.is_empty() {
        match base {
            "integer" => ("Long".to_owned(), "whole"),
            "number" => ("Double".to_owned(), "real"),
            "boolean" => ("Boolean".to_owned(), "flag"),
            // An array or an object is its JSON text; the core decodes it by the schema.
            _ => ("String".to_owned(), "text"),
        }
    } else {
        (format!("{fun}{}", pascal(wire)), "choice")
    };
    // `id` is named for what it identifies, unless that spelling is another property's.
    let named = format!("{}Id", camel(kind));
    let clashes = siblings.iter().any(|other| camel(other) == named);
    let name = if wire == "id" && verb != "create" && side == Side::Act && !clashes {
        named
    } else {
        camel(wire)
    };
    let is_limit = side == Side::Load && wire == "limit";
    let fixed = (entries.len() == 1 && required.contains(&wire)).then(|| entries[0].1.clone());
    Param {
        fixed,
        wire: wire.to_owned(),
        name: keyword_safe(&name),
        ty: if is_limit { "Int".to_owned() } else { ty },
        encode,
        required: required.contains(&wire),
        nullable,
        entries,
        is_limit,
    }
}

fn signature(p: &Param) -> String {
    if p.is_limit {
        return format!("{}: Int = 0", p.name);
    }
    if p.required {
        format!("{}: {}", p.name, p.ty)
    } else if p.nullable {
        format!("{}: Field<{}> = Field.Keep", p.name, p.ty)
    } else {
        format!("{}: {}? = null", p.name, p.ty)
    }
}

/// The `Value` for the Kotlin expression `arg`.
fn value_expr(p: &Param, arg: &str) -> String {
    if p.encode == "choice" {
        format!("text({arg}.wire)")
    } else {
        format!("{}({arg})", p.encode)
    }
}

/// The statement that adds this parameter to the request's map.
fn put(p: &Param) -> String {
    if let Some(only) = &p.fixed {
        format!("put(\"{}\", text(\"{only}\"))", p.wire)
    } else if p.required {
        format!("put(\"{}\", {})", p.wire, value_expr(p, &p.name))
    } else if p.nullable {
        format!(
            "field(\"{}\", {}) {{ {} }}",
            p.wire,
            p.name,
            value_expr(p, "it")
        )
    } else {
        format!(
            "{}?.let {{ put(\"{}\", {}) }}",
            p.name,
            p.wire,
            value_expr(p, "it")
        )
    }
}

fn text<'a>(value: &'a Value, key: &str) -> &'a str {
    value.get(key).and_then(Value::as_str).unwrap_or_default()
}

fn one_line(raw: &str) -> String {
    // Kotlin comments NEST, so a `/*` inside a description would swallow the file.
    raw.replace("*/", "* /")
        .replace("/*", "/ *")
        .replace('\n', " ")
        .replace("  ", " ")
}

/// `organize-task` -> `OrganizeTask`; `catch-up` -> `CatchUp`; `snake_case` too.
fn pascal(raw: &str) -> String {
    let name: String = raw
        .split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            chars.next().map_or_else(String::new, |first| {
                first.to_uppercase().collect::<String>() + chars.as_str()
            })
        })
        .collect();
    // An identifier cannot start with a digit (`3d`).
    if name.starts_with(|c: char| c.is_ascii_digit()) {
        format!("V{name}")
    } else {
        name
    }
}

/// `project_id` -> `projectId`.
fn camel(raw: &str) -> String {
    let pascal = pascal(raw);
    let mut chars = pascal.chars();
    chars.next().map_or_else(String::new, |first| {
        first.to_lowercase().collect::<String>() + chars.as_str()
    })
}

fn keyword_safe(name: &str) -> String {
    const HARD: &[&str] = &[
        "as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in",
        "interface", "is", "null", "object", "package", "return", "super", "this", "throw",
        "true", "try", "typealias", "typeof", "val", "var", "when", "while",
    ];
    if HARD.contains(&name) {
        format!("`{name}`")
    } else {
        name.to_owned()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn root() -> std::path::PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../..")
            .canonicalize()
            .unwrap()
    }

    /// THE FRESHNESS GATE: the committed Kotlin file is exactly what the nine
    /// manifests generate. A manifest edit that does not regenerate fails here.
    #[test]
    fn the_committed_catalogue_is_fresh() {
        run(&root(), true).unwrap();
    }

    #[test]
    fn names_are_spelled_the_kotlin_way() {
        assert_eq!(pascal("organize-task"), "OrganizeTask");
        assert_eq!(pascal("catch-up"), "CatchUp");
        assert_eq!(camel("remind_before_min"), "remindBeforeMin");
        assert_eq!(camel("task"), "task");
    }

    #[test]
    fn tasks_have_their_typed_builders() {
        let file = generate(&root()).unwrap();
        assert!(file.contains("public fun Complete(taskId: String): ActRequest"));
        assert!(file.contains("public fun Board("));
        assert!(file.contains("due: Field<String> = Field.Keep"));
    }
}
