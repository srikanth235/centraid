//! Read actual Rust literals, rather than a regular expression over Rust source.
use std::{collections::BTreeMap, path::Path};

use anyhow::{Context, Result, ensure};
use syn::{Ident, LitStr, Token, parse::Parse, parse::ParseStream};

use super::Artifacts;

struct Catalogue(BTreeMap<String, String>);

impl Parse for Catalogue {
    fn parse(input: ParseStream<'_>) -> syn::Result<Self> {
        let mut words = BTreeMap::new();
        while !input.is_empty() {
            let kind: Ident = input.parse()?;
            let key: Ident = input.parse()?;
            input.parse::<Token![=]>()?;
            let row;
            syn::parenthesized!(row in input);
            let one: LitStr = row.parse()?;
            row.parse::<Token![,]>()?;
            let _: LitStr = row.parse()?;
            if !row.is_empty() {
                row.parse::<Token![,]>()?;
            }
            input.parse::<Token![;]>()?;
            if kind == "plain" {
                if words.insert(key.to_string(), one.value()).is_some() {
                    return Err(syn::Error::new(key.span(), "duplicate catalogue word"));
                }
            } else if kind != "counted" {
                return Err(syn::Error::new(kind.span(), "unknown catalogue row"));
            }
        }
        Ok(Self(words))
    }
}

fn read(source: &str) -> Result<BTreeMap<String, String>> {
    let mut words = BTreeMap::new();
    for item in syn::parse_file(source)?.items {
        if let syn::Item::Macro(item) = item
            && item.mac.path.is_ident("catalog")
        {
            for (key, word) in syn::parse2::<Catalogue>(item.mac.tokens)?.0 {
                ensure!(
                    words.insert(key.clone(), word).is_none(),
                    "duplicate word {key}"
                );
            }
        }
    }
    Ok(words)
}

pub(super) fn emit(root: &Path, out: &mut Artifacts) -> Result<()> {
    let mut words = read(&std::fs::read_to_string(
        root.join("crates/screens/src/strings/shared.rs"),
    )?)?;
    for (key, word) in read(&std::fs::read_to_string(
        root.join("crates/screens/src/strings/home.rs"),
    )?)? {
        words.insert(format!("home::{key}"), word);
    }
    let lookup = |key: &str| -> Result<&str> {
        words
            .get(key)
            .map(String::as_str)
            .filter(|s| !s.is_empty())
            .with_context(|| format!("missing plain catalogue word {key}"))
    };
    let mut swift = String::from(
        "// GENERATED by cargo xtask design from the Rust string catalogues.\nimport Foundation\n\npublic enum KitWords {\n",
    );
    let mut kotlin = String::from(
        "// GENERATED by cargo xtask design from the Rust string catalogues.\npackage dev.centraid.design\n\npublic object KitWords {\n",
    );
    for (name, key) in [
        ("BACK", "back"),
        ("BAND_CURRENT", "home::band_current_spoken"),
        ("BAND_HOME", "kit_band_home"),
        ("BAND_MORE", "kit_band_more"),
        ("CANCEL", "kit_cancel"),
        ("CLOSE_SEARCH", "kit_close_search"),
        ("DISMISS", "kit_dismiss"),
        ("DONE", "kit_done"),
        ("LOADING_MORE", "kit_loading_more"),
        ("OPEN", "kit_open"),
        ("OPENING", "kit_opening"),
        ("PENDING", "kit_pending"),
        ("RETRY", "kit_retry"),
        ("SAVE", "kit_save"),
        ("SEARCH", "kit_search"),
        ("SELECT", "kit_select"),
        ("SHOW_MORE", "kit_show_more"),
        ("WIDGET_AGENDA", "home::widget_agenda"),
        ("WIDGET_OPEN", "home::widget_open"),
        ("WIDGET_NEW", "home::widget_new"),
        ("WIDGET_EMPTY", "home::widget_empty"),
        ("WIDGET_UPDATED", "home::widget_updated"),
        ("AGENDA_OPEN_CALENDAR", "home::intent_calendar"),
        ("AGENDA_OPEN_REMINDERS", "home::intent_reminders"),
        ("AGENDA_NEW_REMINDER", "home::intent_new_reminder"),
        ("AGENDA_REMINDER_TITLE", "home::intent_reminder_title"),
    ] {
        let text = serde_json::to_string(lookup(key)?)?;
        swift.push_str(&format!("    public static let {name} = {text}\n"));
        kotlin.push_str(&format!(
            "    public const val {name}: String = {}\n",
            text.replace('$', "\\$")
        ));
    }
    for (name, key, slot) in [
        ("backTo", "back_to", "parent"),
        ("searchCorrected", "search_corrected", "corrected"),
    ] {
        let text = lookup(key)?;
        ensure!(
            text.contains(&format!("{{{slot}}}")),
            "{key} must carry {{{slot}}}"
        );
        let text = serde_json::to_string(text)?;
        swift.push_str(&format!(
            "    public static func {name}({slot}: String) -> String {{\n"
        ));
        kotlin.push_str(&format!(
            "    public fun {name}({slot}: String): String =\n"
        ));
        if name == "backTo" {
            swift.push_str("        if parent.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty { return BACK }\n");
            kotlin.push_str("        if (parent.isBlank()) BACK else\n");
        }
        swift.push_str(&format!(
            "        return {text}.replacingOccurrences(of: \"{{{slot}}}\", with: {slot})\n    }}\n"
        ));
        kotlin.push_str(&format!(
            "        {}.replace(\"{{{slot}}}\", {slot})\n",
            text.replace('$', "\\$")
        ));
    }
    swift.push_str("}\n");
    kotlin.push_str("}\n");
    out.text("mobile/iosApp/Design/Words.swift", swift);
    out.text(
        "mobile/androidApp/src/main/kotlin/dev/centraid/android/design/Words.kt",
        kotlin,
    );
    out.text(
        "mobile/iosApp/Design/AgendaIntentMetadata.swift",
        intent_metadata(
            [
                lookup("home::intent_calendar")?,
                lookup("home::intent_reminders")?,
                lookup("home::intent_new_reminder")?,
            ],
            lookup("home::intent_reminder_title")?,
        )?,
    );
    Ok(())
}

/// Apple's App Intents metadata extractor requires literal resource values at
/// each declaration. References to KitWords compile as Swift, but prevent export.
/// Actions remain native extensions; their labels still have one Rust source.
fn intent_metadata(titles: [&str; 3], reminder_title: &str) -> Result<String> {
    let mut swift = String::from(
        "// GENERATED by cargo xtask design from the Rust string catalogues.\nimport AppIntents\n",
    );
    for (name, title) in [
        "OpenCalendarIntent",
        "OpenRemindersIntent",
        "NewReminderIntent",
    ]
    .into_iter()
    .zip(titles)
    {
        swift.push_str(&format!(
            "\nstruct {name}: AppIntent {{\n    static let title: LocalizedStringResource = {}\n    static let openAppWhenRun = true\n",
            serde_json::to_string(title)?,
        ));
        if name == "NewReminderIntent" {
            swift.push_str(&format!(
                "    @Parameter(title: {})\n    var reminderTitle: String\n",
                serde_json::to_string(reminder_title)?,
            ));
        }
        swift.push_str("}\n");
    }
    Ok(swift)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_multiline_raw_and_unicode_literals_without_changing_the_words() {
        let words = read(
            r##"catalog! {
            plain back = ("Back\u{2026}", "Back…");
            plain quoted = (r#"Say "hello""#, r#"Say "hello""#);
            plain multiline = (
                "First\nsecond", "First\nsecond",
            );
            counted items = ("One", "Many");
        }"##,
        )
        .expect("valid Rust catalogue");
        assert_eq!(words["back"], "Back…");
        assert_eq!(words["quoted"], "Say \"hello\"");
        assert_eq!(words["multiline"], "First\nsecond");
        assert!(!words.contains_key("items"));
        assert!(read("catalog! { bad key = (\"x\", \"x\"); }").is_err());
    }

    #[test]
    fn intent_metadata_has_literal_resources_even_when_copy_needs_escaping() {
        let source = intent_metadata(
            ["Calendar", "Reminders", "New \"reminder\""],
            "Reminder title",
        )
        .expect("literal metadata");
        let titles: Vec<_> = source
            .lines()
            .filter_map(|line| {
                line.trim()
                    .strip_prefix("static let title: LocalizedStringResource = ")
            })
            .map(|literal| {
                serde_json::from_str::<String>(literal).expect("a literal, not a reference")
            })
            .collect();
        assert_eq!(titles, ["Calendar", "Reminders", "New \"reminder\""]);
        assert!(source.contains("@Parameter(title: \"Reminder title\")"));
        assert!(!source.contains("KitWords"));
        assert!(!source.contains("func perform"));
    }
}
