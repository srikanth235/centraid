//! Four quarters with a genuinely open centre (#1173).
//!
//! Construction comes from QuartersIcon.dc.html: radius 34 on a 120-unit
//! grid, diagonal cuts 5 units wide, and a 21.2-unit square with a 2-unit
//! outline. The vector paths subtract the gaps instead of painting them in
//! a background colour, so the assistant's mark works on every surface.
use anyhow::Result;
use image::{ExtendedColorType, ImageEncoder, codecs::png::PngEncoder};
use serde_json::json;

use super::{ANDROID, Artifacts, IOS, Tokens, rgba};

const SIDES: [&str; 4] = ["right", "bottom", "left", "top"];
const RADIUS: f64 = 34.0;
const HALF_HEART: f64 = 11.6;
const CUT: f64 = 5.0;

fn quarter_path() -> String {
    let cut = CUT / 2.0 * std::f64::consts::SQRT_2;
    let x = (cut + (2.0 * RADIUS * RADIUS - cut * cut).sqrt()) / 2.0;
    let y = x - cut;
    let inner_y = HALF_HEART - cut;
    format!(
        "M{:.5},{:.5} L{:.5},{:.5} A34,34 0 0,1 {:.5},{:.5} L{:.5},{:.5} Z",
        60.0 + HALF_HEART,
        60.0 - inner_y,
        60.0 + x,
        60.0 - y,
        60.0 + x,
        60.0 + y,
        60.0 + HALF_HEART,
        60.0 + inner_y,
    )
}

fn svg(t: &Tokens, tile: Option<&str>, tinted: bool) -> String {
    let viewbox = if tile.is_some() {
        "0 0 120 120"
    } else {
        "22 22 76 76"
    };
    let mut svg = format!(
        "<!-- GENERATED by cargo xtask design. -->\n<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"{viewbox}\">\n"
    );
    if let Some(tile) = tile {
        svg.push_str(&format!(
            "  <rect width=\"120\" height=\"120\" rx=\"27\" fill=\"{tile}\"/>\n"
        ));
        if tile == t.brand["light_tile"] {
            svg.push_str(&format!("  <rect x=\".75\" y=\".75\" width=\"118.5\" height=\"118.5\" rx=\"26.5\" fill=\"none\" stroke=\"{}\" stroke-width=\"1.5\"/>\n", t.brand["edge"]));
        }
    }
    for (i, side) in SIDES.iter().enumerate() {
        let key = if tinted {
            format!("tinted_{side}")
        } else {
            (*side).to_owned()
        };
        svg.push_str(&format!(
            "  <path d=\"{}\" transform=\"rotate({} 60 60)\" fill=\"{}\"/>\n",
            quarter_path(),
            i * 90,
            t.brand[&key]
        ));
    }
    svg.push_str("</svg>\n");
    svg
}

/// Return the quarter whose ink covers this point, leaving the cuts and heart
/// transparent. Positive y points down, as in both native drawing systems.
fn quarter(x: f64, y: f64) -> Option<usize> {
    if x * x + y * y > RADIUS * RADIUS
        || (x.abs() <= HALF_HEART && y.abs() <= HALF_HEART)
        || (x.abs() - y.abs()).abs() / std::f64::consts::SQRT_2 <= CUT / 2.0
    {
        return None;
    }
    Some(if x.abs() > y.abs() {
        if x > 0.0 { 0 } else { 2 }
    } else if y > 0.0 {
        1
    } else {
        3
    })
}

fn png(t: &Tokens, size: u32, tile_key: Option<&str>, tinted: bool) -> Result<Vec<u8>> {
    let colors = SIDES
        .iter()
        .map(|side| {
            let key = if tinted {
                format!("tinted_{side}")
            } else {
                (*side).to_owned()
            };
            rgba(&t.brand[&key])
        })
        .collect::<Result<Vec<_>>>()?;
    let background = tile_key
        .map(|key| rgba(&t.brand[key]))
        .transpose()?
        .unwrap_or([0; 4]);
    let edge = rgba(&t.brand["edge"])?;
    let channels = if tile_key.is_some() { 3 } else { 4 };
    let mut pixels = Vec::with_capacity((size * size * channels) as usize);
    let view = if tile_key.is_some() { 120.0 } else { 76.0 };
    // Four subpixels per axis give deterministic coverage at every launcher
    // density. No host font, browser, image service or platform renderer enters.
    for row in 0..size {
        for column in 0..size {
            let mut sum = [0u32; 4];
            for sy in 0..4 {
                for sx in 0..4 {
                    let x = (f64::from(column) + (f64::from(sx) + 0.5) / 4.0) / f64::from(size)
                        * view
                        - view / 2.0;
                    let y = (f64::from(row) + (f64::from(sy) + 0.5) / 4.0) / f64::from(size) * view
                        - view / 2.0;
                    let mut color = quarter(x, y).map_or(background, |q| colors[q]);
                    if tile_key == Some("light_tile") {
                        // The inset hairline around the white rounded tile.
                        let dx = x.abs() - 33.0;
                        let dy = y.abs() - 33.0;
                        let distance = dx.max(0.0).hypot(dy.max(0.0)) + dx.max(dy).min(0.0) - 27.0;
                        if (-1.5..=0.0).contains(&distance) {
                            color = edge;
                        }
                    }
                    // Accumulate premultiplied colour for the transparent mark
                    // so its antialiased edge has no dark fringe on white.
                    for channel in 0..3 {
                        sum[channel] += u32::from(color[channel]) * u32::from(color[3]);
                    }
                    sum[3] += u32::from(color[3]);
                }
            }
            for value in &sum[..3] {
                pixels.push(if sum[3] == 0 {
                    0
                } else {
                    (value / sum[3]) as u8
                });
            }
            if channels == 4 {
                pixels.push((sum[3] / 16) as u8);
            }
        }
    }
    let mut bytes = Vec::new();
    PngEncoder::new(&mut bytes).write_image(
        &pixels,
        size,
        size,
        if channels == 3 {
            ExtendedColorType::Rgb8
        } else {
            ExtendedColorType::Rgba8
        },
    )?;
    Ok(bytes)
}

fn vector(monochrome: bool, bare: bool) -> String {
    let viewport = if bare { 76 } else { 120 };
    let mut xml = format!(
        "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<!-- GENERATED by cargo xtask design. -->\n<vector xmlns:android=\"http://schemas.android.com/apk/res/android\" android:width=\"{viewport}dp\" android:height=\"{viewport}dp\" android:viewportWidth=\"{viewport}\" android:viewportHeight=\"{viewport}\">\n"
    );
    if bare {
        xml.push_str("    <group android:translateX=\"-22\" android:translateY=\"-22\">\n");
    }
    for (i, side) in SIDES.iter().enumerate() {
        // Android supplies its chosen themed colour to the monochrome mask.
        let color = if monochrome {
            "@android:color/black".to_owned()
        } else {
            format!("@color/design_brand_{side}")
        };
        xml.push_str(&format!("        <group android:rotation=\"{}\" android:pivotX=\"60\" android:pivotY=\"60\">\n            <path android:fillColor=\"{color}\" android:pathData=\"{}\"/>\n        </group>\n", i * 90, quarter_path()));
    }
    if bare {
        xml.push_str("    </group>\n");
    }
    xml.push_str("</vector>\n");
    xml
}

pub(super) fn emit(t: &Tokens, out: &mut Artifacts) -> Result<()> {
    let info = json!({"author":"xcode", "version":1});
    let assets = format!("{IOS}/Resources/Brand.xcassets");
    out.json(format!("{assets}/Contents.json"), &json!({"info":info}))?;
    let variants = [
        ("light", "light_tile", false),
        ("dark", "dark_tile", false),
        ("tinted", "tinted_tile", true),
    ];
    let mut images = Vec::new();
    for (name, key, tinted) in variants {
        out.text(
            format!("design/brand/icon-{name}.svg"),
            svg(t, Some(&t.brand[key]), tinted),
        );
        out.0.insert(
            format!("{assets}/AppIcon.appiconset/{name}.png"),
            png(t, 1024, Some(key), tinted)?,
        );
        let mut image = json!({"filename":format!("{name}.png"),"idiom":"universal","platform":"ios","size":"1024x1024"});
        if name != "light" {
            image["appearances"] = json!([{"appearance":"luminosity","value":name}]);
        }
        images.push(image);
    }
    out.json(
        format!("{assets}/AppIcon.appiconset/Contents.json"),
        &json!({"info":info,"images":images}),
    )?;
    out.text("design/brand/mark.svg", svg(t, None, false));
    out.0.insert(
        format!("{assets}/CentraidBrandMark.imageset/mark.png"),
        png(t, 256, None, false)?,
    );
    out.json(format!("{assets}/CentraidBrandMark.imageset/Contents.json"), &json!({"info":info,"images":[{"filename":"mark.png","idiom":"universal","scale":"1x"}],"properties":{"preserves-vector-representation":false}}))?;

    out.text(
        format!("{ANDROID}/res/drawable/centraid_brand_mark.xml"),
        vector(false, true),
    );
    out.text(
        format!("{ANDROID}/res/drawable/ic_launcher_foreground.xml"),
        vector(false, false),
    );
    out.text(
        format!("{ANDROID}/res/drawable/ic_launcher_monochrome.xml"),
        vector(true, false),
    );
    for (version, themed) in [(26, false), (33, true)] {
        let mono = if themed {
            "    <monochrome android:drawable=\"@drawable/ic_launcher_monochrome\"/>\n"
        } else {
            ""
        };
        let xml = format!(
            "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<!-- GENERATED by cargo xtask design. -->\n<adaptive-icon xmlns:android=\"http://schemas.android.com/apk/res/android\">\n    <background android:drawable=\"@android:color/white\"/>\n    <foreground android:drawable=\"@drawable/ic_launcher_foreground\"/>\n{mono}</adaptive-icon>\n"
        );
        out.text(
            format!("{ANDROID}/res/mipmap-anydpi-v{version}/ic_launcher.xml"),
            xml,
        );
    }
    for (density, size) in [
        ("mdpi", 48),
        ("hdpi", 72),
        ("xhdpi", 96),
        ("xxhdpi", 144),
        ("xxxhdpi", 192),
    ] {
        out.0.insert(
            format!("{ANDROID}/res/mipmap-{density}/ic_launcher.png"),
            png(t, size, Some("light_tile"), false)?,
        );
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn heart_and_diagonal_cuts_are_open_and_quarters_keep_their_direction() {
        assert_eq!(quarter(0.0, 0.0), None);
        assert_eq!(quarter(11.0, 8.0), None);
        assert_eq!(quarter(20.0, 20.0), None);
        assert_eq!(quarter(40.0, 0.0), None);
        assert_eq!(quarter(24.0, 0.0), Some(0));
        assert_eq!(quarter(0.0, 24.0), Some(1));
        assert_eq!(quarter(-24.0, 0.0), Some(2));
        assert_eq!(quarter(0.0, -24.0), Some(3));
    }

    #[test]
    fn launcher_is_opaque_and_chat_mark_has_a_transparent_heart() {
        let tokens: Tokens =
            toml::from_str(include_str!("../../../../design/tokens.toml")).expect("tokens");
        let icon =
            image::load_from_memory(&png(&tokens, 120, Some("light_tile"), false).expect("encode"))
                .expect("decode");
        assert_eq!(icon.color(), image::ColorType::Rgb8);
        let mark = image::load_from_memory(&png(&tokens, 76, None, false).expect("encode"))
            .expect("decode")
            .into_rgba8();
        assert_eq!(mark.get_pixel(38, 38).0[3], 0);
        assert_eq!(
            mark.get_pixel(62, 38).0,
            rgba(&tokens.brand["right"]).expect("right color")
        );
    }
}
