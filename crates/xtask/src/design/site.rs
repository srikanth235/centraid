//! The public sites consume the same values; there is no TypeScript theme.
use super::{Artifacts, Tokens, snake};
use anyhow::Result;

pub(super) fn emit(tokens: &Tokens, out: &mut Artifacts) -> Result<()> {
    let mut css = String::from("/* GENERATED by cargo xtask design from design/tokens.toml. */\n");
    for font in &tokens.fonts {
        css.push_str(&format!("@font-face {{\n  font-family: '{}';\n  font-style: normal;\n  font-display: swap;\n  font-weight: {};\n  src: url(fonts/{}) format('truetype');\n}}\n", font.name, font.weight, font.file));
    }
    css.push_str(":root {\n");
    for (family, fallback) in [("sans", "system-ui, sans-serif"), ("code", "monospace")] {
        if let Some(font) = tokens.fonts.iter().find(|font| font.family == family) {
            css.push_str(&format!(
                "  --font-{family}: '{}', {fallback};\n",
                font.name
            ));
        }
    }
    for (name, value) in &tokens.radii {
        css.push_str(&format!("  --r-{name}: {value}px;\n"));
    }
    for (name, value) in &tokens.spacing {
        css.push_str(&format!("  --sp-{name}: {value}px;\n"));
    }
    for (name, style) in &tokens.typography {
        let name = snake(name).replace('_', "-");
        css.push_str(&format!(
            "  --t-{name}: {} {}rem/{}rem var(--font-{});\n  --t-{name}-size: {}rem;\n",
            style.weight,
            style.size / 16.0,
            style.line_height / 16.0,
            style.family,
            style.size / 16.0
        ));
    }
    for (name, source, unit) in [
        ("dur-1", "durationOne", "ms"),
        ("dur-2", "durationTwo", "ms"),
        ("page-margin", "pageMargin", "px"),
        ("target-min", "targetMinCoarse", "px"),
        ("h-control", "targetMinCoarse", "px"),
        ("h-row", "targetMinCoarse", "px"),
        ("h-segmented", "targetMinCoarse", "px"),
    ] {
        css.push_str(&format!("  --{name}: {}{unit};\n", tokens.geometry[source]));
    }
    css.push_str(&format!("  --app-mark-hue: var(--shell-text);\n  --app-mark-tint: {}%;\n  --c-indigo-text: var(--money-text);\n  --c-ochre-text: var(--notes-text);\n", tokens.geometry["iconChipTintLight"] * 100.0));
    // These are semantic aliases, not another palette or type scale.
    css.push_str("  --accent-hover: var(--accent-ink-hover);\n  --bg-app: var(--bg);\n  --bg-hud: var(--glass);\n  --bg-wall: var(--bg);\n  --shadow-lg: none;\n  --shadow-md: none;\n  --shadow-sm: none;\n  --t-display-tracking: normal;\n  --t-title-tracking: normal;\n  --t-eyebrow-tracking: normal;\n  --t-eyebrow-transform: uppercase;\n  --t-mono-numeric: tabular-nums;\n  --ease: ease-in-out;\n  --ease-entry: ease-out;\n}\n");
    for (selector, dark) in [
        (":root, [data-theme='light']", false),
        (
            "@media (prefers-color-scheme: dark) { :root:not([data-theme])",
            true,
        ),
        ("[data-theme='dark']", true),
    ] {
        css.push_str(&format!("{selector} {{\n"));
        for (name, value) in tokens.colors(dark) {
            css.push_str(&format!(
                "  --{}: {value};\n",
                snake(&name).replace('_', "-")
            ));
        }
        css.push_str("}\n");
        if selector.starts_with('@') {
            css.push_str("}\n");
        }
    }
    out.text("design/site-tokens.css", css);
    Ok(())
}
