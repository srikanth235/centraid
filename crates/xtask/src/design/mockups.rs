//! Dark pages are the light source with the dark token sheet selected. Content
//! colours are never searched-and-replaced: only authored semantic roles vary.
use std::{collections::BTreeSet, fs, path::Path};

use anyhow::{Context, Result, ensure};

use super::{Artifacts, Tokens};

pub(super) fn emit(root: &Path, tokens: &Tokens, out: &mut Artifacts) -> Result<()> {
    let mut css = String::from("/* GENERATED by cargo xtask design from design/tokens.toml. */\n");
    for dark in [false, true] {
        css.push_str(if dark {
            ":root[data-theme=\"dark\"] {\n  color-scheme: dark;\n"
        } else {
            ":root {\n  color-scheme: light;\n"
        });
        for (key, value) in tokens.colors(dark) {
            css.push_str(&format!("  --ds-{key}: {value};\n"));
        }
        let tile = &tokens.brand[if dark { "dark_tile" } else { "light_tile" }];
        css.push_str(&format!("  --ds-brandTile: {tile};\n}}\n"));
    }
    out.text("design/mockups/tokens.css", css);
    // The canvas is the inventory. Every screen on its light page gets a dark
    // partner, even when that partner has not been committed yet.
    let canvas: serde_json::Value = serde_json::from_str(&fs::read_to_string(
        root.join("design/mockups/canvas.json"),
    )?)?;
    let mut screens = BTreeSet::new();
    if let Some(boards) = canvas.get("boards").and_then(serde_json::Value::as_object) {
        for (file, board) in boards {
            if board["page"] == "light" && file.ends_with(".dc.html") {
                screens.insert(file.clone());
            }
        }
    }
    collect_light_screens(&canvas, false, &mut screens);
    // Existing paired files cover older canvas formats too; the source still
    // comes exclusively from the light file, never the old dark bytes.
    for entry in fs::read_dir(root.join("design/mockups"))? {
        let name = entry?.file_name().to_string_lossy().into_owned();
        if let Some(stem) = name.strip_suffix("Dark.dc.html") {
            screens.insert(format!("{stem}.dc.html"));
        }
    }
    ensure!(!screens.is_empty(), "mockup inventory is empty");
    for file in &screens {
        let source = fs::read_to_string(root.join("design/mockups").join(file))
            .with_context(|| file.clone())?;
        ensure!(
            source.contains("tokens.css"),
            "{file} must load the shared token sheet"
        );
        let dark = render_dark(&source, &screens);
        out.text(
            format!(
                "design/mockups/{}Dark.dc.html",
                file.trim_end_matches(".dc.html")
            ),
            dark,
        );
    }
    Ok(())
}

fn collect_light_screens(value: &serde_json::Value, light: bool, screens: &mut BTreeSet<String>) {
    match value {
        serde_json::Value::Object(object) => {
            let light = light || object.values().any(|v| v.as_str() == Some("Light mode"));
            for value in object.values() {
                collect_light_screens(value, light, screens);
            }
        }
        serde_json::Value::Array(values) => {
            for value in values {
                collect_light_screens(value, light, screens);
            }
        }
        serde_json::Value::String(file)
            if light && file.ends_with(".dc.html") && !file.ends_with("Dark.dc.html") =>
        {
            screens.insert(file.clone());
        }
        _ => {}
    }
}

fn render_dark(source: &str, screens: &BTreeSet<String>) -> String {
    let mut dark = source
        .replacen(
            "<html lang=\"en\">",
            "<html lang=\"en\" data-theme=\"dark\">",
            1,
        )
        .replacen("</title>", " (dark)</title>", 1);
    for file in screens {
        dark = dark.replace(
            &format!("href=\"{file}\""),
            &format!("href=\"{}Dark.dc.html\"", file.trim_end_matches(".dc.html")),
        );
    }
    dark
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn dark_navigation_stays_dark_and_content_pixels_and_words_do_not_change() {
        let source = "<html lang=\"en\"><title>A</title><a href=\"B.dc.html\">B</a><svg data-centraid-icon=\"1\" fill=\"#F48E04\"></svg><div style=\"background:#FFFFFF;color:var(--ds-text)\">Document</div></html>";
        let dark = render_dark(source, &BTreeSet::from(["B.dc.html".into()]));
        assert!(dark.contains("data-theme=\"dark\""));
        assert!(dark.contains("href=\"BDark.dc.html\""));
        assert!(dark.contains("fill=\"#F48E04\""));
        assert!(dark.contains("background:#FFFFFF;color:var(--ds-text)"));
        assert!(dark.contains(">Document</div>"));
    }
}
