/// `<!-- part:Row variant="pending" title="Dentist" -->`, alone on its line.
struct Open {
    name: String,
    attrs: Vec<(String, String)>,
}

fn parse_open(line: &str) -> Option<Open> {
    let inner = line
        .trim()
        .strip_prefix("<!-- part:")?
        .strip_suffix("-->")?
        .trim();
    let name_end = inner.find(char::is_whitespace).unwrap_or(inner.len());
    let name = &inner[..name_end];
    if name.is_empty() || !name.bytes().all(|b| b.is_ascii_alphanumeric()) {
        return None;
    }
    let mut attrs = Vec::new();
    let mut rest = inner[name_end..].trim_start();
    while !rest.is_empty() {
        let eq = rest.find("=\"")?;
        let key = rest[..eq].trim().to_owned();
        let after = &rest[eq + 2..];
        let close = after.find('"')?;
        attrs.push((key, after[..close].to_owned()));
        rest = after[close + 1..].trim_start();
    }
    Some(Open {
        name: name.to_owned(),
        attrs,
    })
}

fn is_close(line: &str) -> bool {
    line.trim() == "<!-- /part -->"
}

fn indent_of(line: &str) -> &str {
    &line[..line.len() - line.trim_start().len()]
}

fn part_file(name: &str) -> String {
    format!("Part{name}.dc.html")
}

/// The insertable variants of a part board: `<!-- variant:name -->` … `<!-- /variant -->`.
fn variants(text: &str) -> Vec<(String, String)> {
    let mut out = Vec::new();
    let lines: Vec<&str> = text.split('\n').collect();
    let mut i = 0;
    while i < lines.len() {
        let trimmed = lines[i].trim();
        if let Some(name) = trimmed
            .strip_prefix("<!-- variant:")
            .and_then(|r| r.strip_suffix("-->"))
        {
            let indent = indent_of(lines[i]).len();
            let mut body = Vec::new();
            i += 1;
            while i < lines.len() && lines[i].trim() != "<!-- /variant -->" {
                let line = lines[i];
                let cut = indent.min(line.len() - line.trim_start().len());
                body.push(line[cut..].to_owned());
                i += 1;
            }
            out.push((name.trim().to_owned(), body.join("\n")));
        }
        i += 1;
    }
    out
}

fn apply_slots(name: &str, body: &str, attrs: &[(String, String)]) -> Result<String, String> {
    let mut body = body.to_owned();
    for (key, value) in attrs {
        if key == "variant" {
            continue;
        }
        let needle = format!("data-slot=\"{key}\"");
        let at = body
            .find(&needle)
            .ok_or_else(|| format!("part {name}: no {needle}"))?;
        let open = body[..at]
            .rfind('<')
            .ok_or_else(|| format!("part {name}: {needle} is not in a tag"))?;
        let close = tag_end(&body, open).ok_or_else(|| format!("part {name}: unterminated tag"))?;
        let tag_name: String = body[open + 1..]
            .chars()
            .take_while(|c| c.is_ascii_alphanumeric())
            .collect();
        let end = body[close..]
            .find(&format!("</{tag_name}>"))
            .ok_or_else(|| format!("part {name}: {needle} has no closing tag"))?;
        body.replace_range(close..close + end, value);
    }
    Ok(body)
}

fn part_body(dir: &Path, open: &Open, stack: &[String]) -> Result<String, String> {
    if stack.contains(&open.name) {
        return Err(format!("part cycle: {} > {}", stack.join(" > "), open.name));
    }
    let file = part_file(&open.name);
    let text = std::fs::read_to_string(dir.join(&file))
        .map_err(|_| format!("unknown part {} (no {file})", open.name))?;
    let all = variants(&text);
    let wanted = open
        .attrs
        .iter()
        .find(|(k, _)| k == "variant")
        .map(|(_, v)| v.as_str());
    let body = match (wanted, all.as_slice()) {
        (Some(name), _) => all
            .iter()
            .find(|(n, _)| n == name)
            .map(|(_, b)| b.clone())
            .ok_or_else(|| format!("part {}: no variant {name} in {file}", open.name))?,
        (None, [(_, only)]) => only.clone(),
        (None, []) => return Err(format!("{file} has no <!-- variant:… --> region")),
        (None, _) => return Err(format!("part {} needs a variant=\"…\"", open.name)),
    };
    let mut next = stack.to_vec();
    next.push(open.name.clone());
    let body = flatten(dir, &body, false, &next)?.0;
    apply_slots(&open.name, &body, &open.attrs)
}

/// Rewrite every part region of `text`. Returns the text and the parts whose region was not
/// what the generator writes. With `keep_markers` false the markers are dropped (nesting).
fn flatten(
    dir: &Path,
    text: &str,
    keep_markers: bool,
    stack: &[String],
) -> Result<(String, Vec<String>), String> {
    let lines: Vec<&str> = text.split('\n').collect();
    let mut out: Vec<String> = Vec::new();
    let mut drifted = Vec::new();
    let mut i = 0;
    while i < lines.len() {
        if let Some(open) = parse_open(lines[i]) {
            let mut depth = 1;
            let mut j = i + 1;
            while j < lines.len() {
                if parse_open(lines[j]).is_some() {
                    depth += 1;
                } else if is_close(lines[j]) {
                    depth -= 1;
                    if depth == 0 {
                        break;
                    }
                }
                j += 1;
            }
            if j == lines.len() {
                return Err(format!("part {} has no closing <!-- /part -->", open.name));
            }
            let indent = indent_of(lines[i]);
            let body = part_body(dir, &open, stack)?;
            let body: Vec<String> = body
                .split('\n')
                .map(|l| {
                    if l.is_empty() {
                        String::new()
                    } else {
                        format!("{indent}{l}")
                    }
                })
                .collect();
            if keep_markers {
                if lines[i + 1..j] != body.iter().map(String::as_str).collect::<Vec<_>>() {
                    drifted.push(open.name.clone());
                }
                out.push(lines[i].to_owned());
                out.extend(body);
                out.push(lines[j].to_owned());
            } else {
                out.extend(body);
            }
            i = j + 1;
            continue;
        }
        if is_close(lines[i]) {
            return Err("a closing <!-- /part --> has no opening marker".to_owned());
        }
        out.push(lines[i].to_owned());
        i += 1;
    }
    Ok((out.join("\n"), drifted))
}

