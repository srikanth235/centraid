#[derive(Debug)]
struct Tag {
    name: String,
    attrs: Vec<(String, String)>,
    closing: bool,
    self_closing: bool,
}

impl Tag {
    fn get(&self, name: &str) -> Option<&str> {
        self.attrs
            .iter()
            .find(|(n, _)| n == name)
            .map(|(_, v)| v.as_str())
    }

    fn has(&self, name: &str) -> bool {
        self.attrs.iter().any(|(n, _)| n == name)
    }
}

#[derive(Debug)]
enum Node<'a> {
    Tag(Tag),
    Text(&'a str),
    Raw(&'a str),
    Comment(&'a str),
}

fn parse_tag(source: &str) -> Tag {
    let inner = source
        .trim_start_matches('<')
        .trim_end_matches('>')
        .trim_end_matches('/');
    let closing = inner.starts_with('/');
    let inner = inner.trim_start_matches('/');
    let bytes = inner.as_bytes();
    let mut i = 0;
    while i < bytes.len() && !bytes[i].is_ascii_whitespace() {
        i += 1;
    }
    let name = inner[..i].to_ascii_lowercase();
    let mut attrs = Vec::new();
    while i < bytes.len() {
        while i < bytes.len() && (bytes[i].is_ascii_whitespace() || bytes[i] == b'/') {
            i += 1;
        }
        let start = i;
        while i < bytes.len()
            && !bytes[i].is_ascii_whitespace()
            && bytes[i] != b'='
            && bytes[i] != b'/'
        {
            i += 1;
        }
        if start == i {
            break;
        }
        let key = inner[start..i].to_owned();
        let mut value = String::new();
        if i < bytes.len() && bytes[i] == b'=' {
            i += 1;
            if i < bytes.len() && (bytes[i] == b'"' || bytes[i] == b'\'') {
                let quote = bytes[i];
                let from = i + 1;
                i = from;
                while i < bytes.len() && bytes[i] != quote {
                    i += 1;
                }
                value = inner[from..i].to_owned();
                i += 1;
            } else {
                let from = i;
                while i < bytes.len() && !bytes[i].is_ascii_whitespace() {
                    i += 1;
                }
                value = inner[from..i].to_owned();
            }
        }
        attrs.push((key, value));
    }
    Tag {
        name,
        attrs,
        closing,
        self_closing: source.trim_end_matches('>').ends_with('/'),
    }
}

fn tag_end(html: &str, at: usize) -> Option<usize> {
    let mut quote = None;
    for (offset, byte) in html.as_bytes()[at..].iter().enumerate() {
        match (*byte, quote) {
            (q @ (b'"' | b'\''), None) => quote = Some(q),
            (q, Some(open)) if q == open => quote = None,
            (b'>', None) => return Some(at + offset + 1),
            _ => {}
        }
    }
    None
}

fn nodes(html: &str) -> Vec<Node<'_>> {
    let mut out = Vec::new();
    let mut at = 0;
    while at < html.len() {
        let Some(lt) = html[at..].find('<') else {
            out.push(Node::Text(&html[at..]));
            break;
        };
        if lt > 0 {
            out.push(Node::Text(&html[at..at + lt]));
        }
        at += lt;
        let rest = &html[at..];
        if let Some(body) = rest.strip_prefix("<!--") {
            let end = body.find("-->").map_or(body.len(), |e| e + 3);
            out.push(Node::Comment(body[..end].trim_end_matches("-->")));
            at += 4 + end;
            continue;
        }
        if rest.starts_with("<!") || rest.starts_with("<?") {
            at += rest.find('>').map_or(rest.len(), |e| e + 1);
            continue;
        }
        let Some(end) = tag_end(html, at) else {
            out.push(Node::Text(rest));
            break;
        };
        let tag = parse_tag(&html[at..end]);
        at = end;
        let raw =
            matches!(tag.name.as_str(), "script" | "style") && !tag.closing && !tag.self_closing;
        let name = tag.name.clone();
        out.push(Node::Tag(tag));
        if raw {
            let close = format!("</{name}");
            let body_end = html[at..].find(&close).map_or(html.len(), |e| at + e);
            out.push(Node::Raw(&html[at..body_end]));
            at = body_end;
        }
    }
    out
}

/// Whether `value` writes a colour outside `var()`, `url()` and quotes.
fn writes_raw_colour(value: &str) -> bool {
    let mut clean = String::with_capacity(value.len());
    let bytes = value.as_bytes();
    let mut i = 0;
    while i < bytes.len() {
        let rest = &value[i..];
        if rest.starts_with("var(") || rest.starts_with("url(") {
            let mut depth = 0;
            while i < bytes.len() {
                match bytes[i] {
                    b'(' => depth += 1,
                    b')' => {
                        depth -= 1;
                        if depth == 0 {
                            i += 1;
                            break;
                        }
                    }
                    _ => {}
                }
                i += 1;
            }
            clean.push(' ');
            continue;
        }
        if bytes[i] == b'"' || bytes[i] == b'\'' {
            let quote = bytes[i];
            i += 1;
            while i < bytes.len() && bytes[i] != quote {
                i += 1;
            }
            i += 1;
            clean.push(' ');
            continue;
        }
        let ch = rest.chars().next().unwrap_or(' ');
        clean.push(ch);
        i += ch.len_utf8();
    }
    let cb = clean.as_bytes();
    for (index, byte) in cb.iter().enumerate() {
        if *byte == b'#' {
            let digits = cb[index + 1..]
                .iter()
                .take_while(|b| b.is_ascii_hexdigit())
                .count();
            let after = cb.get(index + 1 + digits);
            if matches!(digits, 3 | 4 | 6 | 8) && !after.is_some_and(|b| b.is_ascii_alphanumeric())
            {
                return true;
            }
        }
    }
    let lower = clean.to_ascii_lowercase();
    for func in [
        "rgb(", "rgba(", "hsl(", "hsla(", "hwb(", "lab(", "lch(", "oklch(", "oklab(",
    ] {
        let mut from = 0;
        while let Some(found) = lower[from..].find(func) {
            let at = from + found;
            let boundary = at == 0
                || !lower.as_bytes()[at - 1].is_ascii_alphanumeric()
                    && lower.as_bytes()[at - 1] != b'-';
            if boundary {
                return true;
            }
            from = at + func.len();
        }
    }
    let lb = lower.as_bytes();
    let mut i = 0;
    while i < lb.len() {
        if lb[i].is_ascii_alphabetic() {
            let start = i;
            while i < lb.len() && (lb[i].is_ascii_alphanumeric() || lb[i] == b'-' || lb[i] == b'_')
            {
                i += 1;
            }
            let word = &lower[start..i];
            let before_ok = start == 0 || !matches!(lb[start - 1], b'-' | b'_');
            if before_ok && COLOUR_NAMES.contains(&word) {
                return true;
            }
        } else {
            i += 1;
        }
    }
    false
}

/// Every `#RRGGBB` in `text`, upper case.
fn hexes_of(text: &str) -> Vec<String> {
    let bytes = text.as_bytes();
    let mut out = Vec::new();
    for (i, b) in bytes.iter().enumerate() {
        if *b == b'#'
            && bytes.len() >= i + 7
            && bytes[i + 1..i + 7].iter().all(u8::is_ascii_hexdigit)
            && !bytes.get(i + 7).is_some_and(u8::is_ascii_alphanumeric)
        {
            out.push(text[i..i + 7].to_ascii_uppercase());
        }
    }
    out
}

/// What a board says, drawn from its markup.
#[derive(Debug, Default)]
struct Facts {
    problems: Vec<String>,
    links: Vec<String>,
    nexts: Vec<String>,
    comments: usize,
    shown: String,
    hexes_in_text: Vec<String>,
    hexes_painted: Vec<String>,
}

fn board_link(tag: &Tag) -> Option<&str> {
    let href = tag.get("href")?;
    let name = href.strip_suffix(".dc.html")?;
    (!name.is_empty() && name.bytes().all(|b| b.is_ascii_alphanumeric())).then_some(href)
}

fn scan(html: &str, check_colour: bool) -> Facts {
    let mut facts = Facts::default();
    let mut stack: Vec<(String, bool, bool)> = Vec::new();
    let mut in_title = false;
    for node in nodes(html) {
        match node {
            Node::Comment(text) => {
                let text = text.trim();
                let marker = text.starts_with("part:")
                    || text == "/part"
                    || text.starts_with("variant:")
                    || text == "/variant";
                if !marker {
                    facts.comments += 1;
                }
            }
            Node::Raw(body) => {
                let in_style = stack.last().is_some_and(|f| f.0 == "style");
                let keep = stack.iter().any(|f| f.1);
                if in_style && check_colour && !keep && writes_raw_colour(body) {
                    facts
                        .problems
                        .push("a raw colour in a <style> block".to_owned());
                }
            }
            Node::Text(text) => {
                if stack.iter().any(|f| f.0 == "script" || f.0 == "style") {
                    continue;
                }
                facts.shown.push_str(text);
                facts.shown.push(' ');
                if in_title {
                    facts.shown.push(' ');
                }
                facts.hexes_in_text.extend(hexes_of(text));
            }
            Node::Tag(tag) => {
                if tag.closing {
                    if tag.name == "title" {
                        in_title = false;
                    }
                    if let Some(pos) = stack.iter().rposition(|f| f.0 == tag.name) {
                        stack.truncate(pos);
                    }
                    continue;
                }
                let keep_here = tag.has("data-keep") || stack.iter().any(|f| f.1);
                let link = board_link(&tag).map(str::to_owned);
                if let Some(href) = &link {
                    facts
                        .links
                        .push(href.trim_end_matches(".dc.html").to_owned());
                }
                if let Some(next) = tag.get("data-next") {
                    facts.nexts.push(next.to_owned());
                }
                if tag.name == "button" && stack.iter().any(|f| f.2) {
                    facts
                        .problems
                        .push("a <button> inside a board link".to_owned());
                }
                for (key, value) in &tag.attrs {
                    if COLOUR_ATTRS.contains(&key.as_str()) {
                        facts.hexes_painted.extend(hexes_of(value));
                    }
                    if SHOWN_ATTRS.contains(&key.as_str()) {
                        facts.shown.push_str(value);
                        facts.shown.push(' ');
                    }
                    if check_colour
                        && !keep_here
                        && COLOUR_ATTRS.contains(&key.as_str())
                        && writes_raw_colour(value)
                    {
                        let clip: String = value.chars().take(48).collect();
                        facts
                            .problems
                            .push(format!("a raw colour in <{} {key}=\"{clip}\">", tag.name));
                    }
                }
                if tag.name == "title" {
                    in_title = true;
                }
                if !VOID.contains(&tag.name.as_str()) && !tag.self_closing {
                    stack.push((tag.name.clone(), tag.has("data-keep"), link.is_some()));
                }
            }
        }
    }
    facts
}

