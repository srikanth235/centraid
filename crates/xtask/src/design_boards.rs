/// The "Never" column of the Say/Never table in `wording.md`.
fn never_words(wording: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut in_table = false;
    for line in wording.lines() {
        let cells: Vec<&str> = line.split('|').map(str::trim).collect();
        if cells.len() >= 4 && cells[1] == "Say" && cells[2] == "Never" {
            in_table = true;
            continue;
        }
        if !in_table {
            continue;
        }
        if !line.starts_with('|') {
            break;
        }
        if cells.len() < 4 || cells[1].starts_with("---") {
            continue;
        }
        for item in cells[2].split(',') {
            let item = item.trim();
            if !item.is_empty() {
                out.push(item.to_owned());
            }
        }
    }
    out
}

fn find_word(text: &str, phrase: &str) -> bool {
    let lower = text.to_ascii_lowercase();
    let needle = phrase.to_ascii_lowercase();
    let mut from = 0;
    while let Some(found) = lower[from..].find(&needle) {
        let start = from + found;
        let end = start + needle.len();
        let before = start == 0 || !lower.as_bytes()[start - 1].is_ascii_alphanumeric();
        let after = end >= lower.len() || !lower.as_bytes()[end].is_ascii_alphanumeric();
        if before && after {
            return true;
        }
        from = start + 1;
    }
    false
}

fn what_may_read(text: &str) -> bool {
    let lower = text.to_ascii_lowercase();
    let mut from = 0;
    while let Some(found) = lower[from..].find("what ") {
        let start = from + found;
        let window = &lower[start..lower.len().min(start + 70)];
        if let Some(at) = window.find(" may read")
            && !window[..at].contains(['.', '\n'])
        {
            return true;
        }
        from = start + 1;
    }
    false
}

/// The one literal command a member types keeps its name (`wording.md`).
fn without_commands(shown: &str) -> String {
    [
        "centraid-gateway",
        "centraid\u{2011}gateway",
        "centraid&#8209;gateway",
    ]
    .iter()
    .fold(shown.to_owned(), |text, command| text.replace(command, " "))
}

fn word_problems(shown: &str, never: &[String]) -> Vec<String> {
    let shown = &without_commands(shown);
    let mut out = Vec::new();
    for word in RETIRED {
        if find_word(shown, word) {
            out.push(format!("the retired word \"{word}\""));
        }
    }
    if what_may_read(shown) {
        out.push("a \"What … may read\" row".to_owned());
    }
    for word in never {
        if find_word(shown, word) {
            out.push(format!("the word \"{word}\", which wording.md says never"));
        }
    }
    out
}

