fn token_hexes(tokens: &Tokens) -> (BTreeSet<String>, BTreeSet<String>) {
    let mut all = BTreeSet::new();
    let mut core = BTreeSet::new();
    let put = |set: &mut BTreeSet<String>, value: &str| {
        if value.starts_with('#') && value.len() == 7 {
            set.insert(value.to_ascii_uppercase());
        }
    };
    let (l, d) = (&tokens.surface.light, &tokens.surface.dark);
    for value in [
        &l.page,
        &l.plain_page,
        &l.card,
        &l.sheet,
        &l.sheet_card,
        &l.fill,
        &l.line,
        &l.border,
        &l.tile,
        &d.page,
        &d.plain_page,
        &d.card,
        &d.sheet,
        &d.sheet_card,
        &d.fill,
        &d.line,
        &d.border,
        &d.tile,
    ] {
        put(&mut core, value);
    }
    let (l, d) = (&tokens.text.light, &tokens.text.dark);
    for value in [&l.ink, &l.body, &l.meta, &d.ink, &d.body, &d.meta] {
        put(&mut core, value);
    }
    let mut accents: Vec<&Accent> = vec![&tokens.shell];
    accents.extend(tokens.app.values());
    accents.extend(tokens.state.values());
    for accent in accents {
        for value in [&accent.light, &accent.dark_fill, &accent.dark_text] {
            put(&mut core, value);
        }
        for value in [&accent.tint, &accent.dark_tint, &accent.tile]
            .into_iter()
            .flatten()
        {
            put(&mut all, value);
        }
    }
    for value in tokens.list.values().chain(tokens.brand.values()) {
        put(&mut all, value);
    }
    for role in tokens.board.values() {
        put(&mut all, &role.light);
        put(&mut all, &role.dark);
    }
    let icon = &tokens.icon;
    for value in [
        &icon.light_tile,
        &icon.light_edge,
        &icon.light_tile_bottom,
        &icon.dark_tile,
        &icon.dark_ground_top,
        &icon.dark_ground_bottom,
        &icon.tinted_tile,
        &icon.tinted_mark,
        &icon.themed_tile,
        &icon.themed_glyph,
    ] {
        put(&mut all, value);
    }
    all.extend(core.iter().cloned());
    (all, core)
}

