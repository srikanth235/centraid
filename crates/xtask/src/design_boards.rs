/// What the boards' generator produces and finds.
#[derive(Debug, Default)]
pub struct Generated {
    /// Generated files (`tokens.css`, the dark twins, `canvas.json`), by repository path.
    pub files: BTreeMap<String, String>,
    /// Boards and parts with their part regions refilled, by repository path.
    pub rewrites: BTreeMap<String, String>,
    /// Dark twins on disk that no light board makes.
    pub stale: Vec<String>,
    pub problems: Vec<String>,
    pub counts: Counts,
}

#[derive(Debug, Default, Clone, Copy)]
pub struct Counts {
    pub boards: usize,
    pub parts: usize,
    pub links: usize,
    pub next: usize,
}

fn page_of(canvas: &serde_json::Value, name: &str) -> Option<String> {
    canvas["boards"][name]["page"].as_str().map(str::to_owned)
}

/// Generate everything and find every problem in the boards.
///
/// # Errors
/// An unreadable directory or `canvas.json`.
pub fn generate(root: &Path, tokens: &Tokens) -> Result<Generated> {
    let dir = root.join(MOCKUPS);
    let canvas_text =
        std::fs::read_to_string(dir.join(CANVAS)).with_context(|| format!("read {CANVAS}"))?;
    let mut canvas: serde_json::Value =
        serde_json::from_str(&canvas_text).context("parse canvas.json")?;
    let mut names: BTreeSet<String> = BTreeSet::new();
    for entry in std::fs::read_dir(&dir).with_context(|| format!("read {MOCKUPS}"))? {
        let name = entry?.file_name().to_string_lossy().into_owned();
        if name.ends_with(".dc.html") {
            names.insert(name);
        }
    }
    let is_twin = |name: &str| {
        name.strip_suffix("Dark.dc.html")
            .is_some_and(|stem| names.contains(&format!("{stem}.dc.html")))
    };
    let sources: Vec<String> = names.iter().filter(|n| !is_twin(n)).cloned().collect();
    let mut out = Generated::default();
    let page = |name: &str| page_of(&canvas, name).unwrap_or_default();
    let twinned: BTreeSet<String> = sources
        .iter()
        .filter(|n| matches!(page(n).as_str(), "light" | "parts"))
        .cloned()
        .collect();
    let never = std::fs::read_to_string(root.join(WORDING))
        .map(|text| never_words(&text))
        .unwrap_or_default();
    if never.is_empty() {
        out.problems
            .push(format!("{WORDING}: no Say/Never table found"));
    }
    let (all_hexes, core_hexes) = token_hexes(tokens);
    for name in &sources {
        let path = format!("{MOCKUPS}/{name}");
        let text =
            std::fs::read_to_string(dir.join(name)).with_context(|| format!("read {name}"))?;
        let (flat, drifted) = match flatten(&dir, &text, true, &[]) {
            Ok(done) => done,
            Err(message) => {
                out.problems.push(format!("{name}: {message}"));
                continue;
            }
        };
        for part in drifted.iter().collect::<BTreeSet<_>>() {
            out.problems.push(format!(
                "{name}: part {part} is not what the generator writes; edit {}, not {name}, then run `cargo xtask design`",
                part_file(part)
            ));
        }
        let board_page = page(name);
        let drawn = matches!(board_page.as_str(), "light" | "parts");
        let facts = scan(&flat, drawn);
        out.problems
            .extend(facts.problems.iter().map(|p| format!("{name}: {p}")));
        if drawn && facts.comments > 0 {
            out.problems.push(format!(
                "{name}: {} HTML comment(s); a board holds no history, git does",
                facts.comments
            ));
        }
        if drawn && !WORDS_EXEMPT.contains(&name.as_str()) {
            out.problems.extend(
                word_problems(&facts.shown, &never)
                    .into_iter()
                    .map(|p| format!("{name}: {p}")),
            );
        }
        if drawn && !flat.contains(&format!("href=\"./{TOKENS_CSS}\"")) {
            out.problems
                .push(format!("{name}: does not link ./{TOKENS_CSS}"));
        }
        for link in facts.links.iter().collect::<BTreeSet<_>>() {
            if !names.contains(&format!("{link}.dc.html")) {
                out.problems.push(format!(
                    "{name}: a link to {link}.dc.html, which is no board"
                ));
            }
        }
        for next in facts.nexts.iter().collect::<BTreeSet<_>>() {
            if names.contains(&format!("{next}.dc.html")) {
                out.problems.push(format!(
                    "{name}: data-next=\"{next}\" names a board that exists now; make it a link"
                ));
            }
        }
        out.counts.links += facts.links.len();
        out.counts.next += facts.nexts.len();
        if name == RULES_BOARD {
            let shown: BTreeSet<String> = facts.hexes_in_text.iter().cloned().collect();
            for hex in shown.difference(&all_hexes) {
                out.problems.push(format!(
                    "{name}: shows {hex}, which is no value in tokens.toml"
                ));
            }
            let painted: BTreeSet<String> = facts
                .hexes_painted
                .iter()
                .chain(facts.hexes_in_text.iter())
                .cloned()
                .collect();
            for hex in core_hexes.difference(&painted) {
                out.problems.push(format!(
                    "{name}: does not show {hex}, a value in tokens.toml"
                ));
            }
        }
        if name.starts_with("Part") {
            out.counts.parts += 1;
        } else if drawn {
            out.counts.boards += 1;
        }
        if flat != text {
            out.rewrites.insert(path.clone(), flat.clone());
        }
        if twinned.contains(name) {
            match twin_text(&flat, &twinned) {
                Ok(twin) => {
                    out.files
                        .insert(format!("{MOCKUPS}/{}", dark_name(name)), twin);
                }
                Err(message) => out.problems.push(format!("{name}: {message}")),
            }
        }
    }
    for name in &sources {
        if !canvas["boards"]
            .as_object()
            .is_some_and(|b| b.contains_key(name))
        {
            out.problems
                .push(format!("{name}: a board file with no entry in canvas.json"));
        }
    }
    if let Some(boards) = canvas["boards"].as_object_mut() {
        let light_missing: Vec<String> = boards
            .iter()
            .filter(|(n, e)| e["page"] != "dark" && !names.contains(n.as_str()))
            .map(|(n, _)| n.clone())
            .collect();
        for name in light_missing {
            out.problems
                .push(format!("{name}: a canvas.json entry with no file"));
        }
        let mut dark = BTreeMap::new();
        for name in &twinned {
            if let Some(entry) = boards.get(name) {
                let mut entry = entry.clone();
                entry["page"] = "dark".into();
                let title = entry["title"].as_str().unwrap_or(name).to_owned();
                entry["title"] = format!("{title} · dark").into();
                dark.insert(dark_name(name), entry);
            }
        }
        boards.retain(|_, e| e["page"] != "dark");
        boards.extend(dark);
    }
    let mut canvas_out = serde_json::to_string_pretty(&canvas).context("write canvas.json")?;
    canvas_out.push('\n');
    out.files.insert(format!("{MOCKUPS}/{CANVAS}"), canvas_out);
    out.files
        .insert(format!("{MOCKUPS}/{TOKENS_CSS}"), tokens_css(tokens));
    for name in &names {
        if is_twin(name) && !out.files.contains_key(&format!("{MOCKUPS}/{name}")) {
            out.stale.push(format!("{MOCKUPS}/{name}"));
        }
    }
    out.problems.sort();
    out.problems.dedup();
    Ok(out)
}

/// The first line where two texts differ, shortened to the stretch around the difference.
#[must_use]
pub fn first_difference(have: &str, want: &str) -> String {
    for (number, (a, b)) in have.lines().zip(want.lines()).enumerate() {
        if a != b {
            let common = a.bytes().zip(b.bytes()).take_while(|(x, y)| x == y).count();
            let from = (0..=common.saturating_sub(40))
                .rev()
                .find(|&i| a.is_char_boundary(i) && b.is_char_boundary(i))
                .unwrap_or(0);
            let clip = |s: &str| -> String { s[from..].chars().take(120).collect() };
            return format!(
                "line {}: committed `{}` / generated `{}`",
                number + 1,
                clip(a),
                clip(b)
            );
        }
    }
    format!(
        "committed has {} lines, generated has {}",
        have.lines().count(),
        want.lines().count()
    )
}

