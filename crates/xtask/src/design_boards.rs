fn dark_name(light: &str) -> String {
    light.replacen(".dc.html", "Dark.dc.html", 1)
}

fn twin_text(flat: &str, twins: &BTreeSet<String>) -> Result<String, String> {
    let mut text = flat.to_owned();
    let title = text.find("<title>").ok_or("no <title>")?;
    let end = text[title..].find("</title>").ok_or("no </title>")? + title;
    text.insert_str(end, " (dark)");
    let helmet = text.find("</helmet>").ok_or("no </helmet>")?;
    let root = text[helmet..]
        .find("<div")
        .ok_or("no board root after </helmet>")?
        + helmet;
    let root_end = tag_end(&text, root).ok_or("unterminated board root")?;
    if !text[root..root_end].contains("data-theme") {
        text.insert_str(root + 4, " data-theme=\"dark\"");
    }
    let mut out = String::with_capacity(text.len());
    let mut at = 0;
    while let Some(found) = text[at..].find("href=\"") {
        let start = at + found + 6;
        let Some(len) = text[start..].find('"') else {
            break;
        };
        out.push_str(&text[at..start]);
        let href = &text[start..start + len];
        match href.strip_suffix(".dc.html") {
            Some(stem) if twins.contains(href) && !stem.ends_with("Dark") => {
                out.push_str(&format!("{stem}Dark.dc.html"));
            }
            _ => out.push_str(href),
        }
        at = start + len;
    }
    out.push_str(&text[at..]);
    Ok(out)
}

