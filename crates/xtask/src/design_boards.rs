//! THE BOARDS' GENERATOR (#1214): `design/mockups/tokens.css`, the parts, the dark twins.
//!
//! A board uses colour only as `var(--role)`. [`css_roles`] is the list of roles, read
//! from `design/tokens.toml` (the redesign sections and `[board]`), with the value each
//! takes in light and in dark. Dark is designed there, never derived.

use std::fmt::Write as _;

use centraid_design::tokens::{Accent, Tokens};

/// One colour role as the boards name it: `--name`, with a value per scheme.
#[derive(Debug, Clone, Eq, PartialEq)]
pub struct CssRole {
    pub name: String,
    pub light: String,
    pub dark: String,
}

fn kebab(name: &str) -> String {
    name.replace('_', "-")
}

fn accent_roles(out: &mut Vec<CssRole>, name: &str, accent: &Accent) {
    let mut push = |suffix: &str, light: &str, dark: &str| {
        out.push(CssRole {
            name: format!("{name}{suffix}"),
            light: light.to_owned(),
            dark: dark.to_owned(),
        });
    };
    push("", &accent.light, &accent.dark_text);
    push("-fill", &accent.light, &accent.dark_fill);
    if let (Some(tint), Some(dark_tint)) = (&accent.tint, &accent.dark_tint) {
        push("-tint", tint, dark_tint);
    }
    if let Some(tile) = &accent.tile {
        push("-tile", tile, tile);
    }
}

/// Every colour role the boards may name, in the order `tokens.css` writes them.
#[must_use]
pub fn css_roles(tokens: &Tokens) -> Vec<CssRole> {
    let mut out = Vec::new();
    let (l, d) = (&tokens.surface.light, &tokens.surface.dark);
    for (name, light, dark) in [
        ("page", &l.page, &d.page),
        ("plain-page", &l.plain_page, &d.plain_page),
        ("card", &l.card, &d.card),
        ("sheet", &l.sheet, &d.sheet),
        ("sheet-card", &l.sheet_card, &d.sheet_card),
        ("fill", &l.fill, &d.fill),
        ("line", &l.line, &d.line),
        ("border", &l.border, &d.border),
        ("tile", &l.tile, &d.tile),
    ] {
        out.push(CssRole {
            name: format!("surface-{name}"),
            light: light.clone(),
            dark: dark.clone(),
        });
    }
    let (l, d) = (&tokens.text.light, &tokens.text.dark);
    for (name, light, dark) in [
        ("ink", &l.ink, &d.ink),
        ("body", &l.body, &d.body),
        ("meta", &l.meta, &d.meta),
    ] {
        out.push(CssRole {
            name: format!("text-{name}"),
            light: light.clone(),
            dark: dark.clone(),
        });
    }
    accent_roles(&mut out, "shell", &tokens.shell);
    for (id, accent) in &tokens.app {
        accent_roles(&mut out, &format!("app-{id}"), accent);
    }
    for (id, accent) in &tokens.state {
        accent_roles(&mut out, &format!("state-{id}"), accent);
    }
    for (id, value) in &tokens.list {
        out.push(CssRole {
            name: format!("list-{id}"),
            light: value.clone(),
            dark: value.clone(),
        });
    }
    for (id, value) in &tokens.brand {
        out.push(CssRole {
            name: format!("brand-{id}"),
            light: value.clone(),
            dark: value.clone(),
        });
    }
    for (id, role) in &tokens.board {
        out.push(CssRole {
            name: kebab(id),
            light: role.light.clone(),
            dark: role.dark.clone(),
        });
    }
    out
}

/// `design/mockups/tokens.css`: light on `:root`, dark on `[data-theme="dark"]`.
#[must_use]
pub fn tokens_css(tokens: &Tokens) -> String {
    let roles = css_roles(tokens);
    let mut out = String::from(
        "/* Generated by `cargo xtask design` from design/tokens.toml. Never edit. */\n",
    );
    for (selector, scheme, dark) in [
        (":root", "light", false),
        ("[data-theme=\"dark\"]", "dark", true),
    ] {
        let _ = writeln!(out, "{selector} {{\n  color-scheme: {scheme};");
        for role in &roles {
            let value = if dark { &role.dark } else { &role.light };
            let _ = writeln!(out, "  --{}: {value};", role.name);
        }
        out.push_str("}\n");
    }
    out
}

