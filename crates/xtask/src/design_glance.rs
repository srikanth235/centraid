//! AGENDA'S STATIC WORDS FOR THE PLATFORM, LOWERED NATIVELY (#1173, wave 3).
//!
//! A widget's gallery name, an App Intent's title, a Siri phrase and an Android
//! shortcut's label are read by the operating system before any code runs, so
//! they cannot travel in a view state. Their one source is the Rust catalogue,
//! `crates/screens/src/strings/agenda_glance.rs`; this module reads that file's
//! `catalog!` block with the same strictness as the kit's words
//! ([`crate::design_words`]) and writes:
//!
//! - `mobile/iosApp/Design/GlanceWords.swift`: `GlanceWords`, the static words;
//! - `mobile/iosApp/Design/AgendaShortcuts.swift`: the `AppShortcutsProvider`,
//!   generated because a Siri phrase must be a string literal;
//! - `mobile/androidApp/src/main/res/values/glance_strings.xml`: the same words
//!   as string resources, for the manifest, the appwidget-provider XML and
//!   `shortcuts.xml`.
//!
//! The per-snapshot words (the labels inside the widgets' document) are not
//! here: they travel in the document, in the device's locale.

use std::collections::BTreeMap;

use anyhow::Result;

use crate::design_words::{lookup, quote, read_catalog, slotted};

/// The Rust catalogue the words are read from.
pub const GLANCE_SOURCE: &str = "crates/screens/src/strings/agenda_glance.rs";

/// Member name to the Rust key, for every static word that is not a Siri
/// phrase. Exactly what a platform file names; a word nothing names stays
/// Rust's alone.
const CONSTANTS: [(&str, &str); 9] = [
    ("INTENT_ADD_TITLE", "intent_add_title"),
    ("INTENT_ADD_TITLE_PARAMETER", "intent_add_title_parameter"),
    ("INTENT_NEXT_TITLE", "intent_next_title"),
    ("SHORTCUT_ADD_LONG", "shortcut_add_long"),
    ("SHORTCUT_ADD_SHORT", "shortcut_add_short"),
    (
        "WIDGET_REMINDERS_DESCRIPTION",
        "widget_reminders_description",
    ),
    ("WIDGET_REMINDERS_NAME", "widget_reminders_name"),
    ("WIDGET_UP_NEXT_DESCRIPTION", "widget_up_next_description"),
    ("WIDGET_UP_NEXT_NAME", "widget_up_next_name"),
];

/// The two Siri phrases, each with the one slot the platform fills.
const ADD_PHRASE: &str = "intent_add_phrase";
const NEXT_PHRASE: &str = "intent_next_phrase";
const APP_SLOT: &str = "app";

/// The static words the shells carry.
#[derive(Debug, PartialEq, Eq)]
pub struct GlanceWords {
    /// `(member name, text)` in table order.
    pub constants: Vec<(String, String)>,
    /// "Add a reminder in {app}".
    pub add_phrase: String,
    /// "What's next in {app}".
    pub next_phrase: String,
}

impl GlanceWords {
    fn constant(&self, name: &str) -> &str {
        self.constants
            .iter()
            .find(|(member, _)| member == name)
            .map_or("", |(_, text)| text.as_str())
    }
}

/// Resolve the words from the catalogue's source text.
pub fn resolve(source: &str) -> Result<GlanceWords> {
    let words: BTreeMap<String, String> = read_catalog(source, true)?;
    let mut constants = Vec::new();
    for (name, key) in CONSTANTS {
        constants.push((name.to_owned(), lookup(&words, key, GLANCE_SOURCE)?));
    }
    Ok(GlanceWords {
        constants,
        add_phrase: slotted(
            lookup(&words, ADD_PHRASE, GLANCE_SOURCE)?,
            APP_SLOT,
            ADD_PHRASE,
        )?,
        next_phrase: slotted(
            lookup(&words, NEXT_PHRASE, GLANCE_SOURCE)?,
            APP_SLOT,
            NEXT_PHRASE,
        )?,
    })
}

fn header(comment: &str, lines: &[&str]) -> Vec<String> {
    let mut out = vec![
        format!("{comment} GENERATED by `cargo xtask design` from `{GLANCE_SOURCE}`."),
        format!("{comment} Do not edit: change the Rust catalogue."),
        comment.to_owned(),
    ];
    out.extend(
        lines
            .iter()
            .map(|line| format!("{comment} {line}").trim_end().to_owned()),
    );
    out
}

/// `GlanceWords.swift`.
#[must_use]
pub fn swift_words(words: &GlanceWords) -> String {
    let mut lines = header(
        "//",
        &[
            "The names the platform reads before any code runs: widget gallery",
            "entries, intent titles, shortcut labels (#1173). The words inside a widget",
            "travel in its snapshot document, finished in the device's locale. The gate's",
            "`design` step regenerates this file and fails on any difference.",
        ],
    );
    lines.extend([
        String::new(),
        "import Foundation".to_owned(),
        String::new(),
        "public enum GlanceWords {".to_owned(),
    ]);
    for (name, text) in &words.constants {
        lines.push(format!("    public static let {name} = {}", quote(text)));
    }
    lines.extend(["}".to_owned(), String::new()]);
    lines.join("\n")
}

/// A Siri phrase as a Swift string literal: the text quoted, and `{app}` the
/// platform's own interpolation of the app's name.
fn swift_phrase(phrase: &str) -> String {
    let parts: Vec<String> = phrase
        .split("{app}")
        .map(|part| {
            let quoted = quote(part);
            quoted[1..quoted.len() - 1].to_owned()
        })
        .collect();
    format!("\"{}\"", parts.join("\\(.applicationName)"))
}

/// `AgendaShortcuts.swift`.
#[must_use]
pub fn swift_shortcuts(words: &GlanceWords) -> String {
    let mut lines = header(
        "//",
        &[
            "Siri's phrases for Agenda (#1173). A phrase must be a string literal, which",
            "is why this file is generated and not read from `GlanceWords` at run time:",
            "`{app}` in the catalogue is the platform's `\\(.applicationName)`. The intent",
            "types are `AddReminderIntent` and `WhatsNextIntent`, written in",
            "`Sources/Agenda/Glance/`.",
            "",
            "`systemImageName` is an SF Symbol shown only in the Shortcuts app, the one",
            "place an SF Symbol name is acceptable: no view draws it. The gate's `design`",
            "step regenerates this file and fails on any difference.",
        ],
    );
    let entry = |intent: &str, phrase: &str, title: &str, symbol: &str| {
        vec![
            "        AppShortcut(".to_owned(),
            format!("            intent: {intent}(),"),
            format!("            phrases: [{}],", swift_phrase(phrase)),
            format!("            shortTitle: {},", quote(title)),
            format!("            systemImageName: {}", quote(symbol)),
            "        )".to_owned(),
        ]
    };
    lines.extend([
        String::new(),
        "import AppIntents".to_owned(),
        String::new(),
        "struct AgendaShortcuts: AppShortcutsProvider {".to_owned(),
        "    static var appShortcuts: [AppShortcut] {".to_owned(),
    ]);
    lines.extend(entry(
        "AddReminderIntent",
        &words.add_phrase,
        words.constant("INTENT_ADD_TITLE"),
        "plus.circle",
    ));
    lines.extend(entry(
        "WhatsNextIntent",
        &words.next_phrase,
        words.constant("INTENT_NEXT_TITLE"),
        "calendar",
    ));
    lines.extend(["    }".to_owned(), "}".to_owned(), String::new()]);
    lines.join("\n")
}

/// An Android string resource's text: XML-escaped, then the characters
/// `aapt` reads specially (a quote, a backslash, a leading `@` or `?`).
fn android_text(text: &str) -> String {
    let mut out = String::new();
    for (at, c) in text.chars().enumerate() {
        match c {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '\\' => out.push_str("\\\\"),
            '\'' => out.push_str("\\'"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '@' | '?' if at == 0 => {
                out.push('\\');
                out.push(c);
            }
            other => out.push(other),
        }
    }
    out
}

/// `glance_strings.xml`.
#[must_use]
pub fn android_xml(words: &GlanceWords) -> String {
    let mut out = String::from("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<!--\n");
    out.push_str(&format!(
        "  GENERATED by `cargo xtask design` from `{GLANCE_SOURCE}`. Do not edit.\n\n"
    ));
    out.push_str("  The names the platform reads before any code runs: the manifest, the\n");
    out.push_str("  appwidget-provider XML and shortcuts.xml (#1173). The words inside a widget\n");
    out.push_str("  travel in its snapshot document.\n-->\n<resources>\n");
    for (name, text) in &words.constants {
        out.push_str(&format!(
            "    <string name=\"glance_{}\">{}</string>\n",
            name.to_ascii_lowercase(),
            android_text(text)
        ));
    }
    out.push_str("</resources>\n");
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn source() -> String {
        let mut text = String::from("catalog! {\n");
        for (_, key) in CONSTANTS {
            text.push_str(&format!("    plain {key} = (\"W {key}\", \"x\");\n"));
        }
        text.push_str("    plain intent_add_phrase = (\"Add in {app}\", \"x\");\n");
        text.push_str("    plain intent_next_phrase = (\"Next in {app}\", \"x\");\n}\n");
        text
    }

    #[test]
    fn a_word_the_catalogue_lacks_is_named() {
        let error = resolve("catalog! {\n}\n").expect_err("refused");
        assert!(error.to_string().contains("`intent_add_title`"), "{error}");
    }

    #[test]
    fn a_phrase_without_its_slot_is_refused() {
        let text = source().replace("Add in {app}", "Add in the app");
        let error = resolve(&text).expect_err("no {app}");
        assert!(error.to_string().contains("{app}"), "{error}");
    }

    #[test]
    fn an_unparseable_row_is_an_error() {
        let text = source().replace("plain intent_add_title = (", "plain intent_add_title = (\n");
        assert!(resolve(&text).is_err());
    }

    #[test]
    fn a_siri_phrase_is_a_literal_with_the_platforms_app_name() {
        assert_eq!(
            swift_phrase("Add a reminder in {app}"),
            "\"Add a reminder in \\(.applicationName)\""
        );
        assert_eq!(
            swift_phrase("Say \"hi\" in {app}"),
            "\"Say \\\"hi\\\" in \\(.applicationName)\""
        );
    }

    #[test]
    fn the_shortcuts_file_lists_both_intents_with_their_literals() {
        let words = resolve(&source()).expect("resolves");
        let text = swift_shortcuts(&words);
        assert!(text.contains("struct AgendaShortcuts: AppShortcutsProvider"));
        assert!(text.contains("intent: AddReminderIntent(),"));
        assert!(text.contains("intent: WhatsNextIntent(),"));
        assert!(text.contains("phrases: [\"Add in \\(.applicationName)\"],"));
        assert!(text.contains("shortTitle: \"W intent_next_title\","));
        assert!(text.contains("systemImageName: \"plus.circle\""));
        assert!(text.contains("systemImageName: \"calendar\""));
    }

    #[test]
    fn android_strings_are_escaped_for_aapt_and_xml() {
        assert_eq!(
            android_text("What's <new> & \"more\""),
            "What\\'s &lt;new&gt; &amp; \\\"more\\\""
        );
        assert_eq!(android_text("@home"), "\\@home");
    }

    #[test]
    fn the_committed_catalogue_resolves_every_member() {
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
        let text = std::fs::read_to_string(root.join(GLANCE_SOURCE)).expect("reads");
        let words = resolve(&text).expect("resolves");
        assert_eq!(words.constants.len(), CONSTANTS.len());
        let xml = android_xml(&words);
        assert!(xml.contains("<string name=\"glance_widget_up_next_name\">Up next</string>"));
        assert!(xml.contains("What\\'s next today"));
        assert!(swift_words(&words).contains("WIDGET_UP_NEXT_NAME = \"Up next\""));
        assert!(
            !xml.contains("{app}"),
            "phrases are the shortcuts file's alone"
        );
    }
}
