import Foundation
import SwiftProtobuf

import CentraidShared

/// The thin decoders between a screen's bytes and its SwiftUI view
/// (#1020, D-1020-E3; wired in #1025 S5, lane L5).
///
/// **One file, three screens, no logic.** Each of these takes the `bytes` the
/// shared module published and exposes exactly what its view renders. Every
/// one of them keeps the three-state read law as a Swift `enum` with three
/// cases, which is how the law survives the language boundary: Swift's
/// `Optional` would collapse two of the three, exactly as Kotlin's nullable
/// would.
///
/// The `Centraid_Screen_V1_*` types are generated by `protoc-gen-swift` from
/// `crates/api-proto/proto` — the same tree Wire reads on the Kotlin side, and
/// the reason `buf.gen.yaml` names SwiftProtobuf as this lane's plugin. They
/// are generated now (`Sources/Generated`), so the `unwired()` hand-off that
/// stood here is gone and these decode for real.
///
/// **A DECODE THAT FAILS RENDERS THE INITIAL STATE, NOT AN EMPTY ONE.** The
/// initial state of every screen is `loading`, which is the honest thing to
/// draw when the bytes have not arrived: `Data()` is what these views hold
/// before the bridge has published anything, and an empty `.data` case in its
/// place would be a screen claiming an empty vault before it had read one.

// `ScreenContent` lives in `Kit/ScreenContent.swift` (K5).

struct BandView: Hashable {
    let label: String
    let event: Data
    /// The catalog mark a drawn band shows above the label; empty draws none.
    var iconKey: String = ""
    /// Whether this is the destination on screen — read off the state, never
    /// written down by the view that draws it.
    var selected: Bool = false
    /// The destination's key, when the band's flows tap it by that and not by
    /// its label (`agenda-band-todo` for a "To-do" label); empty falls back to
    /// the lowercased label.
    var key: String = ""
}

struct NoteDraftView {
    let title: String
    let body: String
    let pinned: Bool
    let saveFailure: String?
}

struct NotesEditorStateView {
    let data: Data

    private var state: Centraid_Screen_V1_NotesEditorState {
        (try? Centraid_Screen_V1_NotesEditorState(serializedBytes: data)) ?? .init()
    }

    var content: ScreenContent<NoteDraftView> {
        switch state.content {
        case let .failure(failure):
            return .failure(failure.sentence, failure.remedy)
        case let .draft(draft):
            return .data(
                NoteDraftView(
                    title: draft.title,
                    body: draft.body,
                    pinned: draft.pinned,
                    // THE SAVE'S SENTENCE IS NOT THE READ'S. It rides on the
                    // draft and the view draws it OVER the words, never instead
                    // of them — a refused save that replaced the editor would
                    // have thrown away the only copy.
                    saveFailure: draft.hasSaveFailure ? draft.saveFailure.sentence : nil
                )
            )
        case let .loading(loading):
            return .loading(loading.firstLoad)
        case .none:
            return .loading(true)
        }
    }

    /// THE AUTOSAVE, AS THE MACHINE HOLDS IT — `AutosaveStatus` draws it.
    ///
    /// The explicit Save went with #1015 D3 (close = done), and with it the
    /// five-word `saveLabel` over `save`, including its `.queued` "Waiting for
    /// your gateway", which nothing under autosave produces (K5).
    var autosave: Centraid_Screen_V1_Autosave { state.autosave }

    var pinEvent: Data {
        var event = Centraid_Screen_V1_NotesEditorEvent()
        event.pin = .init()
        return event.encoded
    }

    /// Open (and, from a failure, re-open) the editor on one note.
    static func openedEvent(_ noteIdentifier: String) -> Data {
        var event = Centraid_Screen_V1_NotesEditorEvent()
        event.opened = .with { $0.noteID = noteIdentifier }
        return event.encoded
    }

    /// A TITLE THE MEMBER TYPED (#1025 S5).
    ///
    /// This used to re-assert the title the state already held, with a comment
    /// saying so plainly: a state-derived event cannot carry text that is in a
    /// field rather than in the state, and the view bound its `TextField` to
    /// `.constant`, so there was nothing to carry. The view now owns its typed
    /// text (`NotesEditorView`'s `@State`), which is the only place a keystroke
    /// exists before it is saved, and hands it here.
    ///
    /// An edit moves the draft to dirty; the machine's autosave writes it after
    /// its debounce (`AutosaveLaw`, 900 ms, one invoke key per edit sequence),
    /// so a member typing a paragraph fills their outbox with one revision and
    /// not a hundred.
    static func titleEvent(_ title: String) -> Data {
        var event = Centraid_Screen_V1_NotesEditorEvent()
        event.title = .with { $0.title = title }
        return event.encoded
    }

    static func bodyEvent(_ body: String) -> Data {
        var event = Centraid_Screen_V1_NotesEditorEvent()
        event.body = .with { $0.body = body }
        return event.encoded
    }
}

// ONE `encoded`, FOR EVERY SCREEN IN THIS TARGET.
//
// Three views each grew a `private extension SwiftProtobuf.Message` with this
// same body, and a fourth used `.encoded` without declaring one — which does
// not compile, because a fileprivate helper is not visible from the file that
// needed it. Same shape as the four cell renderers: written once is written
// once.
extension SwiftProtobuf.Message {
    /// The bytes that cross back into `CentraidShared`.
    ///
    /// A serialisation that throws yields EMPTY bytes rather than a crash, and
    /// the shared module decodes those as a message with no `kind` set, which
    /// every reducer's `else` branch already answers with `Step(state)` — a tap
    /// that does nothing rather than a shell that dies on one.
    var encoded: Data { (try? serializedData()) ?? Data() }
}
