events = []
_busy = []  # (start, end) datetimes of everything placed


def dtm(date, hhmm):
    h, m = hhmm.split(":")
    return dt.datetime(date.year, date.month, date.day, int(h), int(m))


def add_event(key, name, start, end, **kw):
    """Place an event unless it overlaps one already placed (a cancelled or trashed event still counts,
    because the vault creates it live). True when placed."""
    for s, e in _busy:
        if start < e and s < end:
            return False
    _busy.append((start, end))
    row = {"key": key, "name": name, "start": start.strftime("%Y-%m-%dT%H:%M"),
           "end": end.strftime("%Y-%m-%dT%H:%M")}
    created = max(EPOCH_DT, start - dt.timedelta(days=4, hours=2))
    if created.date() > TODAY_D:
        created = dt.datetime.combine(TODAY_D, dt.time(8, 0)) - dt.timedelta(days=(start.date() - TODAY_D).days % 9)
    row["created"] = created.strftime("%Y-%m-%dT%H:%M")
    row.update(kw)
    events.append(row)
    return True


def series(prefix, name, first, last, weekdays, start, minutes, attendees=(), skip=None, cancel_pct=3,
           description=None, step=7):
    """Occurrences every `step` days from the first listed weekday on/after `first`; `skip(d)` drops a date,
    `cancel_pct` of the past ones are cancelled."""
    wd = [weekdays] if isinstance(weekdays, int) else list(weekdays)
    assert step == 7 or len(wd) == 1, "a stepped series has one weekday"
    n = 0
    base = first if step == 7 else next_weekday(first, wd[0])
    while base <= last:
        for w in wd:
            d = next_weekday(base, w) if step == 7 else base
            if d > last or d < first:
                continue
            if skip and skip(d):
                continue
            s = dtm(d, start)
            e = s + dt.timedelta(minutes=minutes)
            extra = {}
            if attendees:
                extra["attendees"] = list(attendees)
            if description and R.chance(15):
                extra["description"] = description
            if d < TODAY_D and R.chance(cancel_pct):
                extra["cancelled"] = True
            if add_event(f"{prefix}_{d.strftime('%y%m%d')}", name, s, e, **extra):
                n += 1
        base += dt.timedelta(days=step)
    return n


def monthly(prefix, name, first_month, last_month, nth_weekday, weekday, start, minutes, attendees=(), skip=None,
            cancel_pct=3, description=None):
    """One occurrence a month on the nth (1-based) `weekday`; the months run from (y, m) to (y, m)."""
    y, m = first_month
    n = 0
    while (y, m) <= last_month:
        d = next_weekday(dt.date(y, m, 1), weekday) + dt.timedelta(days=7 * (nth_weekday - 1))
        if EPOCH_D < d <= END_D and not (skip and skip(d)):
            s = dtm(d, start)
            e = s + dt.timedelta(minutes=minutes)
            extra = {}
            if attendees:
                extra["attendees"] = list(attendees)
            if description and R.chance(20):
                extra["description"] = description
            if d < TODAY_D and R.chance(cancel_pct):
                extra["cancelled"] = True
            if add_event(f"{prefix}_{d.strftime('%y%m%d')}", name, s, e, **extra):
                n += 1
        m += 1
        if m > 12:
            y, m = y + 1, 1
    return n


