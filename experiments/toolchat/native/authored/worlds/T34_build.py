def done_stamp(due, hour=None, late_days=0):
    d = dt.date.fromisoformat(due[:10]) - dt.timedelta(days=R.int(2)) + dt.timedelta(days=late_days)
    return f"{iso(d)}T{(hour if hour is not None else 8 + R.int(13)):02d}:{R.int(6) * 10:02d}"


def recurring(prefix, name, first, last, step_days=None, monthly_day=None, every_months=1, lst=None, hour="19:00",
              miss_pct=1, **kw):
    """Instances due on a fixed weekly step or a fixed day of the month; every past one is completed
    (a stray 1 percent forgotten), the next one is open, and later ones are not made yet."""
    dates = []
    if step_days:
        dates = list(days(first, last, step_days))
    else:
        y, m = first.year, first.month
        while dt.date(y, m, monthly_day) <= last:
            dates.append(dt.date(y, m, monthly_day))
            m += every_months
            while m > 12:
                m -= 12
                y += 1
    open_given = False
    count = 0
    for d in dates:
        due = f"{iso(d)}T{hour}"
        row = {}
        if d < TODAY_D - dt.timedelta(days=1):
            if not R.chance(miss_pct):
                row["completed"] = done_stamp(due, hour=int(hour[:2]) - R.int(3) if hour != "00:00" else None)
        elif open_given:
            continue
        else:
            open_given = True
        add_task(f"{prefix}_{d.strftime('%y%m%d')}", name, due, lst, **row, **kw)
        count += 1
    return count


