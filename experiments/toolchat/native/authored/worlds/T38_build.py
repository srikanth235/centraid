def check(w):
    """Keys unique and snake_case, every reference resolves, no two events overlap, every locker type
    present, the shape of the world matches what the brief asks for."""
    keys = {}
    for kind, rows in w.items():
        if not isinstance(rows, list):
            continue
        for r in rows:
            if "key" in r:
                assert r["key"] not in keys, f"duplicate key {r['key']}"
                assert r["key"] == r["key"].lower() and " " not in r["key"], r["key"]
                assert len(r["key"]) <= 30, r["key"]
                keys[r["key"]] = kind
    keys["me"] = "people"

    def need(key, kind):
        assert keys.get(key) == kind, f"{key} is not a {kind}"

    for g in w["groups"]:
        [need(m, "people") for m in g["members"]]
        assert len(set(g["members"])) == len(g["members"]), g["key"]
    for e in w["expenses"]:
        need(e["group"], "groups")
        [need(m, "people") for m in e["split"]]
        need(e["paid_by"], "people")
        members = set(next(g["members"] for g in w["groups"] if g["key"] == e["group"])) | {"me"}
        assert set(e["split"]) | {e["paid_by"]} <= members, f"expense outside its group: {e['name']}"
    for t in w["tasks"]:
        if "parent" in t:
            need(t["parent"], "tasks")
        if "list" in t:
            need(t["list"], "lists")
    for n in w["notes"]:
        if "notebook" in n:
            need(n["notebook"], "notebooks")
    for d in w["documents"]:
        if "folder" in d:
            need(d["folder"], "folders")
    for p in w["photos"]:
        [need(a, "albums") for a in p.get("albums", [])]
        [need(q, "people") for q in p.get("people", [])]
        assert len(set(p.get("albums", []))) == len(p.get("albums", [])), p["key"]
    for d in w["debts"]:
        need(d["person"], "people")
    for e in w["events"]:
        [need(a, "people") for a in e.get("attendees", [])]
    for ln in w["links"]:
        assert ln["from"] in keys and ln["to"] in keys, ln
    names = [g["name"] for g in w["groups"]] + [n["name"] for n in w["notebooks"]] + [a["name"] for a in w["albums"]]
    assert len(names) == len(set(names)), "group/notebook/album names must be unique"
    spans = sorted((e["start"], e.get("end", e["start"]), e["key"]) for e in w["events"])
    for (s1, e1, k1), (s2, e2, k2) in zip(spans, spans[1:]):
        assert e1 <= s2, f"events overlap: {k1} and {k2}"
    assert len({r["type"] for r in w["locker"]}) == 15
    assert len({p["name"] for p in w["people"]}) == len(w["people"]), "duplicate person names"
    assert w["me"] and w["today"]
    # the shape of the large world
    n = {k: len(v) for k, v in w.items() if isinstance(v, list)}
    assert n["people"] >= 160, n["people"]
    assert 600 <= n["events"] <= 900, n["events"]
    assert 700 <= n["tasks"] <= 900, n["tasks"]
    assert n["photos"] == 300 and n["albums"] == 12, (n["photos"], n["albums"])
    assert 40 <= n["debts"] <= 50 and 40 <= n["expenses"] <= 60
    done = sum(1 for t in w["tasks"] if t.get("completed"))
    assert done / n["tasks"] >= 0.7, "tasks should be mostly completed"
    # long recurring history: some names carry 20 to 150 copies
    from collections import Counter
    ev_names = Counter(e["name"] for e in w["events"])
    task_names = Counter(t["name"] for t in w["tasks"])
    assert any(20 <= c <= 150 for c in ev_names.values()) and max(ev_names.values()) <= 150, ev_names.most_common(3)
    assert any(20 <= c <= 150 for c in task_names.values()) and max(task_names.values()) <= 150, task_names.most_common(3)
    # the confusable first names
    firsts = Counter(p["name"].split()[0] for p in w["people"] if "trashed" not in p)
    clusters = {f: c for f, c in firsts.items() if c > 1}
    assert clusters == {"Omar": 2, "Layla": 3, "Yousef": 2}, clusters
    # trashed rows of every trashable kind, some inside the restore window and some past it
    for kind in ("people", "events", "tasks", "notes", "documents", "photos", "locker"):
        stamps = [r["trashed"] for r in w[kind] if "trashed" in r]
        assert stamps, f"no trashed {kind}"
        age = [(dt.datetime.fromisoformat(w["today"]) - dt.datetime.fromisoformat(s)).days for s in stamps]
        assert any(a <= 30 for a in age) and any(a > 30 for a in age), f"trashed {kind} window mix: {age}"
    assert any(e.get("cancelled") for e in w["events"])
    assert any(t.get("status") == "cancelled" for t in w["tasks"])
    assert any(not [e for e in w["expenses"] if e["group"] == g["key"]] for g in w["groups"]), "an empty group"
    assert any(f["key"] not in {d.get("folder") for d in w["documents"]} for f in w["folders"]), "an empty folder"
    assert sum(1 for d in w["documents"] if any(y in d["name"] for y in ("2024", "2025", "2026", "2027"))) >= 90


