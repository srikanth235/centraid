events = []
_busy = []  # (start, end) datetimes of everything placed


def dtm(date, hhmm):
    h, m = hhmm.split(":")
    return dt.datetime(date.year, date.month, date.day, int(h), int(m))


def add_event(key, name, start, end, **kw):
    """Place an event unless it overlaps one already placed (a cancelled or trashed event still counts,
    because the vault creates it live). True when placed."""
    for s, e in _busy:
        if start < e and s < end:
            return False
    _busy.append((start, end))
    row = {"key": key, "name": name, "start": start.strftime("%Y-%m-%dT%H:%M"),
           "end": end.strftime("%Y-%m-%dT%H:%M")}
    created = max(dt.datetime.combine(EPOCH_D, dt.time(9, 0)), start - dt.timedelta(days=4, hours=2))
    if created.date() > TODAY_D:
        created = dt.datetime.combine(TODAY_D, dt.time(8, 0)) - dt.timedelta(days=(start.date() - TODAY_D).days % 9)
    row["created"] = created.strftime("%Y-%m-%dT%H:%M")
    row.update(kw)
    events.append(row)
    return True


def series(prefix, name, first, last, weekday, start, minutes, attendees=(), skip=None, cancel_pct=3,
           description=None, step=7):
    """Weekly (or every `step` days) occurrences from the first `weekday` on/after `first`; `skip(d)`
    drops a date, `cancel_pct` of the rest are cancelled."""
    d = next_weekday(first, weekday)
    n = 0
    while d <= last:
        if not (skip and skip(d)):
            s = dtm(d, start)
            e = s + dt.timedelta(minutes=minutes)
            extra = {}
            if attendees:
                extra["attendees"] = list(attendees)
            if description and R.chance(15):
                extra["description"] = description
            if R.chance(cancel_pct) and d < TODAY_D:
                extra["cancelled"] = True
            if add_event(f"{prefix}_{d.strftime('%y%m%d')}", name, s, e, **extra):
                n += 1
        d += dt.timedelta(days=step)
    return n


