class Lcg:
    """Deterministic pseudo-random numbers, independent of the Python version."""

    def __init__(self, seed):
        self.x = seed

    def next(self):
        self.x = (self.x * 1103515245 + 12345) % 2147483648
        return self.x >> 8

    def int(self, n):
        return self.next() % n

    def pick(self, seq):
        return seq[self.int(len(seq))]

    def chance(self, pct):
        return self.int(100) < pct


