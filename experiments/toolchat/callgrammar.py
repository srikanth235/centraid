"""`agent.py --constrain`: the call line, decoded under the tool language's grammar.

    python callgrammar.py vocab --onto onto.json [--tool-loop BIN --worlds DIR] --out callvocab.json
    python callgrammar.py lark  [--vocab callvocab.json] [--handles 1,2,5]      # print the grammar
    python callgrammar.py prove --calls calls.jsonl --tokenizer CKPT [--vocab …] # the soundness gate

THE VOCABULARY IS GENERATED (`vocab`), never typed here. Its sources are the runtime's own:

* `crates/candidates/src/canon_terminals.rs` — the lexicon the runtime's parser (`canon.rs`)
  reads: kind words and their entities, the global FIELD_WORDS, the verb classes, the egress
  verbs, window phrases, weekdays, decline reasons (itself generated by
  `crates/evalsuite/grammar/derive/emit.py` from derived.json + terminals.json);
* `onto.json` — the per-entity column table `crates/candidates/build.rs` derives from the same
  derived.json for the runtime's ranker;
* `crates/candidates/src/exec.rs` — the commands the executor has a body for (body()) and the
  fields it answers without a column (identity_field / label_field / date_field);
* `crates/candidates/src/tools.rs` read_facts — the facts a result line is read with;
* the reader extras the runtime's rows actually carry (`tool-loop serve` + `peek` over worlds).

A kind's fields are FIELD_WORDS ∩ (its columns ∪ executor aliases ∪ read facts ∪ reader extras
∪ `label`, `deleted_at`). A filter, an aggregate or a projection over a set headed by a kind may
name only that kind's fields; over `things`, a `#n`, `them` or a mixed union, any field in
FIELD_WORDS; `ordered by` takes any FIELD_WORDS field (ordering by an absent field is a no-op
the executor runs, and gold does it). Write verbs: body() commands + verb classes + egress
verbs (which the executor refuses itself). Argument names are open, as the parser has them.

The call language itself is `tools.rs` over `canon.rs`, minus what the harness has retired:
references are `#n` handles (comma lists) and `them` only — no `it`, `that one`, `the other
one`, `the earlier one`, `the last thing I added`, `the Nth one` — and no `same?`, no
`clarify:`. Quoted strings (`called "…"`, `search "…"`, `ask "…"`) are free text.

`--constrain-handles`: `#n` only for the row numbers the conversation has SHOWN (row lines and
link items in the observations), one grammar per distinct set (compiled on demand, cached).

DECODING. Only the CALL is constrained. Under `--think` the reasoning stays free: the mask
switches on once the model has written `</think>`, and the call that follows (after its
"\\n\\n") must parse; the model's end-of-turn token is allowed once it does. Every step where
the mask removed the model's top-1 token is recorded (`events`: what it wanted, what it got,
both probabilities). `soft` mode releases the constraint for the rest of the call when the
best token the grammar allows has probability below `tau` under the model's own distribution:
the model then writes its own line and the runtime answers it (`error: …`, a retry) instead of
a forced, possibly silent, wrong call. Nothing is re-sampled and nothing is rewritten.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, "..", ".."))
SRC = os.path.join(REPO, "crates", "candidates", "src")

# -- the vocabulary (generated) ------------------------------------------------


def _rs(path):
    return open(path, encoding="utf-8").read()


def _fn_body(src, name):
    """the text of `fn name(` up to the next top-level `\\n}`"""
    at = src.index("fn %s(" % name)
    end = src.index("\n}", at)
    return src[at:end]


def _arms(text):
    """(entities, quoted strings of the arm's value) for `"a" | "b" => value,` arms"""
    out = []
    for m in re.finditer(r'((?:"[a-z_.]+"\s*\|\s*)*"[a-z_.]+")\s*=>\s*(.*?)(?=\n\s*(?:"[a-z_.]+"|_)\s*(?:\||=>)|\Z)',
                         text, re.S):
        out.append((re.findall(r'"([a-z_.]+)"', m.group(1)), re.findall(r'"([a-z_]+)"', m.group(2))))
    return out


def terminals(src_dir=SRC):
    """canon_terminals.rs: what the runtime's parser reads"""
    t = _rs(os.path.join(src_dir, "canon_terminals.rs"))
    kinds = dict(re.findall(r'\("([a-z ]+)", \("([a-z_.*]+)", "[a-z*]+"\)\)', t))
    fields = t.split('const FIELD_WORDS: &str = "')[1].split('";')[0].split()
    classes = sorted(set(re.findall(r'^\s+\("([a-z]+)", \[$', t, re.M)))

    def const(name):
        body = t.split("const %s" % name)[1].split("];")[0]
        return re.findall(r'"([^"]+)"', body)
    return {"kinds": kinds, "fields": fields, "classes": classes, "egress": const("EGRESS_VERBS"),
            "windows": const("WINDOW_PHRASES"), "days": const("RELATIVE_DAYS"),
            "reasons": const("DECLINE_REASONS")}


def executor(src_dir=SRC):
    """exec.rs + tools.rs: runnable verbs and the fields answered without a column"""
    e = _rs(os.path.join(src_dir, "exec.rs"))
    body = e[e.index("let body = match verb.as_str() {"):e.index("no body is known for")]
    verbs = set()
    for m in re.finditer(r'^ {8}((?:"[a-z_.]+"\s*\|\s*)*"[a-z_.]+") =>', body, re.M):
        verbs.update(re.findall(r'"([a-z_.]+)"', m.group(1)))
    aliases = {}
    for fn in ("identity_field", "label_field", "date_field"):
        for ents, vals in _arms(_fn_body(e, fn)):
            for ent in ents:
                aliases.setdefault(ent, set()).update(vals)
    tl = _rs(os.path.join(src_dir, "tools.rs"))
    facts = {}
    rf = _fn_body(tl, "read_facts")
    rf = rf[rf.index("match row.entity.as_str()"):rf.index("_ => &[]")]
    for ents, vals in _arms(rf):
        for ent in ents:
            facts.setdefault(ent, set()).update(vals)
    return {"verbs": sorted(verbs), "aliases": {k: sorted(v) for k, v in aliases.items()},
            "facts": {k: sorted(v) for k, v in facts.items()}}


def reader_extras(tool_loop, worlds, kinds):
    """the extra keys the runtime's rows carry, per entity: `peek` every kind in every world"""
    import subprocess
    out = {}
    for w in worlds:
        p = subprocess.Popen([tool_loop, "serve", "--world", "spec:" + w], stdin=subprocess.PIPE,
                             stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, text=True, bufsize=1)

        def ask(m):
            p.stdin.write(json.dumps(m) + "\n")
            p.stdin.flush()
            return json.loads(p.stdout.readline())
        ask({"op": "open"})
        for k in sorted(kinds):
            for q in ("show (%s)" % k, "show (%s) that (deleted_at is not null)" % k):
                for row in ask({"op": "peek", "line": q}).get("rows", []):
                    out.setdefault(row["entity"], set()).update(
                        x for x in row.get("extra", {}) if re.fullmatch(r"[a-z_][a-z0-9_]*", x))
        p.stdin.write(json.dumps({"op": "quit"}) + "\n")
        p.stdin.close()
        p.wait()
    return {k: sorted(v) for k, v in out.items()}


EVERY_ROW = ["label", "deleted_at"]


def build_vocab(onto, tool_loop=None, worlds=()):
    t, x = terminals(), executor()
    extras = reader_extras(tool_loop, worlds, t["kinds"]) if tool_loop and worlds else {}
    fw = set(t["fields"])
    per = {}
    for word, ent in sorted(t["kinds"].items()):
        if ent == "*":
            continue
        f = set(onto["fields"].get(ent, {})) | set(x["aliases"].get(ent, [])) \
            | set(x["facts"].get(ent, [])) | set(extras.get(ent, [])) | set(EVERY_ROW)
        per[word] = sorted(f & fw)
    return {
        "$sources": ["crates/candidates/src/canon_terminals.rs (the runtime parser's lexicon)",
                     "onto.json (build.rs, per-entity columns)",
                     "crates/candidates/src/exec.rs body()/identity_field/label_field/date_field",
                     "crates/candidates/src/tools.rs read_facts",
                     "tool-loop serve peek extras over %d worlds" % len(worlds)],
        "kinds": per,
        "fields": sorted(fw),
        "verbs": sorted(set(x["verbs"]) | set(t["classes"]) | set(t["egress"])),
        "windows": t["windows"], "days": t["days"], "reasons": t["reasons"],
    }


def load_vocab(path=None):
    for p in ([path] if path else []) + [os.path.join(HERE, "callvocab.json")]:
        if p and os.path.exists(p):
            return json.load(open(p))
    raise SystemExit("callgrammar: no callvocab.json (run `callgrammar.py vocab`)")


# -- the grammar -------------------------------------------------------------

def lit(s):
    return json.dumps(s)


def alt(words):
    """longest first: a reader that stops at a prefix never wins"""
    return " | ".join(lit(w) for w in sorted(set(words), key=lambda w: (-len(w), w)))


def ident(kind):
    return re.sub(r"[^a-z0-9]+", "_", kind)


def lark(v, handles=None):
    """The call grammar over vocabulary `v`. `handles`: None, any `#n`; else the
    collection of row numbers a `#n` may name (empty: no `#n` at all)."""
    typed = sorted(v["kinds"])
    g = []
    r = g.append
    r("%llguidance {}")
    r("start: PRE call")
    r(r"PRE: /[ \n]*/")
    r('call: "done" | "nothing" | refuse | "search " STRING | "get " handle | "ask " STRING'
      ' | "show " set_all | "answer " (set_all | value_all) | value_all | cmds')
    r('refuse: "refuse" osp ":" osp reason')
    r("reason: " + alt(v["reasons"]))
    # -- values: an aggregate or a projection names a field of the set's kind
    vals = ['"count of " set_all', '"balance of " set_all " in " set_all',
            '("sum" | "min" | "max") " " field_any " of " set_any', 'field_any " of " set_any']
    for k in typed:
        i = ident(k)
        vals.append('("sum" | "min" | "max") " " field_%s " of " set_%s' % (i, i))
        vals.append('field_%s " of " set_%s' % (i, i))
    r("value_all: " + " | ".join(vals))
    # -- writes
    r('cmds: cmd (" then " cmd)*')
    r('cmd: verb osp "{" osp (args osp)? "}" (" on " set_all)?')
    r('args: arg (osp "," osp arg)*')
    r('arg: ARGNAME osp ":" osp argval')
    r('argval: "(" osp set_all osp ")" | value_all | literal | DURATION | keyword')
    r("verb: " + alt(v["verbs"]))
    # -- sets: one copy per kind; untyped heads (#n, them, things, mixed unions) take any field
    r("set_all: set_any | " + " | ".join("set_" + ident(k) for k in typed))
    r('conj: " and " | " except "')
    r("post_t: post_u | " + " | ".join("post_" + ident(k) for k in typed))
    r("set_any: post_u | post_t (conj post_t)+")
    r("post_u: prim_u suffix_any*")
    r('prim_u: "(" osp set_any osp ")" | "first " NUMBER " of " set_any | ref'
      ' | "things" (" of " prim_all)?')
    r("prim_all: prim_u | " + " | ".join("prim_" + ident(k) for k in typed))
    r(suffix_rule("any"))
    r(pred_rules("any"))
    r("field_any: " + alt(v["fields"]))
    for k in typed:
        i = ident(k)
        r('set_%s: post_%s (conj post_%s)*' % (i, i, i))
        r('post_%s: prim_%s suffix_%s*' % (i, i, i))
        r('prim_%s: "(" osp set_%s osp ")" | "first " NUMBER " of " set_%s | %s (" of " prim_all)?'
          % (i, i, i, lit(k)))
        r(suffix_rule(i))
        r(pred_rules(i))
        r("field_%s: %s" % (i, alt(v["kinds"][k])))
    r('operand: "(" osp set_all osp ")" | literal | keyword')
    r('keyword: "true" | "false" | "null" | "me"')
    r("cmp: " + alt(["!=", "<=", ">=", "<", "=", ">"]))
    r("kind: " + alt(typed + ["things"]))
    # -- references: #n handles and `them`, nothing else
    r('ref: handle (", " handle)* | "them"')
    r("handle: HANDLE")
    if handles is None:
        r("HANDLE: /#[0-9]+/")
    elif handles:
        r("HANDLE: /#(%s)/" % "|".join(str(n) for n in sorted(set(handles), reverse=True)))
    else:
        r(r'HANDLE: /#[^\x00-\xff]/')   # nothing the model can write: no row shown yet
    # -- windows and dates (canon.rs window() / reldate())
    r('window: "(" osp window osp ")" | DATERANGE | DATETIME | DATE | MONTH'
      ' | "from" osp "(" osp value_all osp ")" " to" osp "(" osp value_all osp ")"'
      ' | "next " NUMBER " " ("months" | "days" | "weeks") | winday | ' + alt(v["windows"]))
    r('winday: ("next " | "last ")? weekday | "the " ORDINAL | "in " DIGITS " days"')
    r("weekday: " + alt(v["days"]))
    r('reldate: (winday | "today" | "tomorrow" | "yesterday") (" at " TIME)?')
    r("literal: STRING | DATERANGE | DATETIME | DATE | MONTH | NUMBER | reldate")
    r('osp: " "?')
    # -- terminals (canon.rs lex(): the numeric family in its order)
    r(r"ARGNAME: /[a-z_][a-z0-9_]*/")
    r(r'STRING: /"([^"\\\n]|\\[^\n])*"/')
    r(r"DATERANGE: /[0-9]{4}-[0-9]{2}-[0-9]{2}\.\.[0-9]{4}-[0-9]{2}-[0-9]{2}/")
    r(r"DATETIME: /[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}(:[0-9]{2}(\.[0-9]+)?)?Z?/")
    r(r"DATE: /[0-9]{4}-[0-9]{2}-[0-9]{2}/")
    r(r"MONTH: /[0-9]{4}-[0-9]{2}/")
    r(r"TIME: /([01][0-9]|2[0-3]):[0-5][0-9]/")
    r(r"DURATION: /[+-][0-9]+[hdm]/")
    r(r"ORDINAL: /[0-9]+(st|nd|rd|th)/")
    r(r"NUMBER: /-?[0-9]+(\.[0-9]+)?/")
    r(r"DIGITS: /[0-9]+/")
    return "\n".join(g) + "\n"


def suffix_rule(i):
    return ('suffix_%s: " called " STRING | " that" osp "(" osp pred_%s osp ")"'
            ' | " during " window | " ordered by " field_any " " ("asc" | "desc")' % (i, i))


def pred_rules(i):
    f = "field_" + i
    return "\n".join([
        'pred_%s: patom_%s ((" and " | " or ") patom_%s)*' % (i, i, i),
        'patom_%s: "not " patom_%s | "(" osp pred_%s osp ")" | "count of " kind osp cmp osp NUMBER'
        ' | "member of " prim_all'
        ' | %s " is " ("not ")? ("null" | "me") | %s " during " window | %s " around " NUMBER'
        ' | %s " contains " STRING | %s " in" osp "(" osp STRING (osp "," osp STRING)* osp ")"'
        ' | %s osp cmp osp (operand | %s)' % (i, i, i, f, f, f, f, f, f, f),
    ])


# -- the row numbers a conversation has shown ----------------------------------

SHOWN = re.compile(r'(?:^|\n)[ \t]*#(\d+) [a-z]|#(\d+) "')


def shown_handles(text):
    """row lines (`#4 task "…"`) and link items (`#7 "…"`) in the observations"""
    return sorted({int(a or b) for a, b in SHOWN.findall(text)})


# -- decoding ----------------------------------------------------------------

THINK_OPEN, THINK_CLOSE = "<think>\n", "</think>"


class Constrainer:
    """One per model: the llguidance tokenizer (built once) and the compiled grammars."""

    def __init__(self, tok, n_vocab, vocab=None, stop_ids=(), handles=False, mode="hard", tau=0.05):
        import llguidance
        import llguidance.hf
        self.llg = llguidance
        self.tok = tok
        self.vocab = vocab if isinstance(vocab, dict) else load_vocab(vocab)
        im_end = tok.convert_tokens_to_ids("<|im_end|>")
        eos = im_end if isinstance(im_end, int) and im_end >= 0 else tok.eos_token_id
        self.lltok = llguidance.hf.from_tokenizer(tok, n_vocab=n_vocab, eos_token=eos)
        self.stop_ids = sorted(set(stop_ids) | {eos})
        self.handles, self.mode, self.tau = handles, mode, tau
        self.base = {}          # grammar key -> a pristine matcher to deep_copy
        self.last = None        # the processor of the latest generate() call
        self.stats = {"steps": 0, "mask_ms": 0.0, "compile_ms": 0.0, "compiles": 0,
                      "overrides": 0, "released": 0, "calls": 0}

    def matcher(self, prompt_text):
        import time
        key = tuple(shown_handles(prompt_text)) if self.handles else None
        if key not in self.base:
            t0 = time.time()
            m = self.llg.LLMatcher(self.lltok, lark(self.vocab, key), log_level=1)
            if m.is_error():
                raise RuntimeError("callgrammar: " + m.get_error())
            self.stats["compile_ms"] += 1000 * (time.time() - t0)
            self.stats["compiles"] += 1
            if len(self.base) > 256:
                self.base.clear()
            self.base[key] = m
        return self.base[key].deep_copy()

    def processor(self, prompt_ids):
        self.stats["calls"] += 1
        self.last = CallProcessor(self, prompt_ids)
        return self.last


class CallProcessor:
    """A transformers LogitsProcessor for one generate() call (batch of one)."""

    def __init__(self, c, prompt_ids):
        self.c = c
        ids = list(prompt_ids)
        self.n_prompt = len(ids)
        self.prompt_text = c.tok.decode(ids, skip_special_tokens=False)
        self.phase = "think" if self.prompt_text.endswith(THINK_OPEN) else "call"
        self.m = self.c.matcher(self.prompt_text) if self.phase == "call" else None
        self.fed = 0
        self.free = False       # soft mode released it, or the matcher refused a token
        self.events = []        # every step the mask changed greedy's choice

    def __call__(self, input_ids, scores):
        import time
        import numpy as np
        import torch
        gen = input_ids[0, self.n_prompt:].tolist()
        if self.phase == "think":
            if THINK_CLOSE not in self.c.tok.decode(gen, skip_special_tokens=False):
                return scores
            self.phase, self.fed = "call", len(gen)
            self.m = self.c.matcher(self.prompt_text)
        if self.free:
            return scores
        for t in gen[self.fed:]:
            if not self.m.consume_token(t):
                self.free = True
                self.events.append({"at": len(gen), "refused": t, "error": self.m.get_error()})
                return scores
        self.fed = len(gen)
        t0 = time.time()
        bits = np.frombuffer(self.m.compute_bitmask(), dtype=np.uint8)
        allowed = np.unpackbits(bits, bitorder="little")[: scores.shape[-1]].astype(bool)
        if allowed.shape[0] < scores.shape[-1]:
            allowed = np.concatenate([allowed, np.zeros(scores.shape[-1] - allowed.shape[0], bool)])
        if self.m.is_accepting() or self.m.is_stopped():
            allowed[[s for s in self.c.stop_ids if s < allowed.shape[0]]] = True
        mask = torch.from_numpy(allowed).to(scores.device)
        self.c.stats["steps"] += 1
        top = int(scores[0].argmax())
        if not bool(mask[top]):
            probs = torch.softmax(scores[0].float(), -1)
            masked = scores[0].masked_fill(~mask, float("-inf"))
            best = int(masked.argmax())
            ev = {"at": len(gen), "want": top, "want_s": self.c.tok.decode([top]),
                  "want_p": round(float(probs[top]), 4), "got": best,
                  "got_s": self.c.tok.decode([best]), "got_p": round(float(probs[best]), 4),
                  "so_far": self.c.tok.decode(gen, skip_special_tokens=False).split(THINK_CLOSE)[-1]}
            if self.c.mode == "soft" and float(probs[best]) < self.c.tau:
                ev["released"] = True
                self.events.append(ev)
                self.c.stats["released"] += 1
                self.free = True
                self.c.stats["mask_ms"] += 1000 * (time.time() - t0)
                return scores
            self.events.append(ev)
            self.c.stats["overrides"] += 1
        self.c.stats["mask_ms"] += 1000 * (time.time() - t0)
        return scores.masked_fill(~mask.unsqueeze(0), float("-inf"))


def constrain_model(model, tok, vocab=None, stop_ids=(), handles=False, mode="hard", tau=0.05):
    """Wrap `model.generate` so every call adds the call-grammar processor, built from that
    call's prompt. Returns the Constrainer (`.last.events`, `.stats`)."""
    from transformers import LogitsProcessorList
    n_vocab = model.get_output_embeddings().weight.shape[0]
    c = Constrainer(tok, n_vocab, vocab, stop_ids, handles, mode, tau)
    orig = model.generate

    def generate(*args, **kw):
        ids = kw.get("input_ids", args[0] if args else None)
        procs = LogitsProcessorList(kw.pop("logits_processor", None) or [])
        procs.append(c.processor(ids[0].tolist()))
        return orig(*args, logits_processor=procs, **kw)

    model.generate = generate
    model._callgrammar = c
    return c


def add_args(ap):
    """the flags agent.py and the valscore shim share"""
    ap.add_argument("--constrain", nargs="?", const="hard", choices=["hard", "soft"], default=None,
                    help="decode the call under the call grammar (think block free); soft: release "
                         "when the grammar's best token has p < --constrain-tau")
    ap.add_argument("--constrain-handles", action="store_true",
                    help="--constrain: #n only for row numbers the conversation has shown")
    ap.add_argument("--constrain-tau", type=float, default=0.05)
    ap.add_argument("--constrain-vocab", help="callvocab.json (default: next to callgrammar.py)")


# -- the soundness gate ------------------------------------------------------

RETIRED = [("same?", r"^same\?"), ("clarify:", r"^clarify\s*:"), ("it", r"\bit\b"),
           ("that one", r"\bthat one\b"), ("the other one", r"\bthe other one\b"),
           ("the earlier one", r"\bthe earlier one\b"), ("the last thing I added", r"\bthe last thing I added\b"),
           ("the Nth one", r"\bthe [0-9]+(st|nd|rd|th) one\b")]


def outside_strings(call):
    return re.sub(r'"([^"\\]|\\.)*"', '""', call)


def prove(a):
    """Every gold call must be accepted, token by token; a call whose recorded observation
    is an `error:` (the generator's injected wrong-field steps) is expected to be rejected
    and is counted apart. `#n` is checked against the handles the call's own conversation
    showed (`obs`), when the record carries it."""
    import collections
    import llguidance
    import llguidance.hf
    from transformers import AutoTokenizer
    v = load_vocab(a.vocab)
    tok = AutoTokenizer.from_pretrained(a.tokenizer)
    eos = tok.convert_tokens_to_ids("<|im_end|>")
    lltok = llguidance.hf.from_tokenizer(tok, eos_token=eos)
    base = llguidance.LLMatcher(lltok, lark(v, None), log_level=0)
    assert not base.is_error(), base.get_error()
    tot, ok, cls = collections.Counter(), collections.Counter(), collections.defaultdict(collections.Counter)
    retired = collections.defaultdict(collections.Counter)
    examples = collections.defaultdict(list)
    for line in open(a.calls):
        rec = json.loads(line)
        src, call = rec["src"], rec["call"]
        if a.only and not src.startswith(tuple(a.only.split(","))):
            continue
        bare = outside_strings(call)
        for name, rx in RETIRED:
            if re.search(rx, bare if name not in ("same?", "clarify:") else call):
                retired[src][name] += 1
        m = base.deep_copy()
        ids = tok.encode("\n\n" + call, add_special_tokens=False) + [eos]
        g_ok = m.consume_tokens(ids) and (m.is_accepting() or m.is_stopped())
        h_ok = True
        if "obs" in rec:
            shown = set(shown_handles(rec["obs"]))
            used = {int(n) for n in re.findall(r"#(\d+)", bare)}
            h_ok = used <= shown
        nxt = rec.get("next", "")
        kind = ("error-step" if nxt.startswith("error:") else "real")
        tot[src] += 1
        if g_ok and h_ok:
            ok[src] += 1
            cls[src]["accepted"] += 1
        else:
            why = "grammar" if not g_ok else "unshown #n"
            cls[src]["%s/%s" % (kind, why)] += 1
            examples["%s %s/%s" % (src, kind, why)].append(call)
    res = {"total": dict(tot), "accepted": dict(ok), "classes": {k: dict(c) for k, c in cls.items()},
           "retired_forms": {k: dict(c) for k, c in retired.items()},
           "examples": {k: collections.Counter(c).most_common(60) for k, c in examples.items()}}
    for src in sorted(tot):
        print("%-16s %6d/%-6d accepted  %s" % (src, ok[src], tot[src],
                                              {k: n for k, n in cls[src].items() if k != "accepted"}))
    print("retired forms:", json.dumps(res["retired_forms"]))
    if a.out:
        json.dump(res, open(a.out, "w"), indent=1)
    for k in sorted(examples):
        if k.startswith("model"):
            continue
        for c, n in collections.Counter(examples[k]).most_common(a.show):
            print("  %s x%d: %s" % (k, n, c))


