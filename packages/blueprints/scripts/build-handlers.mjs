#!/usr/bin/env node
/**
 * Precompiles every first-party app handler to a self-contained ES module
 * beside its source (#922 B2).
 *
 * A bundled app is enrolled IN PLACE, so `apps/<id>/queries/<name>.ts` IS the
 * file the dispatcher hands the worker. Shipping a compiled `<name>.js` beside
 * it moves the esbuild transpile of the handler AND of its whole `_shared`
 * graph off every invocation and onto this build. `resolveHandlerFile`
 * (packages/server/src/engine/handlers/dispatcher.ts) prefers the `.js`, so
 * the TS-loader hook is left for code nobody precompiled — user apps and user
 * automations.
 *
 * Bundled, not transpiled per file: the emitted module has no relative
 * imports at all, which is what lets the worker reuse of #922 B3 re-import one
 * URL per run and get a whole fresh handler graph. Bare specifiers stay
 * external and resolve from node_modules exactly as they do today.
 *
 * Output is NOT tracked in git — it is generated by `bun run build` and
 * shipped by `files: ["apps"]`. `build-manifest.mjs` skips a `.js` that has a
 * `.ts` sibling, so the catalog keeps listing sources only.
 *
 * Run via `bun run build:handlers` (part of `bun run build`).
 */
import { promises as fs } from "node:fs";
import path from "node:path";

import * as esbuild from "esbuild";

const here = import.meta.dirname;
const PACKAGE_ROOT = path.resolve(here, "..");
const APPS_DIR = path.join(PACKAGE_ROOT, "apps");
const HANDLER_DIRS = ["actions", "queries"];

/** Test files and type-only siblings are not handlers. */
function isHandlerSource(name) {
  if (!name.endsWith(".ts") || name.endsWith(".d.ts")) return false;
  return !/\.test(?:-fixtures)?\.ts$/u.test(name);
}

async function entryPoints() {
  const apps = await fs.readdir(APPS_DIR, { withFileTypes: true });
  const out = [];
  await Promise.all(
    apps.map(async (app) => {
      if (!app.isDirectory() || app.name.startsWith("_")) return;
      await Promise.all(
        HANDLER_DIRS.map(async (dir) => {
          const full = path.join(APPS_DIR, app.name, dir);
          const names = await fs.readdir(full).catch(() => []);
          for (const name of names.filter((n) => isHandlerSource(n))) {
            out.push(path.join(full, name));
          }
        })
      );
    })
  );
  return out.toSorted();
}

const entries = await entryPoints();
if (entries.length === 0) {
  throw new Error("[build-handlers] no handler sources found under apps/");
}

const result = await esbuild.build({
  entryPoints: entries,
  outdir: APPS_DIR,
  outbase: APPS_DIR,
  bundle: true,
  format: "esm",
  platform: "node",
  // The floor `@centraid/blueprints#engines` declares.
  target: "node22",
  // Bare specifiers keep resolving from node_modules at run time; only the
  // relative graph is inlined.
  packages: "external",
  sourcemap: false,
  // A handler that fails to compile must fail the build, not ship stale.
  logLevel: "warning",
  metafile: true,
});

const written = Object.keys(result.metafile.outputs).length;
process.stdout.write(
  `[build-handlers] compiled ${written} handlers → ${path.relative(process.cwd(), APPS_DIR)}/<app>/{actions,queries}/*.js\n`
);
